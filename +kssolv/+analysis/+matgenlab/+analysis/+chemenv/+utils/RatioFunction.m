            value=kssolv.analysis.matgenlab.analysis.chemenv.utils. ...
                power2_decreasing_exp(input,"edges",[0,obj.options.max], ...
                "alpha",obj.options.alpha);
        end
        function value=smootherstep(obj,input)
            value=kssolv.analysis.matgenlab.analysis.chemenv.utils. ...
                smootherstep(input,"edges",[obj.options.lower,obj.options.upper]);
        end
