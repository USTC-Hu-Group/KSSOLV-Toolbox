classdef RatioFunction < kssolv.analysis.matgenlab.analysis.chemenv.utils.AbstractRatioFunction
    %RATIOFUNCTION General finite and infinite ratio functions.
    methods
        function obj=RatioFunction(varargin)
            obj@kssolv.analysis.matgenlab.analysis.chemenv.utils. ...
                AbstractRatioFunction(varargin{:});
        end
