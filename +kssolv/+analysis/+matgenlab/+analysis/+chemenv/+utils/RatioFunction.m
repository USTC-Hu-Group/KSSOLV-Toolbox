            value=kssolv.analysis.matgenlab.analysis.chemenv.utils. ...
                smoothstep(input,"edges",[obj.options.lower,obj.options.upper]);
        end
        function value=inverse_smootherstep(obj,input)
            value=kssolv.analysis.matgenlab.analysis.chemenv.utils. ...
                smootherstep(input,"edges",[obj.options.lower,obj.options.upper], ...
                "inverse",true);
        end
        function value=inverse_smoothstep(obj,input)
            value=kssolv.analysis.matgenlab.analysis.chemenv.utils. ...
                smoothstep(input,"edges",[obj.options.lower,obj.options.upper], ...
                "inverse",true);
        end
