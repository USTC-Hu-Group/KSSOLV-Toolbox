            value=kssolv.analysis.matgenlab.analysis.chemenv.utils. ...
                power2_inverse_power2_decreasing(input,"edges",[0,obj.options.max]);
        end
    end
    methods (Access=protected)
        function value=allowed_functions(~)
            value=struct(power2_decreasing_exp={{"max","alpha"}}, ...
                smoothstep={{"lower","upper"}}, ...
                smootherstep={{"lower","upper"}}, ...
                inverse_smoothstep={{"lower","upper"}}, ...
                inverse_smootherstep={{"lower","upper"}}, ...
                power2_inverse_decreasing={{"max"}}, ...
                power2_inverse_power2_decreasing={{"max"}});
        end
    end
end
