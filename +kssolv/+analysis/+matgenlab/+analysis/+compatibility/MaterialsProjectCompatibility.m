classdef MaterialsProjectCompatibility < kssolv.analysis.matgenlab.analysis.compatibility.CorrectionsList
    %MATERIALSPROJECTCOMPATIBILITY Frozen legacy MP compatibility scheme.
    properties
        compat_type (1,1) string = "Advanced"
        correct_peroxide (1,1) logical = true
        check_potcar_hash (1,1) logical = false
    end
    methods
        function obj=MaterialsProjectCompatibility(varargin)
            options=struct(compat_type="Advanced",correct_peroxide=true, ...
                check_potcar_hash=false);
            options=kssolv.analysis.matgenlab.analysis.compatibility. ...
                internal.options(options,varargin);
            file=kssolv.analysis.matgenlab.analysis.compatibility.internal. ...
                config_path("MPCompatibility.yaml");
            corrections={ ...
                kssolv.analysis.matgenlab.analysis.compatibility. ...
                    PotcarCorrection("MP","check_hash",options.check_potcar_hash), ...
                kssolv.analysis.matgenlab.analysis.compatibility.GasCorrection(file), ...
                kssolv.analysis.matgenlab.analysis.compatibility. ...
                    AnionCorrection(file,"correct_peroxide",options.correct_peroxide), ...
                kssolv.analysis.matgenlab.analysis.compatibility. ...
                    UCorrection(file,"MP",options.compat_type)};
            obj@kssolv.analysis.matgenlab.analysis.compatibility. ...
                CorrectionsList(corrections);
            obj.compat_type=string(options.compat_type);
            obj.correct_peroxide=options.correct_peroxide;
            obj.check_potcar_hash=options.check_potcar_hash;
        end
    end
end
