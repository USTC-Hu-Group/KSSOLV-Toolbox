classdef KPathSetyawanCurtarolo < ...
        kssolv.analysis.matgenlab.symmetry.kpath.KPathBase
    %KPATHSETYAWANCURTAROLO Setyawan-Curtarolo reciprocal paths.
    properties (SetAccess=private)
        conventional
        prim
        prim_rec
        name (1,1) string = ""
    end

    methods
        function obj=KPathSetyawanCurtarolo( ...
                structure,symprec,angleTolerance,atol)
            if nargin<2,symprec=0.01;end
            if nargin<3,angleTolerance=5;end
            if nargin<4,atol=1e-5;end
            obj@kssolv.analysis.matgenlab.symmetry.kpath.KPathBase( ...
                structure,symprec,angleTolerance,atol);
            analyzer=kssolv.analysis.matgenlab.symmetry.analyzer. ...
                SpacegroupAnalyzer(structure,symprec,angleTolerance);
            obj.prim=analyzer.get_primitive_standard_structure(false);
            obj.conventional= ...
                analyzer.get_conventional_standard_structure(false);
            obj.prim_rec=obj.prim.lattice.reciprocal_lattice;
            obj.rec_lattice=obj.prim_rec;
            latticeType=analyzer.get_lattice_type();
            symbol=analyzer.get_space_group_symbol();
            lengths=obj.conventional.lattice.lengths;
            if latticeType=="cubic"
                if contains(symbol,"P")
                    obj.kpath=obj.cubic();
                elseif contains(symbol,"F")
                    obj.kpath=obj.fcc();
                else
                    obj.kpath=obj.bcc();
                end
            elseif latticeType=="tetragonal"
                if contains(symbol,"P")
                    obj.kpath=obj.tet();
                elseif lengths(3)<lengths(1)
                    obj.kpath=obj.bctet1(lengths(3),lengths(1));
                else
                    obj.kpath=obj.bctet2(lengths(3),lengths(1));
                end
            elseif latticeType=="orthorhombic"
                a=lengths(1);b=lengths(2);c=lengths(3);
                if contains(symbol,"P")
                    obj.kpath=obj.orc();
                elseif contains(symbol,"F")
                    comparison=1/a^2-1/b^2-1/c^2;
                    if comparison>0
                        obj.kpath=obj.orcf1(a,b,c);
                    elseif comparison<0
                        obj.kpath=obj.orcf2(a,b,c);
                    else
                        obj.kpath=obj.orcf3(a,b,c);
                    end
                elseif contains(symbol,"I")
                    obj.kpath=obj.orci(a,b,c);
                else
                    obj.kpath=obj.orcc(a,b,c);
                end
            elseif latticeType=="hexagonal"
                obj.kpath=obj.hex();
            elseif latticeType=="rhombohedral"
                alpha=deg2rad(obj.prim.lattice.angles(1));
                if alpha<pi/2
                    obj.kpath=obj.rhl1(alpha);
                else
                    obj.kpath=obj.rhl2(alpha);
                end
            elseif latticeType=="monoclinic"
                a=lengths(1);b=lengths(2);c=lengths(3);
                alpha=deg2rad(obj.conventional.lattice.angles(1));
                if contains(symbol,"P")
                    obj.kpath=obj.mcl(b,c,alpha);
                else
                    gamma=obj.rec_lattice.angles(3);
                    comparison=b*cos(alpha)/c+ ...
                        b^2*sin(alpha)^2/a^2;
                    if gamma>90
                        obj.kpath=obj.mclc1(a,b,c,alpha);
                    elseif gamma==90
                        obj.kpath=obj.mclc2(a,b,c,alpha);
                    elseif comparison<1
                        obj.kpath=obj.mclc3(a,b,c,alpha);
                    elseif comparison>1
                        obj.kpath=obj.mclc5(a,b,c,alpha);
                    else
                        obj.kpath=obj.mclc4(a,b,c,alpha);
                    end
                end
            else
                reciprocalAngles=obj.rec_lattice.angles;
                if all(reciprocalAngles>90)
                    obj.kpath=obj.tria();
                else
                    obj.kpath=obj.trib();
                end
            end
        end

        function value=cubic(obj)
            obj.name="CUB";
            value=makePath({'\Gamma','X','R','M'}, ...
                [0,0,0;0,.5,0;.5,.5,.5;.5,.5,0], ...
                {{'\Gamma','X','M','\Gamma','R','X'},{'M','R'}});
        end

