        function value=rhl1(obj,alpha)
            obj.name="RHL1";eta=(1+4*cos(alpha))/(2+4*cos(alpha)); ...
                nu=3/4-eta/2;
            value=makePath( ...
                {'\Gamma','B','B_1','F','L','L_1','P','P_1','P_2','Q','X','Z'}, ...
                [0,0,0;eta,.5,1-eta;.5,1-eta,eta-1;.5,.5,0; ...
                .5,0,0;0,0,-.5;eta,nu,nu;1-nu,1-nu,1-eta; ...
                nu,nu,eta-1;1-nu,nu,0;nu,0,-nu;.5,.5,.5], ...
                {{'\Gamma','L','B_1'},{'B','Z','\Gamma','X'}, ...
                {'Q','F','P_1','Z'},{'L','P'}});
        end

        function value=rhl2(obj,alpha)
            obj.name="RHL2";eta=1/(2*tan(alpha/2)^2); ...
