        end

        function value=mcl(obj,b,c,beta)
            obj.name="MCL";eta=(1-b*cos(beta)/c)/(2*sin(beta)^2); ...
                nu=.5-eta*c*cos(beta)/b;
            value=makePath( ...
                {'\Gamma','A','C','D','D_1','E','H','H_1','H_2', ...
                'M','M_1','M_2','X','Y','Y_1','Z'}, ...
                [0,0,0;.5,.5,0;0,.5,.5;.5,0,.5;.5,0,-.5; ...
                .5,.5,.5;0,eta,1-nu;0,1-eta,nu;0,eta,-nu; ...
                .5,eta,1-nu;.5,1-eta,nu;.5,eta,-nu; ...
                0,.5,0;0,0,.5;0,0,-.5;.5,0,0], ...
                {{'\Gamma','Y','H','C','E','M_1','A','X','H_1'}, ...
                {'M','D','Z'},{'Y','D'}});
        end

        function value=mclc1(obj,a,b,c,alpha)
            value=mclc12(obj,a,b,c,alpha,1);
        end
        function value=mclc2(obj,a,b,c,alpha)
            value=mclc12(obj,a,b,c,alpha,2);
        end
        function value=mclc3(obj,a,b,c,alpha)
            value=mclc34(obj,a,b,c,alpha,3);
        end
        function value=mclc4(obj,a,b,c,alpha)
            value=mclc34(obj,a,b,c,alpha,4);
        end

        function value=mclc5(obj,a,b,c,alpha)
            obj.name="MCLC5";
            zeta=(b^2/a^2+(1-b*cos(alpha)/c)/sin(alpha)^2)/4;
            eta=.5+2*zeta*c*cos(alpha)/b;
            mu=eta/2+b^2/(4*a^2)-b*c*cos(alpha)/(2*a^2);
            nu=2*mu-zeta;rho=1-zeta*a^2/b^2;
            omega=(4*nu-1-b^2*sin(alpha)^2/a^2)*c/ ...
                (2*b*cos(alpha));
            delta=zeta*c*cos(alpha)/b+omega/2-.25;
            value=makePath( ...
                {'\Gamma','F','F_1','F_2','H','H_1','H_2', ...
                'I','I_1','L','M','N','N_1','X','Y','Y_1','Y_2','Y_3','Z'}, ...
                [0,0,0;nu,nu,omega;1-nu,1-nu,1-omega; ...
                nu,nu-1,omega;zeta,zeta,eta;1-zeta,-zeta,1-eta; ...
                -zeta,-zeta,1-eta;rho,1-rho,.5;1-rho,rho-1,.5; ...
                .5,.5,.5;.5,0,.5;.5,0,0;0,-.5,0;.5,-.5,0; ...
                mu,mu,delta;1-mu,-mu,-delta;-mu,-mu,-delta; ...
                mu,mu-1,delta;0,0,.5], ...
                {{'\Gamma','Y','F','L','I'}, ...
                {'I_1','Z','H','F_1'}, ...
                {'H_1','Y_1','X','\Gamma','N'},{'M','\Gamma'}});
        end

        function value=tria(obj)
            obj.name="TRI1a";
            value=triclinicPath(false);
        end
        function value=trib(obj)
            obj.name="TRI1b";
            value=triclinicPath(true);
        end
    end

    methods (Access=private)
        function value=mclc12(obj,a,b,c,alpha,variant)
            obj.name="MCLC"+variant;
            zeta=(2-b*cos(alpha)/c)/(4*sin(alpha)^2);
            eta=.5+2*zeta*c*cos(alpha)/b;
            psi=.75-a^2/(4*b^2*sin(alpha)^2);
            phi=psi+(.75-psi)*b*cos(alpha)/c;
            names={'\Gamma','N','N_1','F','F_1','F_2','I','I_1', ...
                'L','M','X','X_1','X_2','Y','Y_1','Z'};
            coords=[0,0,0;.5,0,0;0,-.5,0;1-zeta,1-zeta,1-eta; ...
                zeta,zeta,eta;-zeta,-zeta,1-eta;phi,1-phi,.5; ...
                1-phi,phi-1,.5;.5,.5,.5;.5,0,.5; ...
                1-psi,psi-1,0;psi,1-psi,0;psi-1,-psi,0; ...
                .5,.5,0;-.5,-.5,0;0,0,.5];
            if variant==1
                paths={{'\Gamma','Y','F','L','I'}, ...
                    {'I_1','Z','F_1'},{'Y','X_1'}, ...
                    {'X','\Gamma','N'},{'M','\Gamma'}};
            else
                names{end+1}='F_3';
                coords(end+1,:)=[1-zeta,-zeta,1-eta];
                paths={{'\Gamma','Y','F','L','I'}, ...
                    {'I_1','Z','F_1'},{'N','\Gamma','M'}};
            end
            value=makePath(names,coords,paths);
        end

        function value=mclc34(obj,a,b,c,alpha,variant)
            obj.name="MCLC"+variant;
            mu=(1+b^2/a^2)/4;
            delta=b*c*cos(alpha)/(2*a^2);
            zeta=mu-.25+(1-b*cos(alpha)/c)/(4*sin(alpha)^2);
            eta=.5+2*zeta*c*cos(alpha)/b;
            phi=1+zeta-2*mu;psi=eta-2*delta;
            names={'\Gamma','F','F_1','F_2','H','H_1','H_2', ...
                'I','M','N','N_1','X','Y','Y_1','Y_2','Y_3','Z'};
            coords=[0,0,0;1-phi,1-phi,1-psi;phi,phi-1,psi; ...
                1-phi,-phi,1-psi;zeta,zeta,eta; ...
                1-zeta,-zeta,1-eta;-zeta,-zeta,1-eta; ...
                .5,-.5,.5;.5,0,.5;.5,0,0;0,-.5,0; ...
                .5,-.5,0;mu,mu,delta;1-mu,-mu,-delta; ...
                -mu,-mu,-delta;mu,mu-1,delta;0,0,.5];
            if variant==3
                paths={{'\Gamma','Y','F','H','Z','I','F_1'}, ...
                    {'H_1','Y_1','X','\Gamma','N'},{'M','\Gamma'}};
            else
                paths={{'\Gamma','Y','F','H','Z','I'}, ...
                    {'H_1','Y_1','X','\Gamma','N'},{'M','\Gamma'}};
            end
            value=makePath(names,coords,paths);
        end
    end
end

function value=makePath(names,coordinates,paths)
points=containers.Map("KeyType","char","ValueType","any");
for index=1:numel(names),points(names{index})=coordinates(index,:);end
value=struct("kpoints",points,"path",{paths});
end

function value=triclinicPath(second)
if ~second
    coordinates=[0,0,0;.5,.5,0;0,.5,.5;.5,0,.5; ...
        .5,.5,.5;.5,0,0;0,.5,0;0,0,.5];
else
    coordinates=[0,0,0;.5,-.5,0;0,0,.5;-.5,-.5,.5; ...
        0,-.5,.5;0,-.5,0;.5,0,0;-.5,0,.5];
end
value=makePath({'\Gamma','L','M','N','R','X','Y','Z'}, ...
    coordinates,{{'X','\Gamma','Y'},{'L','\Gamma','Z'}, ...
    {'N','\Gamma','M'},{'R','\Gamma'}});
end
