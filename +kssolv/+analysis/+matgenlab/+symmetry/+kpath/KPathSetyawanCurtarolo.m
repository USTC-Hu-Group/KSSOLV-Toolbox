        function value=orcf1(obj,a,b,c)
            obj.name="ORCF1";zeta=(1+a^2/b^2-a^2/c^2)/4; ...
                eta=(1+a^2/b^2+a^2/c^2)/4;
            value=makePath( ...
                {'\Gamma','A','A_1','L','T','X','X_1','Y','Z'}, ...
                [0,0,0;.5,.5+zeta,zeta;.5,.5-zeta,1-zeta; ...
                .5,.5,.5;1,.5,.5;0,eta,eta;1,1-eta,1-eta; ...
                .5,0,.5;.5,.5,0], ...
                {{'\Gamma','Y','T','Z','\Gamma','X','A_1','Y'}, ...
                {'T','X_1'},{'X','A','Z'},{'L','\Gamma'}});
        end

        function value=orcf2(obj,a,b,c)
            obj.name="ORCF2";phi=(1+c^2/b^2-c^2/a^2)/4; ...
                eta=(1+a^2/b^2-a^2/c^2)/4; ...
                delta=(1+b^2/a^2-b^2/c^2)/4;
            value=makePath( ...
                {'\Gamma','C','C_1','D','D_1','L','H','H_1','X','Y','Z'}, ...
                [0,0,0;.5,.5-eta,1-eta;.5,.5+eta,eta; ...
                .5-delta,.5,1-delta;.5+delta,.5,delta;.5,.5,.5; ...
                1-phi,.5-phi,.5;phi,.5+phi,.5;0,.5,.5; ...
                .5,0,.5;.5,.5,0], ...
                {{'\Gamma','Y','C','D','X','\Gamma','Z','D_1','H','C'}, ...
                {'C_1','Z'},{'X','H_1'},{'H','Y'},{'L','\Gamma'}});
        end

        function value=orcf3(obj,a,b,c)
            obj.name="ORCF3";zeta=(1+a^2/b^2-a^2/c^2)/4; ...
                eta=(1+a^2/b^2+a^2/c^2)/4;
            value=makePath( ...
                {'\Gamma','A','A_1','L','T','X','X_1','Y','Z'}, ...
                [0,0,0;.5,.5+zeta,zeta;.5,.5-zeta,1-zeta; ...
