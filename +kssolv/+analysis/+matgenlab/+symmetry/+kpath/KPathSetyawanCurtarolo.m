        function value=orci(obj,a,b,c)
            obj.name="ORCI";zeta=(1+a^2/c^2)/4; ...
                eta=(1+b^2/c^2)/4;delta=(b^2-a^2)/(4*c^2); ...
                mu=(a^2+b^2)/(4*c^2);
            value=makePath( ...
                {'\Gamma','L','L_1','L_2','R','S','T','W', ...
                'X','X_1','Y','Y_1','Z'}, ...
                [0,0,0;-mu,mu,.5-delta;mu,-mu,.5+delta; ...
                .5-delta,.5+delta,-mu;0,.5,0;.5,0,0;0,0,.5; ...
                .25,.25,.25;-zeta,zeta,zeta;zeta,1-zeta,-zeta; ...
                eta,-eta,eta;1-eta,eta,-eta;.5,.5,-.5], ...
                {{'\Gamma','X','L','T','W','R','X_1','Z', ...
                '\Gamma','Y','S','W'},{'L_1','Y'},{'Y_1','Z'}});
        end

        function value=orcc(obj,a,b,c) %#ok<INUSD>
            obj.name="ORCC";zeta=(1+a^2/b^2)/4;
            value=makePath( ...
                {'\Gamma','A','A_1','R','S','T','X','X_1','Y','Z'}, ...
                [0,0,0;zeta,zeta,.5;-zeta,1-zeta,.5;0,.5,.5; ...
                0,.5,0;-.5,.5,.5;zeta,zeta,0;-zeta,1-zeta,0; ...
