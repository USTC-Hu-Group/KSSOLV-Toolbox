classdef EosTest < matlab.unittest.TestCase
    methods (Test)
        function analyticModelsMatchFrozenReference(testCase)
            testCase.assumeTrue( ...
                kssolv.analysis.matgenlab.test.support. ...
                PymatgenOracle.isAvailable());
            volumes = [16.69182365,17.25441763,17.82951915, ...
                18.41725977,19.01777055,19.63120886,20.25769112, ...
                20.89736201,21.55035204,22.21681221,22.89687316, ...
                23.59066888,24.29834347,25.02003097,25.75586879, ...
                26.5059864,27.27053682,28.04965916,28.84346369, ...
                29.65211363,30.47573817];
            energies = [-1.269884575,-1.339411225,-1.39879471, ...
                -1.44884184,-1.49033594,-1.52397006,-1.550269435, ...
                -1.569937375,-1.583470925,-1.591436505,-1.594347355, ...
                -1.592563495,-1.58647189,-1.576420935,-1.56284009, ...
                -1.54609291,-1.5264432,-1.504198485,-1.4796246, ...
                -1.45297499,-1.424480995];
            for name = ["murnaghan","birch","birch_murnaghan", ...
                    "pourier_tarantola","vinet"]
                request = struct( ...
                    "module","pymatgen.analysis.eos", ...
                    "symbol","EOS", ...
                    "construct",struct("kwargs",struct("eos_name",name)), ...
                    "operations",{{struct("kind","call","name","fit", ...
                    "args",{{volumes,energies}})}});
                % Returning the model itself is not normalized, so query it
                % in a second direct model request via its frozen class.
                className = eosClass(name);
                request.symbol = className;
                request.construct = struct("args",{{volumes,energies}});
                request.operations = {struct("kind","call","name","fit"), ...
                    struct("kind","get","name","results")};
                reference = ...
                    kssolv.analysis.matgenlab.test.support.PymatgenOracle. ...
                    execute(request);
                actual = kssolv.analysis.matgenlab.analysis.EOS(name). ...
                    fit(volumes,energies);
                expected = reference.results{2};
                testCase.verifyEqual(actual.e0,expected.e0,AbsTol=2e-6);
                testCase.verifyEqual(actual.v0,expected.v0,AbsTol=2e-5);
                testCase.verifyEqual(actual.b0,expected.b0,AbsTol=2e-6);
                testCase.verifyEqual(actual.b1,expected.b1,AbsTol=2e-5);
            end
        end

        function polynomialModels(testCase)
            volumes = 35:1:47;
            energies = -10 + 0.02*(volumes-41).^2 + ...
                0.0002*(volumes-41).^3;
            delta = kssolv.analysis.matgenlab.analysis. ...
                DeltaFactor(volumes,energies).fit();
            numerical = kssolv.analysis.matgenlab.analysis. ...
                NumericalEOS(volumes,energies).fit();
            testCase.verifyEqual(delta.v0,41,AbsTol=0.2);
            testCase.verifyEqual(numerical.v0,41,AbsTol=0.2);
            testCase.verifyEqual(numerical.func(numerical.v0), ...
                numerical.e0,AbsTol=1e-8);
        end

        function facadePropertiesAndPlotting(testCase)
            volumes=16:2:32;
            energies=-5+.01*(volumes-24).^2;
            model=kssolv.analysis.matgenlab.analysis. ...
                EOS("murnaghan").fit(volumes,energies);
            testCase.verifyEqual(model.results,struct( ...
                "e0",model.e0,"b0",model.b0, ...
                "b1",model.b1,"v0",model.v0));
            testCase.verifyEqual(double(model.b0_GPa), ...
                model.b0*160.2176634,RelTol=1e-9);
            testCase.verifyEqual(model(model.v0),model.e0,AbsTol=1e-8);
            axesHandle=model.plot(6,4,[],150);
            cleanup=onCleanup(@()close(axesHandle.Parent));
            testCase.verifyEqual(axesHandle.Parent.Position(3:4),[6,4]);
            testCase.verifyEqual(numel(axesHandle.Children),2);
            figureHandle=model.plot_ax(axesHandle,14);
            testCase.verifyTrue(figureHandle==axesHandle.Parent);
            testCase.verifyEqual(axesHandle.FontSize,14);
            clear cleanup
            testCase.verifyError(@()kssolv.analysis.matgenlab.analysis. ...
                EOS("unknown"),"KSSOLV:Matgenlab:EOS:FitError");
            polynomial=kssolv.analysis.matgenlab.analysis. ...
                PolynomialEOS(volumes,energies);
            testCase.verifyError(@()polynomial.fit(), ...
                "KSSOLV:Matgenlab:EOS:MissingPolynomialOrder");
        end
    end
end

function value = eosClass(name)
switch name
    case "murnaghan", value = "Murnaghan";
    case "birch", value = "Birch";
    case "birch_murnaghan", value = "BirchMurnaghan";
    case "pourier_tarantola", value = "PourierTarantola";
    otherwise, value = "Vinet";
end
end
