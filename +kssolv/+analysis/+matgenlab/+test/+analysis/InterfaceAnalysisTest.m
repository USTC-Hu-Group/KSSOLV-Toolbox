classdef InterfaceAnalysisTest < matlab.unittest.TestCase
    methods (Test)
        function officialSurfaceVectors(testCase)
            analyzer = ...
                kssolv.analysis.matgenlab.analysis.interfaces. ...
                SubstrateAnalyzer();
            sets = analyzer.generate_surface_vectors( ...
                conventionalVO2(), conventionalTiO2(), ...
                [1,0,0], [1,1,1]);
            testCase.verifySize(sets, [1,4]);
            film = sets{1,1};
            substrate = sets{1,2};
            testCase.verifyEqual(vecnorm(film,2,2), ...
                [3.03542922;4.51502263], AbsTol=1e-6);
            testCase.verifyEqual(vecnorm(substrate,2,2), ...
                [7.613414525142487;12.870736246973966], ...
                AbsTol=1e-6);
            testCase.verifyEqual(norm(cross(film(1,:),film(2,:))), ...
                13.705031620063249, AbsTol=1e-6);
            testCase.verifyEqual( ...
                norm(cross(substrate(1,:),substrate(2,:))), ...
                97.52451926178126, AbsTol=1e-6);
            testCase.verifyEqual(dot(film(1,:),film(2,:)), ...
                0, AbsTol=1e-6);
            testCase.verifyEqual( ...
                dot(substrate(1,:),substrate(2,:)), ...
                9.542394617977376, AbsTol=1e-6);
        end

        function officialSubstrateMatchCount(testCase)
            analyzer = ...
                kssolv.analysis.matgenlab.analysis.interfaces. ...
                SubstrateAnalyzer();
            matches = analyzer.calculate( ...
                conventionalVO2(), conventionalTiO2());
            testCase.verifyNumElements(matches, 296);
            testCase.verifyClass(matches{1}, ...
                "kssolv.analysis.matgenlab.analysis.interfaces.SubstrateMatch");
            testCase.verifyTrue(isscalar(matches{1}.match_area));
        end

        function officialTerminationSearch(testCase)
            substrate = kssolv.analysis.matgenlab.core.Structure( ...
                kssolv.analysis.matgenlab.core.Lattice.cubic(5.431), ...
                {"Si","Si"}, [0,0,0;.25,.25,.25]);
            film = kssolv.analysis.matgenlab.core.Structure( ...
                kssolv.analysis.matgenlab.core.Lattice.cubic(5.658), ...
                {"Ge","Ge"}, [0,0,0;.25,.25,.25]);
            analyzer = ...
                kssolv.analysis.matgenlab.analysis.interfaces. ...
                SubstrateAnalyzer();
            matches = analyzer.calculate(film, substrate);
            testCase.verifyNumElements(matches, 39);
            testCase.verifyEqual(matches{1}.film_miller, [0,0,1]);
            builder = ...
                kssolv.analysis.matgenlab.analysis.interfaces. ...
                CoherentInterfaceBuilder(substrate,film, ...
                matches{1}.film_miller,matches{1}.substrate_miller, ...
                analyzer,1e-4,true,false);
            expected = { ...
                '1_Ge_P4/mmm_1','1_Si_P4/mmm_1'; ...
                '1_Ge_P4/mmm_1','2_Si_P4/mmm_1'; ...
                '2_Ge_P4/mmm_1','1_Si_P4/mmm_1'; ...
                '2_Ge_P4/mmm_1','2_Si_P4/mmm_1'};
            testCase.verifyEqual(builder.terminations,expected);
            interfaces = builder.get_interfaces(builder.terminations(1,:));
            testCase.verifyNumElements(interfaces,numel(builder.zsl_matches));
            testCase.verifyClass(interfaces{1}, ...
                "kssolv.analysis.matgenlab.core.Interface");

            builder = ...
                kssolv.analysis.matgenlab.analysis.interfaces. ...
                CoherentInterfaceBuilder(substrate,film, ...
                matches{1}.film_miller,matches{1}.substrate_miller, ...
                analyzer,[2,.1],true,false);
            testCase.verifyEqual(builder.terminations,{ ...
                '1_Ge_C2/m_2','1_Si_P4/mmm_1'; ...
                '1_Ge_C2/m_2','2_Si_P4/mmm_1'});
        end
    end
end

