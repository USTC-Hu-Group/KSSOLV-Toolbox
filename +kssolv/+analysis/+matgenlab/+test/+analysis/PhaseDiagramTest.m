classdef PhaseDiagramTest < matlab.unittest.TestCase
    methods (Test)
        function officialFixtureHullAndDecomposition(testCase)
            path=phaseFixture("pd_entries_test.csv");
            testCase.assumeTrue(isfile(path),"Official phase-diagram fixture unavailable.");
            entries=kssolv.analysis.matgenlab.core.EntrySet.from_csv(path);
            pd=kssolv.analysis.matgenlab.analysis.PhaseDiagram(entries);
            testCase.verifyEqual(length(entries),490);
            testCase.verifyEqual(numel(pd.qhull_entries),143);
            testCase.verifyEqual(numel(pd.facets),12);
            testCase.verifyEqual(numel(pd.stable_entries),11);
            decomposition=pd.get_decomposition( ...
                kssolv.analysis.matgenlab.core.Composition("Li3Fe7O11"));
            formulas=cellfun(@(x)x.formula,decomposition(:,1));
            expected=containers.Map(["Fe2 O2","Li1 Fe1 O2","Fe6 O8"], ...
                [2/21,4/7,1/3]);
            for ii=1:numel(formulas)
                testCase.verifyEqual(decomposition{ii,2},expected(formulas(ii)),AbsTol=1e-12);
            end
            target=pd.stable_entries{find(cellfun(@(x) ...
                x.reduced_formula=="Li5FeO4",pd.stable_entries),1)};
            testCase.verifyEqual(pd.get_form_energy(target), ...
                -164.8117344866667,AbsTol=1e-8);
        end

        function grandCompoundAndMSON(testCase)
            path=phaseFixture("pd_entries_test.csv");
            testCase.assumeTrue(isfile(path));
            entries=kssolv.analysis.matgenlab.core.EntrySet.from_csv(path);
            grand=kssolv.analysis.matgenlab.analysis. ...
                GrandPotentialPhaseDiagram(entries,{"O",-5});
            testCase.verifyEqual(numel(grand.stable_entries),5);
            formulas=sort(cellfun(@(x)x.original_entry.reduced_formula,grand.stable_entries));
            testCase.verifyEqual(formulas,sort( ...
                ["Li5FeO4","Li2FeO3","LiFeO2","Fe2O3","Li2O2"]));
            compound=kssolv.analysis.matgenlab.analysis.CompoundPhaseDiagram( ...
                entries,{kssolv.analysis.matgenlab.core.Composition("Li2O"), ...
                kssolv.analysis.matgenlab.core.Composition("Fe2O3")});
            testCase.verifyEqual(numel(compound.stable_entries),4);
            restored=kssolv.analysis.matgenlab.analysis. ...
                CompoundPhaseDiagram.from_dict(compound.as_dict());
            testCase.verifyEqual(sort(cellfun(@(x)x.name,restored.stable_entries)), ...
                sort(cellfun(@(x)x.name,compound.stable_entries)));
        end

        function patchedAndReactionDiagram(testCase)
            path=phaseFixture("reaction_entries_test.csv");
            testCase.assumeTrue(isfile(path));
            entries=kssolv.analysis.matgenlab.core.EntrySet.from_csv(path);
            entries.add(kssolv.analysis.matgenlab.analysis.PDEntry("He",-1.23));
            patched=kssolv.analysis.matgenlab.analysis.PatchedPhaseDiagram(entries);
            full=kssolv.analysis.matgenlab.analysis.PhaseDiagram(entries);
            testCase.verifyEqual(length(patched),4);
            testCase.verifyEqual(numel(patched.stable_entries),numel(full.stable_entries));
            restored=kssolv.analysis.matgenlab.analysis. ...
                PatchedPhaseDiagram.from_dict(patched.as_dict());
            testCase.verifyEqual(length(restored),4);

            raw=entries.entries(~cellfun(@(x)x.reduced_formula=="He",entries.entries));
            first=raw{find(cellfun(@(x)x.reduced_formula=="VPO5",raw),1)};
            second=raw{find(cellfun(@(x)x.reduced_formula=="H4(CO)3",raw),1)};
            diagram=kssolv.analysis.matgenlab.analysis.ReactionDiagram( ...
                first,second,raw(3:end));
            testCase.verifyEqual(numel(diagram.rxn_entries),9);
            testCase.verifyClass(diagram.get_compound_pd(), ...
                "kssolv.analysis.matgenlab.analysis.CompoundPhaseDiagram");
        end

