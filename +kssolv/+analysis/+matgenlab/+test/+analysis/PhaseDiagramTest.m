        end

        function interfacialAndGrandInterfacial(testCase)
            import kssolv.analysis.matgenlab.analysis.*
            import kssolv.analysis.matgenlab.core.*
            entries={ComputedEntry("Li",0),ComputedEntry("Mn",0), ...
                ComputedEntry("O2",0),ComputedEntry("MnO2",-10), ...
                ComputedEntry("Mn2O4",-60),ComputedEntry("MnO3",20), ...
                ComputedEntry("Li2O",-10),ComputedEntry("Li2O2",-8), ...
                ComputedEntry("LiMnO2",-30)};
            pd=PhaseDiagram(entries);
            interfacial=InterfacialReactivity(Composition("O2"), ...
                Composition("Mn"),pd,"norm",false,"use_hull_energy",false);
            kinks=interfacial.get_kinks();
            testCase.verifyEqual([kinks.ratio],[0,.5,1],AbsTol=1e-8);
            testCase.verifyEqual([kinks.energy],[0,-15,0],AbsTol=1e-8);
            testCase.verifyEqual(interfacial.minimum,[.5,-15],AbsTol=1e-8);
            testCase.verifySize(interfacial.labels,[3,2]);
            testCase.verifyNotEmpty(interfacial.products);
            testCase.verifyEqual(height(interfacial.get_dataframe()),3);
            axesHandle=interfacial.plot();
            testCase.verifyTrue(isgraphics(axesHandle,"axes"));
            close(axesHandle.Parent);
            restored=InterfacialReactivity.from_dict(interfacial.as_dict());
            testCase.verifyEqual(restored.minimum,interfacial.minimum,AbsTol=1e-8);
            grand=GrandPotentialPhaseDiagram(entries,{"Li",-3});
            grandInterface=GrandPotentialInterfacialReactivity( ...
                Composition("Li2O"),Composition("Mn"),grand,pd, ...
                "norm",false,"include_no_mixing_energy",true, ...
                "use_hull_energy",false);
            testCase.verifyEqual(grandInterface.get_energy(2/3), ...
                -22/3,AbsTol=1e-8);
            testCase.verifyEqual(grandInterface.get_grand_potential( ...
                Composition("LiMnO2")),-27,AbsTol=1e-8);
            testCase.verifySize( ...
                grandInterface.get_no_mixing_energy(),[2,2]);
            restoredGrand=GrandPotentialInterfacialReactivity. ...
                from_dict(grandInterface.as_dict());
            testCase.verifyEqual(restoredGrand.get_energy(2/3), ...
                grandInterface.get_energy(2/3),AbsTol=1e-8);
            testCase.verifyEqual(InterfacialReactivity. ...
                get_chempot_correction("O",1000,1e-25),-3.8,AbsTol=.01);
        end

        function frozenPhaseDiagramOracle(testCase)
            testCase.assumeTrue(kssolv.analysis.matgenlab.test.support. ...
                PymatgenOracle.isAvailable());
            entry=@(formula,energy)struct(x_module="pymatgen.analysis.phase_diagram", ...
                x_class="PDEntry",composition=formula,energy=energy);
            composition=struct("x_module","pymatgen.core.composition", ...
                "x_class","Composition","Li",1,"O",1);
            request=struct(module="pymatgen.analysis.phase_diagram", ...
                symbol="PhaseDiagram",construct=struct(args={{ ...
                {entry("Li",0),entry("O2",0),entry("Li2O",-5),entry("LiO2",-4)}}}), ...
                operations={{struct(kind="call",name="get_hull_energy_per_atom", ...
                args={{composition}}),struct(kind="call", ...
                name="get_transition_chempots",args={{struct( ...
                "x_module","pymatgen.core.periodic_table", ...
                "x_class","Element","element","Li")}})}});
            reference=kssolv.analysis.matgenlab.test.support. ...
                PymatgenOracle.execute(request);
            entries={kssolv.analysis.matgenlab.analysis.PDEntry("Li",0), ...
                kssolv.analysis.matgenlab.analysis.PDEntry("O2",0), ...
                kssolv.analysis.matgenlab.analysis.PDEntry("Li2O",-5), ...
                kssolv.analysis.matgenlab.analysis.PDEntry("LiO2",-4)};
            pd=kssolv.analysis.matgenlab.analysis.PhaseDiagram(entries);
            testCase.verifyEqual(pd.get_hull_energy_per_atom( ...
                kssolv.analysis.matgenlab.core.Composition("LiO")), ...
                reference.results{1},AbsTol=1e-12);
            testCase.verifyEqual(pd.get_transition_chempots("Li"), ...
                reshape(reference.results{2},1,[]),AbsTol=1e-12);
        end

        function frozenChemicalPotentialOracle(testCase)
            testCase.assumeTrue(kssolv.analysis.matgenlab.test.support. ...
                PymatgenOracle.isAvailable());
            import kssolv.analysis.matgenlab.analysis.*
            entries={PDEntry("Li",0),PDEntry("O2",0), ...
                PDEntry("Li2O",-5),PDEntry("LiO2",-4)};
            encoded=cellfun(@(entry)entry.as_dict(),entries, ...
                "UniformOutput",false);
            request=struct(module="pymatgen.analysis.chempot_diagram", ...
                symbol="ChemicalPotentialDiagram",construct=struct( ...
                args={{encoded}},kwargs=struct(default_min_limit=-10, ...
                formal_chempots=false)),operations={{struct( ...
                kind="get",name="hyperplanes")}});
            reference=kssolv.analysis.matgenlab.test.support. ...
                PymatgenOracle.execute(request);
            diagram=ChemicalPotentialDiagram(entries, ...
                "default_min_limit",-10,"formal_chempots",false);
            testCase.verifyEqual(sortrows(diagram.hyperplanes), ...
                sortrows(squeeze(reference.results)),AbsTol=1e-12);
        end

        function frozenInterfacialOracle(testCase)
            testCase.assumeTrue(interfaceOracleAvailable());
            import kssolv.analysis.matgenlab.analysis.*
            import kssolv.analysis.matgenlab.core.*
            entries={ComputedEntry("Li",0),ComputedEntry("Mn",0), ...
                ComputedEntry("O2",0),ComputedEntry("MnO2",-10), ...
                ComputedEntry("Mn2O4",-60),ComputedEntry("MnO3",20), ...
                ComputedEntry("Li2O",-10),ComputedEntry("Li2O2",-8), ...
                ComputedEntry("LiMnO2",-30)};
            pd=PhaseDiagram(entries);
            interfacial=InterfacialReactivity(Composition("O2"), ...
                Composition("Mn"),pd,"norm",false,"use_hull_energy",false);
            encoded=pd.as_dict();
            encoded=rmfield(encoded,"computed_data");
            c1=struct(x_module="pymatgen.core.composition", ...
                x_class="Composition",O=2);
            c2=struct(x_module="pymatgen.core.composition", ...
                x_class="Composition",Mn=1);
            request=struct(module="pymatgen.analysis.interface_reactions", ...
                symbol="InterfacialReactivity",construct=struct( ...
                args={{c1,c2,encoded}},kwargs=struct(norm=false, ...
                use_hull_energy=false)),operations={{ ...
                struct(kind="get",name="minimum"), ...
                struct(kind="call",name="get_critical_original_kink_ratio")}});
            reference=kssolv.analysis.matgenlab.test.support. ...
                PymatgenOracle.execute(request);
            testCase.verifyEqual(interfacial.minimum, ...
                reshape(reference.results{1},1,[]),AbsTol=1e-12);
            testCase.verifyEqual( ...
                interfacial.get_critical_original_kink_ratio(), ...
                reshape(reference.results{2},1,[]),AbsTol=1e-12);
        end
    end
end

function path=phaseFixture(name)
roots=[string(getenv("MATGENLAB_PYMATGEN_CORE")), ...
    "/tmp/matgenlab-pymatgen-core-v2026.7.24"];
path="";
for root=roots
    if strlength(root)==0,continue,end
    candidate=fullfile(root,"test-files","analysis",name);
    if isfile(candidate),path=candidate;return,end
end
end

function available=interfaceOracleAvailable()
python=kssolv.analysis.matgenlab.test.support.PymatgenOracle.python();
command=sprintf('"%s" -c "import pymatgen.analysis.interface_reactions"', ...
    python);
available=system(command)==0;
end
