        function slabThermodynamicsAndPlotter(testCase)
            import kssolv.analysis.matgenlab.analysis.SlabEntry
            import kssolv.analysis.matgenlab.core.ComputedStructureEntry
            import kssolv.analysis.matgenlab.core.Lattice
            import kssolv.analysis.matgenlab.core.Structure
            bulkStructure=Structure(Lattice.cubic(4),{"Pt"},[0,0,0]);
            bulk=ComputedStructureEntry(bulkStructure,-5);
            slabLattice=Lattice([4,0,0;0,4,0;0,0,20]);
            cleanStructure=Structure(slabLattice,{"Pt","Pt"}, ...
                [0,0,0.4;0.5,0.5,0.6]);
            clean=SlabEntry(cleanStructure,-9,[1,0,0]);
            oxygen=ComputedStructureEntry( ...
                Structure(Lattice.cubic(10),{"O"},[0,0,0]),-4);
            adsStructure=Structure(slabLattice,{"Pt","Pt","O"}, ...
                [0,0,0.4;0.5,0.5,0.6;0.25,0.25,0.8]);
            ads=SlabEntry(adsStructure,-13.5,[1,0,0], ...
                "adsorbates",{oxygen},"clean_entry",clean);
            expression=ads.surface_energy(bulk);
            testCase.verifyEqual(expression.coefficients.delu_O, ...
                -1/(2*ads.surface_area),AbsTol=1e-14);
            testCase.verifyEqual(ads.Nads_in_slab,1);
            testCase.verifyEqual(ads.Nsurfs_ads_in_slab,1);
            testCase.verifyEqual(ads.get_monolayer,1,AbsTol=1e-14);
            testCase.verifyEqual(ads.gibbs_binding_energy(),-0.5, ...
                AbsTol=1e-14);
            plotter=kssolv.analysis.matgenlab.analysis. ...
                SurfaceEnergyPlotter({clean,ads},bulk);
            [entry,~]=plotter.get_stable_entry_at_u([1,0,0], ...
                "delu_dict",struct("delu_O",0));
            testCase.verifyEqual(entry,ads);
            solution=plotter.get_surface_equilibrium({clean,ads});
            testCase.verifyTrue(isfield(solution,"delu_O"));
            testCase.verifyTrue(isfield(solution,"gamma"));
        end

        function wulffOracleAndScaling(testCase)
            lattice=kssolv.analysis.matgenlab.core.Lattice.cubic(4);
            shape=kssolv.analysis.matgenlab.analysis.WulffShape(lattice, ...
                [1,0,0;1,1,0;1,1,1],[0.8,1,0.9]);
            testCase.verifyEqual(shape.volume,3.268210038023174, ...
                AbsTol=2e-12);
            testCase.verifyEqual(shape.effective_radius, ...
                0.9206059626071695,AbsTol=2e-12);
            testCase.verifyEqual(shape.area_fractions, ...
                [0.556999560186461,0.079273753361202, ...
                0.363726686452337],AbsTol=2e-12);
            testCase.verifyEqual(shape.weighted_surface_energy, ...
                0.8522274193174741,AbsTol=2e-12);
            stability=kssolv.analysis.matgenlab.analysis. ...
                NanoscaleStability({});
            scaled=stability.scaled_wulff(shape,10);
            testCase.verifyEqual(scaled.effective_radius,10,AbsTol=2e-11);
        end

        function workFunctionOracle(testCase)
            lattice=kssolv.analysis.matgenlab.core.Lattice( ...
                [4,0,0;0,4,0;0,0,20]);
            structure=kssolv.analysis.matgenlab.core.Structure(lattice, ...
                {"Pt","Pt","Pt"},[0,0,0.4;0.5,0.5,0.5;0,0,0.6]);
            potential=[10,10,8,4,0,0,0,4,8,10,10];
            analyzer=kssolv.analysis.matgenlab.analysis. ...
                WorkFunctionAnalyzer(structure,potential,3.2,-0.25,3.5);
            testCase.verifyEqual(analyzer.slab_regions,[0.15,0.35], ...
                AbsTol=3e-15);
            testCase.verifyEqual(analyzer.ave_bulk_p,0,AbsTol=1e-15);
            testCase.verifyEqual(analyzer.vacuum_locpot,10);
            testCase.verifyEqual(analyzer.work_function,6.8,AbsTol=1e-15);
            testCase.verifyEqual(analyzer.ave_locpot,5);
            testCase.verifyTrue(analyzer.is_converged());
        end
