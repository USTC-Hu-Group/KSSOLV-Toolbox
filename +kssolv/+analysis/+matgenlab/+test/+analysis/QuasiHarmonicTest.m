classdef QuasiHarmonicTest < matlab.unittest.TestCase
    methods (Test)
        function officialBoronNitrideOracle(testCase)
            structure=kssolv.analysis.matgenlab.core.Structure( ...
                kssolv.analysis.matgenlab.core.Lattice([ ...
                2.21964022,0,1.28151046;.73987974,2.09269747, ...
                1.28151046;0,0,2.56301993]), ...
                {'B','N'},[0,0,0;.25,.25,.25]);
            energies=[-15.76315281,-16.11541813,-16.41784171, ...
                -16.47471523,-16.63624155,-16.6741551,-16.78661144, ...
                -16.88768073,-16.92450672,-17.04863261,-17.06126553, ...
                -17.15786866,-17.19784976,-17.25078749,-17.30017149, ...
                -17.32578594,-17.3708922,-17.38125127,-17.41231934, ...
                -17.41534352,-17.42636644];
            volumes=[8.678977833994137,8.971505437031707, ...
                9.27052889309282,15.845976281427582,15.417733609491387, ...
                9.576127994353376,14.997270631725604,9.888370962140854, ...
                14.584523227465766,14.179424329180256, ...
                10.20732378093211,13.78189117535765, ...
                10.533067462993838,13.391864274742145, ...
                10.865663655755416,13.009260480347871, ...
                11.205193091129587,12.634015019827533, ...
                11.551718049704352,12.26606042141808, ...
                11.90531496343142];
            model=kssolv.analysis.matgenlab.analysis. ...
                QuasiHarmonicDebyeApprox(energies,volumes,structure, ...
                300,100,300,"vinet");
            volume=model.optimum_volumes(1);
            testCase.verifyEqual(volume,11.957803302392925,AbsTol=1e-3);
            testCase.verifyEqual(model.debye_temperature(volume), ...
                2559.675227,AbsTol=1e-3);
            testCase.verifyEqual(model.gruneisen_parameter(300,volume), ...
                1.670486,AbsTol=1e-3);
            testCase.verifyEqual(model.thermal_conductivity(300,volume), ...
                131.736242,AbsTol=.1);
            testCase.verifyEqual( ...
                model.vibrational_internal_energy(300,volume), ...
                .50102,AbsTol=1e-3);
            testCase.verifyEqual( ...
                model.vibrational_free_energy(300,volume), ...
                .494687,AbsTol=1e-3);
            summary=model.get_summary_dict();
            testCase.verifyEqual(summary.temperatures,300);
            testCase.verifyEqual(summary.optimum_volumes,volume);
        end

        function officialAnharmonicAluminumOracle(testCase)
            structure=kssolv.analysis.matgenlab.core.Structure( ...
                kssolv.analysis.matgenlab.core.Lattice([ ...
                2.473329,0,1.427977;.824443,2.331877,1.427977; ...
                0,0,2.855955]),{'Al'},[0,0,0]);
            model=kssolv.analysis.matgenlab.analysis. ...
                QuasiHarmonicDebyeApprox( ...
                [-3.69150886,-3.70788383,-3.71997361,-3.72522301, ...
                -3.73569569,-3.73649743,-3.74054982], ...
                [14.824542034870653,18.118887714656875, ...
                15.373596786943025,17.569833126580278, ...
                15.92265868064787,17.02077912220064, ...
                16.471717630914863],structure, ...
                500,100,500,"vinet",0,.25,false,true);
            volume=model.optimum_volumes(1);
            testCase.verifyEqual(volume,17.216094889116807,AbsTol=1e-3);
            testCase.verifyEqual(model.debye_temperature(volume), ...
                601.239096,AbsTol=.05);
            testCase.verifyEqual(model.gruneisen_parameter( ...
                0,model.ev_eos_fit.v0),2.188302,AbsTol=1e-2);
            testCase.verifyEqual(model.thermal_conductivity(500,volume), ...
                21.810997,AbsTol=.1);
            testCase.verifyError(@() ...
                kssolv.analysis.matgenlab.analysis. ...
                QuasiHarmonicDebyeApprox( ...
                model.energies,model.volumes,structure, ...
                500,100,500,"vinet",0,.25,true,true), ...
                "KSSOLV:Matgenlab:QuasiHarmonic:Circular");
        end
    end
end
