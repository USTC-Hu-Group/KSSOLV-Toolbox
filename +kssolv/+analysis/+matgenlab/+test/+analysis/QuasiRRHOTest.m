classdef QuasiRRHOTest < matlab.unittest.TestCase
    methods (Test)
        function waterOracle(testCase)
            molecule=kssolv.analysis.matgenlab.core.Molecule( ...
                {'O','H','H'},[0,0,0;.9572,0,0;-.2399872,.927297,0]);
            [average,eigenvalues]= ...
                kssolv.analysis.matgenlab.analysis. ...
                get_avg_mom_inertia(molecule);
            testCase.verifyEqual(average, ...
                1.9602830344134645e-47,RelTol=2e-15);
            testCase.verifyEqual(eigenvalues, ...
                [1.02138462e-47,1.91903993e-47,2.94042455e-47], ...
                RelTol=5e-9);
            value=kssolv.analysis.matgenlab.analysis.QuasiRRHO( ...
                molecule,[1595,3657,3756],-76.4,1);
            testCase.verifyEqual(value.entropy_quasiRRHO, ...
                46.442758414063185,AbsTol=2e-13);
            testCase.verifyEqual(value.h_corrected, ...
                .024301776410323297,AbsTol=2e-16);
            testCase.verifyEqual(value.free_energy_quasiRRHO, ...
                -76.39776467675651,AbsTol=2e-13);
        end

        function linearMoleculeOracle(testCase)
            molecule=kssolv.analysis.matgenlab.core.Molecule( ...
                {'O','C','O'},[0,0,-1.16;0,0,0;0,0,1.16]);
            value=kssolv.analysis.matgenlab.analysis.QuasiRRHO( ...
                molecule,[667,667,1333,2349],-188,1);
            testCase.verifyEqual(value.free_energy_ho, ...
                -188.00992132076436,AbsTol=5e-13);
            testCase.verifyEqual(value.free_energy_quasiRRHO, ...
                -188.00992134926233,AbsTol=5e-13);
        end

        function outputAdapters(testCase)
            molecule=kssolv.analysis.matgenlab.core.Molecule( ...
                {'O','H','H'},[0,0,0;.9572,0,0;-.2399872,.927297,0]);
            base=kssolv.analysis.matgenlab.analysis.QuasiRRHO( ...
                molecule,[1595,3657,3756],-76.4,1);
            gaussian=struct(final_structure=molecule, ...
                frequencies={{{struct(frequency=1595), ...
                struct(frequency=3657),struct(frequency=3756)}}}, ...
                final_energy=-76.4,spin_multiplicity=1);
            fromGaussian=kssolv.analysis.matgenlab.analysis. ...
                QuasiRRHO.from_gaussian_output(gaussian);
            qc=struct(data=struct(optimization=false, ...
                initial_molecule=molecule,frequencies=[1595,3657,3756], ...
                SCF_energy_in_the_final_basis_set=-76.4,multiplicity=1));
            fromQc=kssolv.analysis.matgenlab.analysis. ...
                QuasiRRHO.from_qc_output(qc);
            testCase.verifyEqual(fromGaussian.free_energy_quasiRRHO, ...
                base.free_energy_quasiRRHO,AbsTol=1e-14);
            testCase.verifyEqual(fromQc.free_energy_quasiRRHO, ...
                base.free_energy_quasiRRHO,AbsTol=1e-14);
        end
    end
end
