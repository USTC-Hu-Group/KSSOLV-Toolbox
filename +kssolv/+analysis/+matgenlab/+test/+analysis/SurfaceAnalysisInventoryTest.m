        function officialNanoscaleStabilityMatches(testCase)
            [hcp,~]=entryAnalyzer("La_hcp_entries.txt","La_hcp");
            [fcc,~]=entryAnalyzer("La_fcc_entries.txt","La_fcc");
            stability=kssolv.analysis.matgenlab.analysis. ...
                NanoscaleStability({fcc,hcp});
            radius=stability.solve_equilibrium_point(hcp,fcc);
            testCase.verifyEqual(radius,3.0322452206447053,AbsTol=1e-3);
            hcpShape=hcp.wulff_from_chempot();
            fccShape=fcc.wulff_from_chempot();
            testCase.verifyEqual(hcpShape.weighted_surface_energy, ...
                .048256197490888775,AbsTol=1e-6);
            testCase.verifyEqual(fccShape.weighted_surface_energy, ...
                .046372640341005994,AbsTol=1e-6);
            testCase.verifyEqual(stability.scaled_wulff( ...
                hcpShape,10).effective_radius,10,AbsTol=3e-11);
            testCase.verifyEqual(stability.scaled_wulff( ...
                fccShape,10).effective_radius,10,AbsTol=3e-11);
            low=radius*10-10;high=radius*10+10;
            [hcpLow,rLow]=stability.wulff_gform_and_r( ...
                hcpShape,hcp.ucell_entry,low,from_sphere_area=true);
            [fccLow,~]=stability.wulff_gform_and_r( ...
                fccShape,fcc.ucell_entry,low,from_sphere_area=true);
            [hcpHigh,rHigh]=stability.wulff_gform_and_r( ...
                hcpShape,hcp.ucell_entry,high,from_sphere_area=true);
            [fccHigh,~]=stability.wulff_gform_and_r( ...
                fccShape,fcc.ucell_entry,high,from_sphere_area=true);
            testCase.verifyLessThan(fccLow,hcpLow);
            testCase.verifyGreaterThan(fccHigh,hcpHigh);
            testCase.verifyEqual(rLow,low/10,AbsTol=3e-12);
            testCase.verifyEqual(rHigh,high/10,AbsTol=3e-12);
        end

