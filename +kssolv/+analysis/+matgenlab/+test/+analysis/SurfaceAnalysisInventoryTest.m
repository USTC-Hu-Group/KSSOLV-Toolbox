    methods (Test)
        function officialAdsorptionThermodynamicsMatch(testCase)
            [analyzers,adsorbate]=oxygenAnalyzers();
            cases={ ...
                "Ni",[1,0,0],3.999997719057772, ...
                    -5.974739886828379,0.016850001417724858, ...
                    -0.02032305430046445; ...
                "Ni",[1,1,1],3.9983696241768216, ...
                    -5.809246189180817,-0.015987252837530885, ...
                    -0.023467041742257062; ...
                "Pt",[1,1,1],4.0000020116831, ...
                    -4.508212135271725,0.008366102097000283, ...
                    -0.018253586607084236; ...
                "Rh",[1,0,0],4, ...
                    -5.440490009999996,0.05769410651804696, ...
                    -0.016907295048884708};
            for index=1:size(cases,1)
                analyzer=analyzers.(cases{index,1});
                group=facetGroup(analyzer,cases{index,2});
                clean=group.clean{1};ads=group.ads{1}{1};
                testCase.verifyEqual(ads.get_unit_primitive_area, ...
                    cases{index,3},AbsTol=2e-12);
                testCase.verifyEqual(ads.get_monolayer, ...
                    1/cases{index,3},AbsTol=2e-12);
                testCase.verifyEqual(ads.Nads_in_slab,1);
                testCase.verifyEqual(ads.Nsurfs_ads_in_slab,1);
                testCase.verifyEqual(ads.gibbs_binding_energy(), ...
                    cases{index,4},AbsTol=2e-12);
                testCase.verifyEqual(ads.gibbs_binding_energy(true), ...
                    cases{index,4},AbsTol=2e-12);
                expression=ads.surface_energy(analyzer.ucell_entry);
                testCase.verifyEqual(expression.constant, ...
                    cases{index,5},AbsTol=2e-12);
                testCase.verifyEqual(expression.coefficients.delu_O, ...
                    cases{index,6},AbsTol=2e-12);
                testCase.verifyEqual(clean.create_slab_label, ...
                    sprintf("(%d, %d, %d) %s1",cases{index,2}, ...
                    cases{index,1}));
                testCase.verifyEqual(ads.create_slab_label, ...
                    sprintf("(%d, %d, %d) %s1+O, 0.250 ML", ...
                    cases{index,2},cases{index,1}));
                testCase.verifyEqual(ads.cleaned_up_slab.composition. ...
                    reduced_composition, ...
                    clean.composition.reduced_composition);
                testCase.verifyEqual(ads.gibbs_binding_energy(), ...
                    (ads.energy-ads.get_unit_primitive_area*clean.energy)- ...
                    adsorbate.energy_per_atom,AbsTol=2e-12);
            end
        end

        function officialSurfaceStabilityMatches(testCase)
            [analyzers,~]=oxygenAnalyzers();
            expected=struct( ...
                "Ni_100",[.13827389280017743,.13827389280017743, ...
                    .03717305571818931,.016850001417724858], ...
                "Ni_111",[.11945397619021669,.11945397619021669, ...
                    .007479788904726177,-.015987252837530885], ...
                "Pt_111",[.09065803211215662,.09065803211215662, ...
                    .02661968870408452,.008366102097000283], ...
                "Rh_100",[.14967807632762642,.14967807632762642, ...
                    .07460140156693167,.05769410651804696]);
            names=fieldnames(expected);potentials=[-7,-6,-1,0];
            for index=1:numel(names)
                tokens=split(string(names{index}),"_");
                analyzer=analyzers.(tokens(1));
                hkl=double(char(tokens(2)))-double('0');
                for point=1:numel(potentials)
                    [entry,gamma]=analyzer.get_stable_entry_at_u( ...
                        hkl,"delu_dict", ...
                        struct("delu_O",potentials(point)));
                    testCase.verifyEqual(gamma, ...
                        expected.(names{index})(point),AbsTol=2e-12);
                    if point<=2
                        testCase.verifyFalse(contains(string(entry.label),"_O"));
                    else
                        testCase.verifyTrue(contains(string(entry.label),"_O"));
                    end
                end
            end
            ranges=analyzers.Rh.stable_u_range_dict( ...
                [-1,0],"delu_O","no_doped",false);
            testCase.verifyNotEmpty(ranges);
            testCase.verifyGreaterThan(numel(ranges(1).range),1);
            colors=analyzers.Ni.color_palette_dict();
            testCase.verifyEqual(numel(colors),4);
            variables=analyzers.Ni.set_all_variables(struct(),-2);
            testCase.verifyEqual(variables.delu_O,-2);
            testCase.verifyEqual(variables.constant,1);
        end

