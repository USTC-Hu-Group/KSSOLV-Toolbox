function [analyzers,adsorbate]=oxygenAnalyzers()
cleanData=readJson("cs_entries_slabs.json");
adsData=readJson("cs_entries_o_ads.json");
adsorbate=kssolv.analysis.matgenlab.core.ComputedStructureEntry. ...
    from_dict(readJson("isolated_O_entry.txt"));
bulkData=readJson("ucell_entries.txt");
analyzers=struct();
for element=["Ni","Pt","Rh"]
    entries={};names=fieldnames(cleanData);
    for index=1:numel(names)
        name=names{index};
        if ~contains(name,element),continue,end
        hkl=parseTrailingHkl(name);
        cleanBase=kssolv.analysis.matgenlab.core. ...
            ComputedStructureEntry.from_dict(cleanData.(name));
        clean=kssolv.analysis.matgenlab.analysis.SlabEntry( ...
            cleanBase.structure,cleanBase.energy,hkl, ...
            label=name+"_clean");
        adsBase=kssolv.analysis.matgenlab.core. ...
            ComputedStructureEntry.from_dict(adsData.(name));
        ads=kssolv.analysis.matgenlab.analysis.SlabEntry( ...
            adsBase.structure,adsBase.energy,hkl,label=name+"_O", ...
            adsorbates={adsorbate},clean_entry=clean);
        entries=[entries,{clean,ads}]; %#ok<AGROW>
    end
    bulk=kssolv.analysis.matgenlab.core.ComputedStructureEntry. ...
        from_dict(bulkData.(element));
    analyzers.(element)=kssolv.analysis.matgenlab.analysis. ...
        SurfaceEnergyPlotter(entries,bulk);
end
end

function [analyzer,entries]=entryAnalyzer(filename,bulkName,refNames)
if nargin<3,refNames={};end
data=readJson(filename);names=fieldnames(data);entries=cell(1,numel(names));
for index=1:numel(names)
    base=kssolv.analysis.matgenlab.core.ComputedStructureEntry. ...
        from_dict(data.(names{index}));
    hkl=parseEntryHkl(names{index});
    entries{index}=kssolv.analysis.matgenlab.analysis.SlabEntry( ...
        base.structure,base.energy,hkl,label=names{index});
end
bulkData=readJson("ucell_entries.txt");
bulk=kssolv.analysis.matgenlab.core.ComputedStructureEntry. ...
    from_dict(bulkData.(bulkName));
references=cell(1,numel(refNames));
for index=1:numel(refNames)
    references{index}=kssolv.analysis.matgenlab.core. ...
        ComputedStructureEntry.from_dict(bulkData.(refNames{index}));
end
analyzer=kssolv.analysis.matgenlab.analysis.SurfaceEnergyPlotter( ...
    entries,bulk,references);
end

function hkl=parseEntryHkl(name)
if endsWith(name,"_2_12")
    hkl=[2,-1,2];
    return
end
token=regexp(name,'_([0-9])([0-9])([0-9])_shift','tokens','once');
if isempty(token)
    token=regexp(name,'_([0-9])([0-9])([0-9])$','tokens','once');
end
if isempty(token)
    error("KSSOLV:Matgenlab:Test:SurfaceFixture", ...
        "Cannot identify Miller index in '%s'.",name);
end
hkl=cellfun(@str2double,token);
end

function hkl=parseTrailingHkl(name)
token=regexp(name,'_([0-9])([0-9])([0-9])$','tokens','once');
hkl=cellfun(@str2double,token);
end

function group=facetGroup(analyzer,hkl)
index=find(arrayfun(@(x)isequal(x.hkl,reshape(hkl,1,3)), ...
    analyzer.all_slab_entries),1);
group=analyzer.all_slab_entries(index);
end

function value=readJson(name)
value=jsondecode(fileread(fullfile(surfaceFixtureDirectory(),name)));
end

function directory=surfaceFixtureDirectory()
root=fileparts(fileparts(mfilename("fullpath")));
directory=fullfile(root,"+fixtures","+analysis","surfaces");
end
