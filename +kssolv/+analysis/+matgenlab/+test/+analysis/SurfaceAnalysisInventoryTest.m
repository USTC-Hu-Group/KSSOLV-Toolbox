        function nonStoichiometricAndSerializationMatch(testCase)
            [plotter,entries]=entryAnalyzer( ...
                "MgO_slab_entries.txt","MgO",{"Mg"});
            testCase.verifyEqual(numel(entries),2);
            for index=1:numel(entries)
                expression=entries{index}.surface_energy( ...
                    plotter.ucell_entry,plotter.ref_entries);
                testCase.verifyTrue(isfield(expression.coefficients,"delu_Mg"));
                testCase.verifyFalse(isfield(expression.coefficients,"delu_O"));
            end
            source=entries{1};
            restored=kssolv.analysis.matgenlab.analysis.SlabEntry. ...
                from_dict(source.as_dict());
            converted=kssolv.analysis.matgenlab.analysis.SlabEntry. ...
                from_computed_structure_entry(source,[1,1,1]);
            testCase.verifyEqual(restored.energy,source.energy);
            testCase.verifyEqual(restored.structure,source.structure);
            testCase.verifyEqual(converted.energy,source.energy);
            testCase.verifyEqual(converted.miller_index,[1,1,1]);
            grouped=kssolv.analysis.matgenlab.analysis. ...
                entry_dict_from_list(entries);
            testCase.verifyEqual(numel(grouped),1);
            expression=kssolv.analysis.matgenlab.analysis. ...
                SurfaceEnergyExpression(2,struct("delu_Mg",-.5));
            testCase.verifyEqual(kssolv.analysis.matgenlab.analysis. ...
                sub_chempots(expression,struct("delu_Mg",4)),0);
        end

