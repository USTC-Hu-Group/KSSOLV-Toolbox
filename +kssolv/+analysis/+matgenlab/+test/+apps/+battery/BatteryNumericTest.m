function verifyMembers(testCase,className,methodNames,propertyNames)
availableMethods=string(methods(char(className)));
availableProperties=string(properties(char(className)));
for name=reshape(string(methodNames),1,[])
    testCase.verifyTrue(any(availableMethods==name), ...
        "Missing method "+className+"."+name);
end
for name=reshape(string(propertyNames),1,[])
    testCase.verifyTrue(any(availableProperties==name), ...
        "Missing property "+className+"."+name);
end
end
function value=loadFixture(name)
path=fullfile(fileparts(mfilename("fullpath")),"+fixtures",name);
value=kssolv.analysis.matgenlab.util.decode(fileread(path));
end
function structure=loadCif(name,oxidationStates)
path=fullfile(fileparts(mfilename("fullpath")),"+fixtures",name);
structure=kssolv.analysis.matgenlab.core.Structure.from_file(path);
structure=structure.add_oxidation_state_by_element(oxidationStates);
end
