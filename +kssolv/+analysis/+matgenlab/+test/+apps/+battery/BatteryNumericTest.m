        function conversionOfficialFixtures(testCase)
            formulas=["LiCoO2","FeF3","MnO2"];ions=["Li","Li","Mg"];
            expected=[2.26940307125,903.197529112,2903.35804724; ...
                3.06179925889,601.545087016,2132.20691151; ...
                1.71270276879017,790.914207003,3543.20200353];
            for index=1:numel(formulas)
                entries=loadFixture(formulas(index)+"_batt.json");
                electrode=kssolv.analysis.matgenlab.apps.battery. ...
                    ConversionElectrode.from_composition_and_entries( ...
                    formulas(index),entries,ions(index));
                diagram=kssolv.analysis.matgenlab.analysis.PhaseDiagram(entries);
                fromDiagram=kssolv.analysis.matgenlab.apps.battery. ...
                    ConversionElectrode.from_composition_and_pd( ...
                    formulas(index),diagram,ions(index));
                testCase.verifyEqual(fromDiagram.get_average_voltage(), ...
                    electrode.get_average_voltage(),AbsTol=1e-14);
                testCase.verifyEqual(electrode.get_average_voltage(), ...
                    expected(index,1),AbsTol=2e-10);
                testCase.verifyEqual(electrode.get_capacity_grav(), ...
                    expected(index,2),AbsTol=1e-3);
                testCase.verifyEqual(electrode.get_capacity_vol(), ...
                    expected(index,3),AbsTol=1e-3);
                testCase.verifyEqual(numel(electrode.get_sub_electrodes(true)), ...
                    electrode.num_steps);
                testCase.verifyEqual(numel(electrode.get_sub_electrodes(false)), ...
                    sum(1:electrode.num_steps));
                adjacent=electrode.get_sub_electrodes(true);
                testCase.verifyTrue(electrode.is_super_electrode(adjacent{1}));
                testCase.verifyEqual(electrode.initial_comp.reduced_formula, ...
                    formulas(index));
                summary=electrode.get_summary_dict();
                testCase.verifyEqual(numel(summary.reactions), ...
                    electrode.num_steps);
                restored=kssolv.analysis.matgenlab.apps.battery. ...
                    ConversionElectrode.from_dict(electrode.as_dict());
                testCase.verifyEqual(restored.get_average_voltage(), ...
                    electrode.get_average_voltage(),AbsTol=1e-14);
            end
        end

        function analyzerOfficialFixtures(testCase)
            previous=warning("off","all");cleanup=onCleanup(@()warning(previous));
            structure=loadCif("LiFePO4.cif", ...
                struct("Li",1,"Fe",2,"P",5,"O",-2));
            analyzer=kssolv.analysis.matgenlab.apps.battery. ...
                BatteryAnalyzer(structure,"Li");
            testCase.verifyGreaterThanOrEqual(analyzer.max_ion_removal,0);
            testCase.verifyGreaterThanOrEqual(analyzer.max_ion_insertion,0);
            testCase.verifyEqual(analyzer.get_max_capgrav(), ...
                169.89053,AbsTol=1e-3);
            testCase.verifyEqual(analyzer.get_max_capvol(), ...
                594.17518,AbsTol=1e-3);
            structure=loadCif("Li4Fe3Mn1(PO4)4.cif", ...
                struct("Li",1,"Fe",2,"Mn",2,"P",5,"O",-2));
            analyzer=kssolv.analysis.matgenlab.apps.battery. ...
                BatteryAnalyzer(structure,"Li");
            testCase.verifyEqual(analyzer.get_removals_int_oxid(),1:4);
            structure=loadCif("MgNiF6.cif", ...
                struct("Mg",2,"Ni",4,"F",-1));
            analyzer=kssolv.analysis.matgenlab.apps.battery. ...
                BatteryAnalyzer(structure,"F");
            testCase.verifyEqual(analyzer.get_removals_int_oxid(),[1,2]);
            testCase.verifyTrue(kssolv.analysis.matgenlab.apps.battery. ...
                is_redox_active_intercalation("Fe"));
            testCase.verifyFalse(kssolv.analysis.matgenlab.apps.battery. ...
                is_redox_active_intercalation("Li"));
            clear cleanup
        end
