        function insertionOfficialFixtures(testCase)
            entries=loadFixture("LiTiO2_batt.json");
            lithium=kssolv.analysis.matgenlab.core.ComputedEntry( ...
                "Li",-1.90753119);
            electrode=kssolv.analysis.matgenlab.apps.battery. ...
                InsertionElectrode.from_entries(entries,lithium);
            testCase.verifyEqual(electrode.max_voltage,2.78583901,AbsTol=1e-8);
            testCase.verifyEqual(electrode.min_voltage,0.89702381,AbsTol=1e-8);
            testCase.verifyEqual(electrode.get_average_voltage(), ...
                1.84143141,AbsTol=1e-8);
            testCase.verifyEqual(electrode.get_capacity_grav(), ...
                308.74865045,AbsTol=2e-4);
            testCase.verifyEqual(electrode.get_capacity_vol(), ...
                1205.99391136,AbsTol=2e-4);
            testCase.verifyEqual(electrode.get_specific_energy(), ...
                electrode.get_capacity_grav()* ...
                electrode.get_average_voltage(),AbsTol=1e-10);
            testCase.verifyEqual(electrode.get_energy_density(), ...
                electrode.get_capacity_vol()* ...
                electrode.get_average_voltage(),AbsTol=1e-10);
            testCase.verifyEqual(numel(electrode.get_sub_electrodes(false,true)),3);
            testCase.verifyEqual(numel(electrode.get_sub_electrodes(true,true)),2);
            testCase.verifyEqual(numel(electrode.get_stable_entries()),3);
            testCase.verifyEqual(electrode.get_stable_entries(false), ...
                fliplr(electrode.get_stable_entries()));
            testCase.verifyEqual(numel(electrode.get_all_entries()), ...
                numel(electrode.get_stable_entries())+ ...
                numel(electrode.get_unstable_entries()));
            stable=electrode.get_stable_entries();
            testCase.verifyEqual(electrode.fully_charged_entry, ...
                stable{1});
            testCase.verifyEqual(electrode.fully_discharged_entry,stable{end});
            testCase.verifyGreaterThanOrEqual(electrode.max_delta_volume,0);
            testCase.verifyGreaterThan(electrode.normalization_mass,0);
            testCase.verifyGreaterThan(electrode.normalization_volume,0);
            pair=electrode.voltage_pairs{1};
            testCase.verifyEqual(pair.mAh,13400.7411749,AbsTol=1e-3);
            testCase.verifyEqual(pair.mass_charge,79.8658,AbsTol=1e-8);
            testCase.verifyEqual(pair.vol_charge,37.553684467,AbsTol=1e-9);
            testCase.verifyEqual(pair.x_discharge,0.5,AbsTol=1e-14);
            testCase.verifyEqual(pair.working_ion.symbol,"Li");
            testCase.verifyEqual(pair.framework.reduced_formula,"TiO2");
            restored=kssolv.analysis.matgenlab.apps.battery. ...
                InsertionElectrode.from_dict(electrode.as_dict());
            testCase.verifyEqual(restored.get_average_voltage(), ...
                electrode.get_average_voltage(),AbsTol=1e-14);
            legacy=kssolv.analysis.matgenlab.apps.battery. ...
                InsertionElectrode.from_dict_legacy( ...
                electrode.as_dict_legacy());
            testCase.verifyEqual(legacy.get_average_voltage(), ...
                electrode.get_average_voltage(),AbsTol=1e-14);
        end

