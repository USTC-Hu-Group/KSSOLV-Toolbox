        function neighborStrategiesOnCsCl(testCase)
            structure=kssolv.analysis.matgenlab.core.Structure( ...
                kssolv.analysis.matgenlab.core.Lattice.cubic(4.209), ...
                {"Cl1-","Cs1+"},[.5,.5,.5;0,0,0]);
            voronoi=kssolv.analysis.matgenlab.core.VoronoiNN();
            isayev=kssolv.analysis.matgenlab.core.IsayevNN();
            crystal=kssolv.analysis.matgenlab.core.CrystalNN();
