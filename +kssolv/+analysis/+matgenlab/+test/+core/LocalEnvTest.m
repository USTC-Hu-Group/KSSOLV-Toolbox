            testCase.verifyEqual(voronoi.get_cn(structure,1),14);
            testCase.verifyEqual(isayev.get_cn(structure,1),8);
            testCase.verifyEqual(crystal.get_cn(structure,1),8);
            testCase.verifyEqual(weighted.get_cn(structure,1,"use_weights",true), ...
                8.114587261697661,AbsTol=1e-10);
        end

