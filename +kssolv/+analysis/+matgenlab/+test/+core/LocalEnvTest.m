        function officialValenceAndMolecularOracles(testCase)
            mgo=kssolv.analysis.matgenlab.core.Structure( ...
                kssolv.analysis.matgenlab.core.Lattice.cubic(4.212), ...
                [repmat({"Mg"},1,4),repmat({"O"},1,4)], ...
                [0,0,0;.5,.5,0;.5,0,.5;0,.5,.5; ...
                .5,0,0;0,.5,0;0,0,.5;.5,.5,.5]);
            evaluator=kssolv.analysis.matgenlab.core. ...
                ValenceIonicRadiusEvaluator(mgo);
            testCase.verifyEqual(sort(cell2mat(struct2cell(evaluator.valences))), ...
                [-2;2]);
            testCase.verifyEqual(sort(cell2mat(struct2cell(evaluator.radii))), ...
                [.86;1.26],AbsTol=1e-12);
            testCase.verifyEqual(evaluator.structure.num_sites,8);

            fixture=kssolv.analysis.matgenlab.test.core.LocalEnvTest.fixturePath();
            benzene=kssolv.analysis.matgenlab.core.Molecule.from_file( ...
                fullfile(fixture,"benzene.xyz"));
            acetylene=kssolv.analysis.matgenlab.core.Molecule.from_file( ...
                fullfile(fixture,"acetylene.xyz"));
            covalent=kssolv.analysis.matgenlab.core.CovalentBondNN();
            acetyleneInfo=covalent.get_nn_info(acetylene,1);
            testCase.verifyEqual(sort(cellfun(@(item)item.weight,acetyleneInfo)), ...
                [1,3],AbsTol=1e-12);
            benzeneInfo=covalent.get_nn_info(benzene,1);
            testCase.verifyEqual(sort(cellfun(@(item)item.weight,benzeneInfo)), ...
                [1,1.6596,1.6596],AbsTol=1e-4);
            lengths=kssolv.analysis.matgenlab.core.CovalentBondNN( ...
                "order",false). ...
                get_nn_info(benzene,1);
            symbols=cellfun(@(item)item.site.specie.symbol,lengths);
            weights=cellfun(@(item)item.weight,lengths);
            testCase.verifyEqual(weights(symbols=="H"),1.02,AbsTol=.02);
            testCase.verifyEqual(weights(find(symbols=="C",1)),1.41,AbsTol=.02);

            openbabel=kssolv.analysis.matgenlab.core.OpenBabelNN();
            testCase.verifyEqual(sort(cellfun(@(item)item.weight, ...
                openbabel.get_nn_info(acetylene,1))),[1,3],AbsTol=1e-12);
            openbabelLengths=kssolv.analysis.matgenlab.core.OpenBabelNN( ...
                "order",false). ...
                get_nn_info(acetylene,1);
            testCase.verifyEqual(openbabelLengths{1}.weight,1.19,AbsTol=.02);
            testCase.verifyEqual(covalent.get_bonded_structure(acetylene). ...
                graph.number_of_nodes(),4);
        end

        function officialNeighborStrategyMatrix(testCase)
            [diamond,nacl,cscl,lifepo4]=kssolv.analysis.matgenlab.test. ...
                core.LocalEnvTest.crystalFixtures();
            core="kssolv.analysis.matgenlab.core.";
            names=["MinimumDistanceNN","MinimumOKeeffeNN","MinimumVIRENN", ...
                "BrunnerNNReciprocal","BrunnerNNRelative","BrunnerNNReal", ...
                "EconNN","VoronoiNN","CrystalNN"];
            expected=[4,6,8,6;4,6,8,2;4,6,8,2;4,6,14,6; ...
                4,6,14,6;4,6,14,30;4,6,14,6;4,6,8,6;4,6,8,6];
            for ii=1:numel(names)
                constructor=str2func(core+names(ii));
                if any(ii==2:6)
                    strategy=constructor("tol",.01);
                elseif names(ii)=="VoronoiNN"
                    strategy=constructor("tol",.5);
                else
                    strategy=constructor();
                end
                actual=[strategy.get_cn(diamond,1),strategy.get_cn(nacl,1), ...
                    strategy.get_cn(cscl,1),strategy.get_cn(lifepo4,1)];
                testCase.verifyEqual(actual,expected(ii,:), ...
                    "Strategy "+names(ii)+" diverged from the frozen oracle.");
            end
            allSites=kssolv.analysis.matgenlab.core.MinimumDistanceNN( ...
                "cutoff",5, ...
                "get_all_sites",true);
            testCase.verifyEqual(allSites.get_cn(cscl,1),14);
            testCase.verifyEqual(kssolv.analysis.matgenlab.core. ...
                IsayevNN().get_cn(lifepo4,1),2);

            jmol=kssolv.analysis.matgenlab.core.JmolNN();
            testCase.verifyEqual(arrayfun(@(ii)jmol.get_cn(lifepo4,ii),1:12), ...
                [zeros(1,4),6*ones(1,4),4*ones(1,4)]);
            updated=kssolv.analysis.matgenlab.core.JmolNN( ...
                "el_radius_updates",struct(Li=1));
            testCase.verifyEqual(updated.get_cn(lifepo4,1),2);

            motif=str2func(core+"site_is_of_motif_type");
            testCase.verifyEqual(motif(diamond,1),"tetrahedral");
            testCase.verifyEqual(motif(nacl,1),"octahedral");
            testCase.verifyEqual(motif(cscl,1),"bcc");
            neighbors=str2func(core+"get_neighbors_of_site_with_index");
            testCase.verifyNumElements(neighbors(diamond,1),4);
            testCase.verifyNumElements(neighbors(nacl,1),6);
            testCase.verifyNumElements(neighbors(cscl,1),8);
        end

        function officialVoronoiAndCrystalOracles(testCase)
            simple=kssolv.analysis.matgenlab.core.Structure( ...
                kssolv.analysis.matgenlab.core.Lattice.cubic(1),{"Cu"},[0,0,0]);
            voronoi=kssolv.analysis.matgenlab.core.VoronoiNN();
            poly=voronoi.get_voronoi_polyhedra(simple,1);
            testCase.verifyNumElements(poly,6);
            testCase.verifyEqual(sum(cellfun(@(item)item.solid_angle,poly)), ...
                4*pi,AbsTol=1e-8);
            testCase.verifyTrue(all(cellfun(@(item) ...
                numel(item.adj_neighbors)==4,poly)));
            firstShell=voronoi.get_nn_shell_info(simple,1,1);
            secondShell=voronoi.get_nn_shell_info(simple,1,2);
            testCase.verifyNumElements(firstShell,6);
            testCase.verifyNumElements(secondShell,18);
            secondImages=cell2mat(cellfun(@(item)item.image,secondShell, ...
                "UniformOutput",false).');
            secondWeights=cellfun(@(item)item.weight,secondShell);
            testCase.verifyEqual(sort(secondWeights(max(abs(secondImages),[],2)==2)), ...
                ones(1,6),AbsTol=1e-12);
            testCase.verifyEqual(sort(secondWeights(max(abs(secondImages),[],2)==1)), ...
                2*ones(1,12),AbsTol=1e-12);

            [~,~,~,lifepo4]=kssolv.analysis.matgenlab.test.core. ...
                LocalEnvTest.crystalFixtures();
            weighted=kssolv.analysis.matgenlab.core.CrystalNN( ...
                "weighted_cn",true);
            actual=arrayfun(@(ii)weighted.get_cn(lifepo4,ii, ...
                "use_weights",true),1:lifepo4.num_sites);
            expected=[5.863,5.8716,5.863,5.8716,5.7182,5.7182,5.719, ...
                5.7181,3.991,3.991,3.991,3.9907,3.5997,3.525,3.4133, ...
                3.4714,3.4727,3.4133,3.525,3.5997,3.5997,3.525,3.4122, ...
                3.4738,3.4728,3.4109,3.5259,3.5997];
            testCase.verifyEqual(actual,expected,AbsTol=5e-5);
            fixed=kssolv.analysis.matgenlab.core.CrystalNN( ...
                "fingerprint_length",30). ...
                get_nn_data(lifepo4,1);
            testCase.verifyNumElements(keys(fixed.cn_weights),30);
            testCase.verifyNumElements(keys(fixed.cn_nninfo),30);

            he=kssolv.analysis.matgenlab.core.Structure( ...
                kssolv.analysis.matgenlab.core.Lattice( ...
                [2.58063058,0,-.91239069;-1.29031529,2.23489164,-.91239069; ...
                0,0,2.73717207]),{"He"},[0,0,0]);
            he=he.add_oxidation_state_by_guess();
            testCase.verifyEqual(kssolv.analysis.matgenlab.core. ...
                CrystalNN().get_cn(he,1),0);
            testCase.verifyEqual(kssolv.analysis.matgenlab.core.CrystalNN( ...
                "distance_cutoffs",{1.25,5}).get_cn(he,1),8);
        end

        function officialGraphExtenderOracles(testCase)
            fixture=fullfile(kssolv.analysis.matgenlab.test.core. ...
                LocalEnvTest.fixturePath(),"fragmenter_files");

            liec=kssolv.analysis.matgenlab.core.Molecule.from_file( ...
                fullfile(fixture,"LiEC.xyz"));
            liecEdges=[1,3;1,2;2,4;2,5;3,8;3,6;3,9;4,7;5,6;6,10;6,11];
            liecGraph=kssolv.analysis.matgenlab.core.MoleculeGraph. ...
                from_edges(liec,liecEdges);
            testCase.verifyEqual(liecGraph.graph.number_of_edges(),11);
            liecGraph=kssolv.analysis.matgenlab.core. ...
                metal_edge_extender(liecGraph);
            testCase.verifyEqual(liecGraph.graph.number_of_edges(),12);

            phsh=kssolv.analysis.matgenlab.core.Molecule.from_file( ...
                fullfile(fixture,"phsh.xyz"));
            phshEdges=[1,2;1,3;1,4;1,5;5,6;5,7;5,19;7,8;7,17; ...
                8,9;8,10;10,11;10,12;12,15;13,14;13,26;15,16; ...
                15,17;17,18;19,20;19,21;19,22;22,23;22,24;22,25];
            phshGraph=kssolv.analysis.matgenlab.core.MoleculeGraph. ...
                from_edges(phsh,phshEdges);
            testCase.verifyEqual(phshGraph.graph.number_of_edges(),25);
            phshGraph=kssolv.analysis.matgenlab.core. ...
                oxygen_edge_extender(phshGraph);
            testCase.verifyEqual(phshGraph.graph.number_of_edges(),26);

            potassium=kssolv.analysis.matgenlab.core.Molecule.from_file( ...
                fullfile(fixture,"water_cluster_K.xyz"));
            potassiumGraph=kssolv.analysis.matgenlab.core.MoleculeGraph. ...
                from_empty_graph(potassium);
            kssolv.analysis.matgenlab.core.metal_edge_extender(potassiumGraph, ...
                "metals",{},"cutoff",2.5);
            testCase.verifyEqual(potassiumGraph.graph.number_of_edges(),0);
            kssolv.analysis.matgenlab.core.metal_edge_extender(potassiumGraph, ...
                "metals",{"K"},"cutoff",2.5);
            testCase.verifyEqual(potassiumGraph.graph.number_of_edges(),4);

            magnesium=kssolv.analysis.matgenlab.core.Molecule.from_file( ...
                fullfile(fixture,"water_cluster_Mg.xyz"));
            magnesiumGraph=kssolv.analysis.matgenlab.core.MoleculeGraph. ...
                from_empty_graph(magnesium);
            kssolv.analysis.matgenlab.core.metal_edge_extender( ...
                magnesiumGraph,"cutoff",1.5);
            testCase.verifyEqual(magnesiumGraph.graph.number_of_edges(),6);
        end

