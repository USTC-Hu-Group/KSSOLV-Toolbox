            element = meta.class.fromName( ...
                "kssolv.analysis.matgenlab.core.ElementBase");
            properties = ["X", "atomic_radius", "atomic_mass", ...
                "atomic_mass_number", "atomic_orbitals_eV", "data", ...
                "ionization_energy", "electron_affinity", ...
                "electronic_structure", "average_ionic_radius", ...
                "average_cationic_radius", "average_anionic_radius", ...
                "ionic_radii", "number", "max_oxidation_state", ...
                "min_oxidation_state", "oxidation_states", ...
                "common_oxidation_states", "icsd_oxidation_states", ...
                "full_electronic_structure", "n_electrons", "valence", ...
                "term_symbols", "ground_state_term_symbol", "row", ...
                "group", "block", "is_noble_gas", ...
                "is_transition_metal", "is_post_transition_metal", ...
                "is_rare_earth", "is_metal", "is_metalloid", ...
                "is_alkali", "is_alkaline", "is_halogen", ...
                "is_chalcogen", "is_lanthanoid", "is_actinoid", ...
                "is_radioactive", "is_quadrupolar", ...
                "nmr_quadrupole_moment", "iupac_ordering"];
            testCase.verifyTrue(all(ismember(properties, ...
                string({element.PropertyList.Name}))));
            methods = ["from_Z", "from_name", "from_row_and_group", ...
                "is_valid_symbol", "as_dict", "from_dict", ...
                "print_periodic_table"];
            testCase.verifyTrue(all(ismember(methods, ...
                string({element.MethodList.Name}))));
        end
