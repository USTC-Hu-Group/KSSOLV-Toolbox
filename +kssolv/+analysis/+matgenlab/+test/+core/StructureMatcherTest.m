    methods (Access = private)
        function structure = loadStructure(testCase, filename)
            value = jsondecode(fileread( ...
                fullfile(testCase.fixtureRoot(), filename)));
            structure = ...
                kssolv.analysis.matgenlab.core.Structure.from_dict(value);
        end

        function path = fixtureRoot(~)
            path = fullfile(fileparts(mfilename("fullpath")), ...
                "fixtures", "structure_matcher");
        end

        function value=loadOracle(~)
            root=fileparts(fileparts(fileparts(fileparts( ...
                fileparts(fileparts(mfilename("fullpath")))))));
            value=jsondecode(fileread(fullfile(root,"dev","matgenlab", ...
                "oracles","structure_matcher_2026.7.24.json")));
        end
    end
