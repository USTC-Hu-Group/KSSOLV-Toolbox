        function frozenPlotterOracle(testCase)
            testCase.assumeTrue(kssolv.analysis.matgenlab.test.support. ...
                PymatgenOracle.isAvailable());
            root=electronicFixtureRoot();testCase.assumeTrue(isfolder(root));
            raw=jsondecode(fileread(fullfile(root,"bandstructure", ...
                "CaO_2605_bandstructure.json")));
            band=kssolv.analysis.matgenlab.electronic_structure. ...
                BandStructure.from_dict(raw);
            wire=band.as_dict();
            request=struct(module="pymatgen.electronic_structure.plotter", ...
                symbol="BSPlotter",construct=struct(args={{wire}}), ...
                operations={{struct(kind="call",name="get_ticks")}});
            reference=kssolv.analysis.matgenlab.test.support. ...
                PymatgenOracle.execute(request);
            plotter=kssolv.analysis.matgenlab.electronic_structure.BSPlotter(band);
            ticks=plotter.get_ticks();
            testCase.verifyEqual(ticks.distance, ...
                reshape(reference.results.distance,1,[]),AbsTol=1e-12);
            testCase.verifyEqual(ticks.label, ...
                reshape(string(reference.results.label),1,[]));
        end

        function projectedCohpAndReciprocalPlots(testCase)
            import kssolv.analysis.matgenlab.electronic_structure.*
            import kssolv.analysis.matgenlab.core.*
            root=electronicFixtureRoot();testCase.assumeTrue(isfolder(root));
            band=BandStructure.from_dict(jsondecode(fileread(fullfile(root, ...
                "bandstructure","Cu2O_361_bandstructure.json"))));
            projected=BSPlotterProjected(band);
            axesHandles=projected.get_projected_plots_dots( ...
                struct("Cu",["d","s"],"O","p"));
            testCase.verifyNumElements(axesHandles,4);
            testCase.verifyEqual(string(axesHandles(4).Visible),"off");
            close(ancestor(axesHandles(1),"figure"));
            summedAxes=projected.get_projected_plots_dots_patom_pmorb( ...
                struct("Cu",["dxy","s","px"],"O",["px","py","pz"]), ...
                struct("Cu",[3,5],"O",1),struct("Cu",[3,5]), ...
                struct("Cu",["dxy","px"]),true,[],false,[0,2],[],3);
            testCase.verifyNumElements(summedAxes,5);
            testCase.verifyEqual(string(summedAxes(1).Title.String),"Cu all s");
            close(ancestor(summedAxes(1),"figure"));

            cohp=Cohp(0,[-1,0,1],struct("up",[-1,0,1]), ...
                "icohp",struct("up",[-1,-1,0]));
            cp=CohpPlotter();cp.add_cohp("bond",cohp);
