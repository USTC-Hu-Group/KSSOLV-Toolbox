classdef CohpPlotterTest < matlab.unittest.TestCase
    methods (Test)
        function cohpNumericsMsonAndOracle(testCase)
            import kssolv.analysis.matgenlab.electronic_structure.*
            cohp=Cohp(0,[-2,-1,0,1], ...
                struct("up",[-.2,.2,-.1,.3],"down",[-.1,.1,-.05,.15]), ...
                "icohp",struct("up",[0,-.2,-.3,0],"down",[0,-.1,-.15,0]));
            testCase.verifyEqual(cohp.get_interpolated_value(-.5).up,.05,AbsTol=1e-14);
            testCase.verifyTrue(cohp.has_antibnd_states_below_efermi().up);
            restored=Cohp.from_dict(cohp.as_dict());
            testCase.verifyEqual(restored.cohp,cohp.cohp);
            lines=splitlines(string(char(Cohp(0,[-1,0], ...
                struct("up",[-1,0])))));
            testCase.verifyEqual(lines(2),"-1.00000 -1.00000");
            testCase.verifyEqual(lines(3),"0.00000 0.00000");

            testCase.assumeTrue(kssolv.analysis.matgenlab.test.support. ...
                PymatgenOracle.isAvailable());
            request=struct(module="pymatgen.electronic_structure.cohp", ...
                symbol="Cohp",construct=struct(args={{0,[-2,-1,0,1], ...
                cohp.as_dict().COHP}},kwargs=struct(icohp=cohp.as_dict().ICOHP)), ...
                operations={{struct(kind="call",name="get_interpolated_value", ...
                args={{-.5}}),struct(kind="call", ...
                name="has_antibnd_states_below_efermi")}});
            reference=kssolv.analysis.matgenlab.test.support. ...
                PymatgenOracle.execute(request);
            first=oracleResult(reference.results,1);
            second=oracleResult(reference.results,2);
            testCase.verifyEqual(cohp.get_interpolated_value(-.5).up, ...
                first.x1,AbsTol=1e-14);
            testCase.verifyEqual(cohp.has_antibnd_states_below_efermi().up, ...
                second.x1);
        end

