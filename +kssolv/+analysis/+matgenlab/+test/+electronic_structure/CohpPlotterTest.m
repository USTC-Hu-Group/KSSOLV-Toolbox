function root=electronicFixtureRoot()
base=string(getenv("MATGENLAB_PYMATGEN_CORE"));
if base=="",base="/tmp/matgenlab-pymatgen-core-v2026.7.24";end
root=fullfile(base,"test-files","electronic_structure");
end
function root=cohpFixtureRoot(),root=fullfile(electronicFixtureRoot(),"cohp");end
function value=mockMuDoping()
value=struct("n",struct("x300",[1,1.5]), ...
    "p",struct("x300",[-.5,-.2]));
end
function value=mockTransport(varargin)
if any(cellfun(@(x)islogical(x)&&~x,varargin))
    value=struct("x300",reshape(1:15,5,3));
else
    carrier=struct("x300",[1,2;2,3]);
    value=struct("n",carrier,"p",carrier);
end
end
function value=mockSpecial(varargin) %#ok<INUSD>
value=reshape(1:15,5,3);
end
function value=oracleResult(results,index)
if iscell(results),value=results{index};else,value=results(index);end
end
