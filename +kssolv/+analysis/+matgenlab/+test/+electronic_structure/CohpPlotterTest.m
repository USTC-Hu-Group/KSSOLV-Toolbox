            testCase.verifyNumElements(data.distances{1},16);
            testCase.verifyEqual(sum(cellfun(@numel,data.distances)),160);
            testCase.verifyEqual(plotter.get_ticks().label(6),"K");
            testCase.verifyEqual(plotter.get_ticks().distance(6), ...
                2.406607625322699,AbsTol=1e-12);
