            analyzer=struct(mu_steps=energies,gap=1,vol=10, ...
                doping=struct("n",[1e18,1e19],"p",[1e18,1e19]), ...
                mu_doping=mockMuDoping(),x_carrier_conc=struct("x300",1:5), ...
                dos=Dos(0,energies,ones(1,5)), ...
