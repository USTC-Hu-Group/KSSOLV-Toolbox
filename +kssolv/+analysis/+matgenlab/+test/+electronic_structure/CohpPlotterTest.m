                get_power_factor=@mockTransport,get_zt=@mockTransport, ...
                get_average_eff_mass=@mockTransport, ...
                get_seebeck_eff_mass=@mockSpecial, ...
                get_complexity_factor=@mockSpecial, ...
                get_hall_carrier_concentration=@()struct("x300",1:5));
            plotter=BoltztrapPlotter(analyzer);
            handles={plotter.plot_seebeck_mu(300), ...
                plotter.plot_conductivity_temp(), ...
                plotter.plot_power_factor_dop(300), ...
                plotter.plot_seebeck_eff_mass_mu(300), ...
                plotter.plot_complexity_factor_mu(300), ...
                plotter.plot_dos(),plotter.plot_carriers(), ...
                plotter.plot_hall_carriers()};
            testCase.verifyTrue(all(cellfun(@(x)isgraphics(x,"axes"),handles)));
            cellfun(@(x)close(ancestor(x,"figure")),handles);
        end
