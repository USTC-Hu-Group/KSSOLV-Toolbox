        function nativeRawLobsterAndLmto(testCase)
            import kssolv.analysis.matgenlab.electronic_structure.*
            root=cohpFixtureRoot();testCase.assumeTrue(isfolder(root));
            warning("off","KSSOLV:Matgenlab:Poscar:DefaultNames");
            cleanup=onCleanup(@()warning("on","KSSOLV:Matgenlab:Poscar:DefaultNames"));
            lobster=CompleteCohp.from_file("LOBSTER", ...
                fullfile(root,"COHPCAR.lobster.gz"),fullfile(root,"POSCAR"));
            testCase.verifyNumElements(lobster.energies,301);
            testCase.verifyEqual(lobster.efermi,9.75576,AbsTol=1e-12);
            testCase.verifyEqual(double(lobster.all_cohps.Count),2);
            orbital=CompleteCohp.from_file("LOBSTER", ...
                fullfile(root,"COHPCAR.lobster.orbitalwise.gz"), ...
                fullfile(root,"POSCAR.orbitalwise"));
            testCase.verifyEqual(double(orbital.orb_res_cohp("2").Count),16);
            testCase.verifyClass(orbital.get_orbital_resolved_cohp( ...
                "2","4s-4px"), ...
                "kssolv.analysis.matgenlab.electronic_structure.Cohp");
            lmto=CompleteCohp.from_file("LMTO",fullfile(root,"COPL"), ...
                fullfile(root,"CTRL"));
            testCase.verifyNumElements(lmto.energies,801);
            testCase.verifyEqual(lmto.efermi,-1.1658,AbsTol=1e-5);
            testCase.verifyEqual(double(lmto.all_cohps.Count),8);

            multi=CompleteCohp.from_file("LOBSTER", ...
                fullfile(root,"COBICAR.lobster.GeTe_4center"), ...
                fullfile(root,"POSCAR.GeTe"), ...
                "are_multi_center_cobis",true);
            testCase.verifyEqual(double(multi.all_cohps.Count),13);
            testCase.verifyNumElements(multi.bonds("13").sites,4);
            spinMulti=CompleteCohp.from_file("LOBSTER", ...
                fullfile(root,"COBICAR.lobster.B2H6.spin"), ...
                fullfile(root,"POSCAR.B2H6"), ...
                "are_multi_center_cobis",true);
            lobsterAverage=CompleteCohp.from_file("LOBSTER", ...
                fullfile(root,"COBICAR.lobster.B2H6.spin.average.2"), ...
                fullfile(root,"POSCAR.B2H6"),"are_cobis",true);
            testCase.verifyEqual(spinMulti.cohp.up,lobsterAverage.cohp.up, ...
                AbsTol=1e-4);
            testCase.verifyEqual(spinMulti.cohp.down, ...
                lobsterAverage.cohp.down,AbsTol=1e-4);
            testCase.verifyEqual(spinMulti.icohp.up, ...
                lobsterAverage.icohp.up,AbsTol=1e-4);
            testCase.verifyEqual(spinMulti.icohp.down, ...
                lobsterAverage.icohp.down,AbsTol=1e-4);
            clear cleanup
        end

        function icohpValueAndCollection(testCase)
            import kssolv.analysis.matgenlab.electronic_structure.*
            value=IcohpValue("1","K1","F2",2.1,[-1,0,0],1, ...
                struct("up",-1.1,"down",-1));
            testCase.verifyEqual(value.summed_icohp,-2.1,AbsTol=1e-14);
            collection=IcohpCollection(["1","2"],["K1","K1"], ...
                ["F2","F3"],[2.1,3.2],{[-1,0,0],[0,0,0]},[1,1], ...
                {struct("up",-1.1,"down",-1), ...
                struct("up",-.2,"down",-.4)},true);
            testCase.verifyEqual(collection.get_icohp_by_label("1"),-2.1);
            testCase.verifyEqual(collection.get_summed_icohp_by_label_list( ...
                ["1","2"],2),-1.35,AbsTol=1e-14);
            testCase.verifyEqual(collection.extremum_icohpvalue(),-2.1);
            testCase.verifyEqual(double(collection.get_icohp_dict_by_bondlengths( ...
                2,2.5).Count),1);
            restored=IcohpCollection.from_dict(collection.as_dict());
            testCase.verifyEqual(restored.get_icohp_by_label("2"),-.6,AbsTol=1e-14);

            orbitalData={struct("x2s_6s",struct( ...
                "icohp",struct("x1",.0247,"x_1",.0247), ...
                "orbitals",{{{2,0},{6,0}}}))};
            orbitalCollection=IcohpCollection("1","O5","Ta2",1.99474, ...
                {[0,0,-1]},1,{struct("up",.29324,"down",.29324)}, ...
                true,"list_orb_icohp",orbitalData,"are_cobis",true);
            testCase.verifyEqual(orbitalCollection.get_icohp_by_label( ...
                "1",true,"up","2s-6s"),.0494,AbsTol=1e-14);
            orbitalRestored=IcohpCollection.from_dict( ...
                orbitalCollection.as_dict());
            testCase.verifyEqual(orbitalRestored.get_icohp_by_label( ...
                "1",false,"down","2s-6s"),.0247,AbsTol=1e-14);
        end

