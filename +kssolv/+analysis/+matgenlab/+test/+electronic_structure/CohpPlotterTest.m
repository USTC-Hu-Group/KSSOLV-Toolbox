            testCase.verifyNumElements(joined.distances,2);
            testCase.verifyNumElements(joined.distances{1},144);
            ax=plotter.get_plot();testCase.verifyTrue(isgraphics(ax,"axes"));
            close(ancestor(ax,"figure"));

            dos=kssolv.analysis.matgenlab.electronic_structure.CompleteDos. ...
                from_dict(jsondecode(fileread(fullfile(root,"dos", ...
                "complete_dos.json"))));
