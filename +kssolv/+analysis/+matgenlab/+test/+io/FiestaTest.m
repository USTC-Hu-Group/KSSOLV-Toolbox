function path = fiestaFixture(name)
path = fullfile(fileparts(mfilename("fullpath")), ...
    "+fixtures", "+fiesta", name);
end

function output = nwchemExecutor(program, commandArguments, ~)
assert(program == "NWCHEM2FIESTA");
assert(isequal(commandArguments, ...
    ["methane.nw", "methane.nwout", "methane.movecs"]));
output = struct("stdout", "converted", "status", 0);
end

function output = runnerExecutor(program, commandArguments, ~)
output = program + "|" + strjoin(commandArguments, ",");
end

function output = failedExecutor(~, ~, ~)
output = struct("stdout", "failed", "status", 7);
end

function writeText(path, value)
[identifier, message] = fopen(path, "w", "n", "UTF-8");
assert(identifier >= 0, message);
cleanup = onCleanup(@() fclose(identifier));
fwrite(identifier, char(string(value)), "char");
clear cleanup
end

function deleteFiles(paths)
for path = string(paths)
    if isfile(path), delete(path); end
end
end

function removeTree(path)
if isfolder(path), rmdir(path, "s"); end
end

function names = metadataNames(values)
if iscell(values), values = [values{:}]; end
names = string({values.Name});
end
