        function nwchemRunnerRequiresAndUsesExplicitExecutor(testCase)
            folder = string(tempname);
            mkdir(folder);
            cleanup = onCleanup(@() removeTree(folder));
            runner = ...
                kssolv.analysis.matgenlab.io.fiesta.Nwchem2Fiesta( ...
                folder, "methane", "convert.log");
            testCase.verifyError(@() runner.run(), ...
                "KSSOLV:Matgenlab:Fiesta:ExecutorRequired");
            runner.executor = @nwchemExecutor;
            runner.run();
            testCase.verifyEqual(string(fileread( ...
                fullfile(folder, "convert.log"))), "converted");
            value = runner.as_dict();
            testCase.verifyEqual(fieldnames(value), ...
                {'x_module'; 'x_class'; 'filename'; 'folder'});
            restored = ...
                kssolv.analysis.matgenlab.io.fiesta.Nwchem2Fiesta. ...
                from_dict(value);
            testCase.verifyEqual(restored.log_file, "log_n2f");
            decoded = kssolv.analysis.matgenlab.util.decode( ...
                runner.toJSON());
            testCase.verifyClass(decoded, ...
                "kssolv.analysis.matgenlab.io.fiesta.Nwchem2Fiesta");
            clear cleanup
        end

        function fiestaRunnerGwBseMSONAndErrors(testCase)
            folder = string(tempname);
            mkdir(folder);
            cleanup = onCleanup(@() removeTree(folder));
            gw = kssolv.analysis.matgenlab.io.fiesta.FiestaRun( ...
                folder, [2, 2, 2], "gw.log", @runnerExecutor);
            gw.run();
            testCase.verifyEqual(gw.mpi_procs, 8);
            testCase.verifyEqual(string(fileread( ...
                fullfile(folder, "gw.log"))), ...
                "mpirun|-n,8,fiesta,2,2,2");
            bse = kssolv.analysis.matgenlab.io.fiesta.FiestaRun( ...
                folder, [2, 2], "bse.log", @runnerExecutor);
            testCase.verifyError(@() bse.bse_run(), ...
                "KSSOLV:Matgenlab:Fiesta:MPIProcsUnset");
            bse.run();
            testCase.verifyEqual(bse.mpi_procs, 4);
            testCase.verifyEqual(string(fileread( ...
                fullfile(folder, "bse.log"))), ...
                "mpirun|-n,4,bse,2,2");
            restored = ...
                kssolv.analysis.matgenlab.io.fiesta.FiestaRun. ...
                from_dict(gw.as_dict());
            testCase.verifyEqual(restored.grid, [2, 2, 2]);
            decoded = kssolv.analysis.matgenlab.util.decode(gw.toJSON());
            testCase.verifyClass(decoded, ...
                "kssolv.analysis.matgenlab.io.fiesta.FiestaRun");

            invalid = ...
                kssolv.analysis.matgenlab.io.fiesta.FiestaRun( ...
                folder, 2, "bad.log", @runnerExecutor);
            testCase.verifyError(@() invalid.run(), ...
                "KSSOLV:Matgenlab:Fiesta:GridSize");
            failed = ...
                kssolv.analysis.matgenlab.io.fiesta.FiestaRun( ...
                folder, [1, 1, 1], "bad.log", @failedExecutor);
            testCase.verifyError(@() failed.run(), ...
                "KSSOLV:Matgenlab:Fiesta:ExecutorFailed");
            clear cleanup
        end
    end
end

