classdef FiestaTest < matlab.unittest.TestCase
    % Frozen pymatgen 2026.5.4 oracle tests for pymatgen.io.fiesta.

    methods (Test)
        function frozenInventorySurfaceIsImplemented(testCase)
            ledger = readtable(fullfile(KSSOLV_Toolbox.RootDirectory, ...
                "dev", "matgenlab", "inventory", ...
                "compatibility_ledger.csv"), TextType = "string", ...
                Delimiter = ",");
            rows = ledger(ledger.module == "pymatgen.io.fiesta", :);
            testCase.verifyEqual(height(rows), 28);
            testCase.verifyTrue(all(rows.status == "implemented"), ...
                join(rows.api_id(rows.status ~= "implemented"), newline));

            package = "kssolv.analysis.matgenlab.io.fiesta.";
            expected = struct( ...
                "Nwchem2Fiesta", ...
                    ["run", "as_dict", "from_dict"], ...
                "FiestaRun", ...
                    ["run", "bse_run", "as_dict", "from_dict"], ...
                "BasisSetReader", ...
                    ["set_n_nlmo", "infos_on_basis_set"], ...
                "FiestaInput", ...
                    ["set_auxiliary_basis_set", "set_gw_options", ...
                    "make_full_bse_densities_folder", ...
                    "set_bse_options", "dump_bse_data_in_gw_run", ...
                    "dump_tddft_data_in_gw_run", "write_file", ...
                    "as_dict", "from_dict", "from_str", "from_file"], ...
                "FiestaOutput", strings(1, 0), ...
                "BSEOutput", strings(1, 0));
            classes = fieldnames(expected);
            for index = 1:numel(classes)
                metadata = meta.class.fromName( ...
                    package + classes{index});
                testCase.verifyNotEmpty(metadata, classes{index});
                methods = metadataNames(metadata.MethodList);
                testCase.verifyTrue(all(ismember( ...
                    expected.(classes{index}), methods)), ...
                    classes{index});
            end
            metadata = meta.class.fromName(package + "FiestaInput");
            properties = metadataNames(metadata.PropertyList);
            testCase.verifyTrue(all(ismember( ...
                ["infos_on_system", "molecule"], properties)));
        end

        function fiestaInputExactFrozenTextAndRoundTrip(testCase)
            input = methaneInput();
            testCase.verifyEqual(string(input), frozenCellInput());
            testCase.verifyEqual(input.infos_on_system, ...
                frozenSystemInfo());
            restored = ...
                kssolv.analysis.matgenlab.io.fiesta.FiestaInput. ...
                from_str(string(input));
            testCase.verifyEqual(string(restored), string(input));
            testCase.verifyEqual(restored.GW_options.nc_corr, "10");
            testCase.verifyEqual(restored.cohsex_options.eigMethod, "C");
            testCase.verifyEqual(restored.molecule.cart_coords, ...
                input.molecule.cart_coords, AbsTol = 1e-15);

            scaledText = replace(string(input), ...
                "# scaling factor" + newline + "    1.000", ...
                "# scaling factor" + newline + "    2.000");
            scaled = ...
                kssolv.analysis.matgenlab.io.fiesta.FiestaInput. ...
                from_str(scaledText);
            testCase.verifyEqual(scaled.molecule.cart_coords, ...
                input.molecule.cart_coords, AbsTol = 1e-15);
        end

        function fiestaInputDefaultsAndMutatorsMatchOracle(testCase)
            input = methaneInput();
            input.set_gw_options();
            testCase.verifyEqual(input.GW_options, ...
                struct("nc_corr", 10, "nit_gw", 5, "nv_corr", 10));
            testCase.verifyEqual(input.correlation_grid, ...
                struct("dE_grid", .5, "n_grid", 6));
            input.set_bse_options();
            testCase.verifyEqual(input.bse_tddft_options.npsi_bse, 10);
            testCase.verifyEqual(input.bse_tddft_options.nit_bse, 200);
            input.dump_bse_data_in_gw_run(false);
            testCase.verifyEqual(input.bse_tddft_options.do_bse, 0);
            testCase.verifyEqual(input.bse_tddft_options.do_tddft, 0);
            input.dump_tddft_data_in_gw_run(false);
            testCase.verifyEqual(input.bse_tddft_options.do_bse, "0");
            testCase.verifyEqual(input.bse_tddft_options.do_tddft, "0");
            input.dump_tddft_data_in_gw_run();
            testCase.verifyEqual(input.bse_tddft_options.do_tddft, "1");
        end

        function fiestaSystemInfoAlternateBranchesMatchOracle(testCase)
            input = methaneInput();
            exc = input.Exc_DFT_option;
            exc.rdVxcpsi = "0";
            input.Exc_DFT_option = exc;
            cohsex = input.cohsex_options;
            cohsex.eigMethod = "HF";
            cohsex.nv_cohsex = "2";
            cohsex.nc_cohsex = "3";
            cohsex.nit_cohsex = "4";
            input.cohsex_options = cohsex;
            dumps = input.bse_tddft_options;
            dumps.do_bse = "0";
            dumps.do_tddft = "1";
            input.bse_tddft_options = dumps;
            info = input.infos_on_system;
            testCase.verifyTrue(contains(info, ...
                "' Exchange and correlation energy re-computed'"));
            testCase.verifyTrue(contains(info, ...
                "' Correcting  2 valence bands and  3 conduction bands at HF level'"));
            testCase.verifyTrue(contains(info, ...
                "' Performing   4 diagonal HF iterations'"));
            testCase.verifyFalse(contains(info, ...
                "Dumping data for BSE treatment"));
            testCase.verifyTrue(contains(info, ...
                "' Dumping data for TD-DFT treatment'"));
        end

        function fiestaInputDictionaryUsesFrozenKeysAndError(testCase)
            input = methaneInput();
            value = input.as_dict();
            testCase.verifyEqual(fieldnames(value), ...
                {'mol'; 'correlation_grid'; 'Exc_DFT_option'; ...
                'COHSEX_options'; 'GW_options'; 'BSE_TDDFT_options'});
            testCase.verifyError(@() ...
                kssolv.analysis.matgenlab.io.fiesta.FiestaInput. ...
                from_dict(value), ...
                "KSSOLV:Matgenlab:Fiesta:FrozenFromDictKey");
            value.geometry_options = value.COHSEX_options;
            value.symmetry_options = value.GW_options;
            value.memory_options = value.BSE_TDDFT_options;
            restored = ...
                kssolv.analysis.matgenlab.io.fiesta.FiestaInput. ...
                from_dict(value);
            testCase.verifyEqual(string(restored), string(input));
            decoded = jsondecode(input.toJSON());
            testCase.verifyEqual(string(decoded.GW_options.nc_corr), "10");
        end

        function fiestaInputFilesCompressionAndParseErrors(testCase)
            input = methaneInput();
            paths = [string(tempname) + ".cell.in", ...
                string(tempname) + ".cell.in.gz"];
            cleanup = onCleanup(@() deleteFiles(paths));
            for path = paths
                input.write_file(path);
                restored = ...
                    kssolv.analysis.matgenlab.io.fiesta.FiestaInput. ...
                    from_file(path);
                testCase.verifyEqual(string(restored), string(input));
            end
            unsupported = string(tempname) + ".xz";
            testCase.verifyError(@() input.write_file(unsupported), ...
                "KSSOLV:Matgenlab:Fiesta:CompressionUnsupported");
            testCase.verifyError(@() ...
                kssolv.analysis.matgenlab.io.fiesta.FiestaInput. ...
                from_str("not a cell.in"), ...
                "KSSOLV:Matgenlab:Fiesta:Parse");
            clear cleanup
        end

        function auxiliaryBasisAndDensityFolderSemantics(testCase)
            input = methaneInput();
            destination = string(tempname);
            mkdir(destination);
            cleanup = onCleanup(@() removeTree(destination));
            input.set_auxiliary_basis_set(destination, ...
                fiestaFixture(""));
            testCase.verifyEqual(strtrim(string(fileread( ...
                fullfile(destination, "C2.ion")))), ...
                "C auxiliary oracle");
            testCase.verifyEqual(strtrim(string(fileread( ...
                fullfile(destination, "H2.ion")))), ...
                "H auxiliary oracle");

            root = string(tempname);
            mkdir(root);
            rootCleanup = onCleanup(@() removeTree(root));
            testCase.verifyEqual( ...
                kssolv.analysis.matgenlab.io.fiesta.FiestaInput. ...
                make_full_bse_densities_folder(root), ...
                "makedirs FULL_BSE_Densities folder");
            testCase.verifyError(@() ...
                kssolv.analysis.matgenlab.io.fiesta.FiestaInput. ...
                make_full_bse_densities_folder(root), ...
                "KSSOLV:Matgenlab:Fiesta:FileExists");

            fileRoot = string(tempname);
            mkdir(fileRoot);
            fileCleanup = onCleanup(@() removeTree(fileRoot));
            writeText(fullfile(fileRoot, "FULL_BSE_Densities"), "x");
            testCase.verifyEqual( ...
                kssolv.analysis.matgenlab.io.fiesta.FiestaInput. ...
                make_full_bse_densities_folder(fileRoot), ...
                "FULL_BSE_Densities folder already exists");
            clear cleanup rootCleanup fileCleanup
        end

