        function polymerAndExternalSeams(testCase)
            head = readXYZ(fullfile(testCase.fixtureFolder, ...
                "peo_head.xyz"));
            bulk = readXYZ(fullfile(testCase.fixtureFolder, ...
                "peo_bulk.xyz"));
            tail = readXYZ(fullfile(testCase.fixtureFolder, ...
                "peo_tail.xyz"));
            polymer = kssolv.analysis.matgenlab.io.lammps.Polymer( ...
                head, 0, 5, bulk, 0, 4, tail, 0, 4, 5, ...
                1.5075, true);
            testCase.verifyEqual(polymer.molecule.num_sites, ...
                head.num_sites + 3 * bulk.num_sites + tail.num_sites);

            runner = kssolv.analysis.matgenlab.io.lammps. ...
                LammpsRunner("in.test", "lmp -sf omp");
            testCase.verifyError(@() runner.run(), ...
                "KSSOLV:Matgenlab:LammpsRunner:ExecutorRequired");
            runner = kssolv.analysis.matgenlab.io.lammps. ...
                LammpsRunner("in.test", "lmp -sf omp", ...
                @successfulLammps);
            [stdout, stderr] = runner.run();
            testCase.verifyEqual(string(char(stdout)), "LAMMPS done");
            testCase.verifyEmpty(stderr);

            params = {struct("number", 1, ...
                "fixed", [0, 0, 0, 0, 0, 0])};
            packmol = kssolv.analysis.matgenlab.io.lammps. ...
                PackmolRunner({head}, params, "pack.inp", 2, ...
                "xyz", struct("maxit", 20), false, ...
                "packed.xyz", "packmol", @successfulPackmol);
            old = pwd;
            folder = string(tempname);
            mkdir(folder);
            cleanup = onCleanup(@() restoreAndRemove(old, folder));
            cd(folder);
            packed = packmol.run();
            testCase.verifyEqual(packed.num_sites, 1);
            testCase.verifyEqual(packed.sites{1}.specie.symbol, "H");

            atom = struct("atomicnum", 8, "coords", [1, 2, 3]);
            converted = packmol.convert_obatoms_to_molecule(atom);
            testCase.verifyEqual(converted.formula, "O1");
            pdbPath = fullfile(folder, "one.pdb");
            marked = kssolv.analysis.matgenlab.core.Molecule( ...
                "H", [0, 0, 0], site_properties = ...
                struct("ff_map", {{"h1"}}));
            pdbRunner = kssolv.analysis.matgenlab.io.lammps. ...
                PackmolRunner({marked}, {struct("number", 1)}, ...
                "pack.inp", 2, "pdb", struct(), false, ...
                "one.pdb", "packmol");
            pdbRunner.write_pdb(marked, pdbPath, "ml1", 1);
            restored = pdbRunner.restore_site_properties( ...
                "ff_map", pdbPath);
            testCase.verifyEqual(restored.num_sites, 1);
            testCase.verifyEqual(string( ...
                restored.site_properties.ff_map{1}), "h1");
            nativePacked = kssolv.analysis.matgenlab.io. ...
                lammps.PackmolRunner({head}, params, "native.pack.inp", ...
                2, "xyz", struct("maxit", 1, "nloop", 1), false, ...
                "native-packed.xyz").run();
            testCase.verifyEqual(nativePacked.num_sites, head.num_sites);
            clear cleanup
            cd(old);
        end
    end
end

function molecule = readXYZ(path)
lines = splitlines(string(fileread(path)));
n = str2double(lines(1));
species = strings(n, 1);
coords = zeros(n, 3);
for index = 1:n
    fields = split(strtrim(lines(index + 2)));
    species(index) = fields(1);
    coords(index, :) = str2double(fields(2:4));
end
molecule = kssolv.analysis.matgenlab.core.Molecule(species, coords);
end

function result = successfulLammps(request)
assert(request.command == "lmp -sf omp");
assert(isequal(request.args, ["-in", "in.test"]));
result = struct("status", 0, "stdout", "LAMMPS done", ...
    "stderr", "");
end

function result = successfulPackmol(request)
assert(request.command == "packmol");
assert(contains(request.stdin, "structure"));
result = struct("status", 0, "stdout", "PACKMOL done", ...
    "stderr", "", "output_text", ...
    "1" + newline + "packed" + newline + "H 0 0 0" + newline);
end

function deleteIfPresent(path)
if isfile(path), delete(path); end
end

function removeFolder(folder)
if isfolder(folder), rmdir(folder, "s"); end
end

function restoreAndRemove(old, folder)
cd(old);
removeFolder(folder);
end
