    methods (Test)
        function boxAndDataMatchOfficialValues(testCase)
            box = kssolv.analysis.matgenlab.io.lammps.LammpsBox( ...
                [0, 4.9134; 0, 4.255129; 0, 5.4052], ...
                [-2.4567, 0, 0]);
            testCase.verifyEqual(box.volume, 113.007331, ...
                "AbsTol", 1e-6);
            testCase.verifyEqual(string(box.get_str(4)), ...
                "0.0000 4.9134  xlo xhi" + newline + ...
                "0.0000 4.2551  ylo yhi" + newline + ...
                "0.0000 5.4052  zlo zhi" + newline + ...
                "-2.4567 0.0000 0.0000  xy xz yz");
            testCase.verifyEqual(box.get_box_shift([0, 1, -1]), ...
                [-2.4567, 4.255129, -5.4052], "AbsTol", 1e-12);
            testCase.verifyEqual(box.to_lattice().matrix, ...
                [4.9134, 0, 0; -2.4567, 4.255129, 0; ...
                0, 0, 5.4052], "AbsTol", 1e-12);

            lattice = kssolv.analysis.matgenlab.core.Lattice( ...
                [3, 0, 0; 1, 4, 0; 0.5, 0.25, 5]);
            [converted, operation] = ...
                kssolv.analysis.matgenlab.io.lammps. ...
                lattice_2_lmpbox(lattice, [1, 2, 3]);
            testCase.verifyEqual(converted.bounds(:, 1), [1; 2; 3]);
            testCase.verifyEqual(abs(det(operation.rotation_matrix)), 1, ...
                "AbsTol", 1e-12);

            filename = fullfile(testCase.fixtureFolder, "li.data");
            data = kssolv.analysis.matgenlab.io.lammps.LammpsData. ...
                from_file(filename);
            testCase.verifyEqual(data.atom_style, "full");
            testCase.verifyEqual(data.box.bounds, ...
                [-1, 54; -1, 54; -1, 54]);
            testCase.verifyEqual(data.masses.mass, 6.94, ...
                "AbsTol", 1e-12);
            testCase.verifyEqual(data.atoms{1, :}, ...
                [1, 1, 1, 16.0126, 34.0688, 37.8399], ...
                "AbsTol", 1e-12);
            testCase.verifyEqual(data.structure.num_sites, 1);
            data = data.set_charge_atom(struct("x1", -0.25));
            testCase.verifyEqual(data.atoms.q, -0.25);
            data = data.set_charge_atom_type(struct("x1", 0.5));
            testCase.verifyEqual(data.atoms.q, 0.5);
            text = data.get_str();
            testCase.verifySubstring(text, "Generated by " + ...
                "pymatgen.io.lammps.data.LammpsData");

            out = tempname + ".data";
            cleanup = onCleanup(@() deleteIfPresent(out));
            data.write_file(out);
            roundTrip = kssolv.analysis.matgenlab.io.lammps. ...
                LammpsData.from_file(out);
            testCase.verifyEqual(roundTrip.atoms.q, 0.5);
            [outBox, outForceField, outTopologies] = data.disassemble();
            testCase.verifyClass(outBox, ...
                "kssolv.analysis.matgenlab.io.lammps.LammpsBox");
            testCase.verifyClass(outForceField, ...
                "kssolv.analysis.matgenlab.io.lammps.ForceField");
            testCase.verifyNumElements(outTopologies, 1);
            clear cleanup
        end

        function topologyForceFieldAndConstructors(testCase)
            molecule = kssolv.analysis.matgenlab.core.Molecule( ...
                ["H", "O", "H"], ...
                [-0.75, 0, 0; 0, 0, 0; 0.75, 0, 0], ...
                site_properties = struct("charge", ...
                {{0.4; -0.8; 0.4}}));
            topology = kssolv.analysis.matgenlab.io.lammps.Topology. ...
                from_bonding(molecule);
            testCase.verifyEqual(size(topology.topologies.Bonds), [2, 2]);
            testCase.verifyEqual(size(topology.topologies.Angles), [1, 3]);

            coefficients = struct();
            coefficients.Bond_Coeffs = {struct( ...
                "coeffs", [450, 0.96], ...
                "types", {{{"H", "O"}}})};
            forceField = kssolv.analysis.matgenlab.io.lammps.ForceField( ...
                {"H", "H"; "O", "O"}, [0.1, 2; 0.2, 3], ...
                coefficients);
            testCase.verifyEqual(forceField.masses.mass, ...
                [1.00794; 15.9994], "AbsTol", 1e-4);
            dict = forceField.asDict();
            restored = kssolv.analysis.matgenlab.io.lammps.ForceField. ...
                from_dict(dict);
            testCase.verifyEqual(restored.masses.mass, ...
                forceField.masses.mass);
            path = tempname + ".json";
            cleanup = onCleanup(@() deleteIfPresent(path));
            forceField.to_file(path);
            loaded = kssolv.analysis.matgenlab.io.lammps.ForceField. ...
                from_file(path);
            testCase.verifyEqual(loaded.masses.mass, ...
                forceField.masses.mass);

            box = kssolv.analysis.matgenlab.io.lammps.LammpsBox( ...
                [0, 10; 0, 10; 0, 10]);
            bondTopology = kssolv.analysis.matgenlab.io.lammps. ...
                Topology.from_bonding(molecule, true, false, false);
            assembled = kssolv.analysis.matgenlab.io.lammps. ...
                LammpsData.from_ff_and_topologies(box, forceField, ...
                {bondTopology});
            testCase.verifyEqual(height(assembled.atoms), 3);
            testCase.verifyEqual(height(assembled.topology("Bonds")), 2);
            fromMolecule = kssolv.analysis.matgenlab.io.lammps. ...
                LammpsData.from_molecule(molecule, box);
            testCase.verifyEqual(height(fromMolecule.atoms), 3);
            fromStructure = kssolv.analysis.matgenlab.io.lammps. ...
                LammpsData.from_structure(fromMolecule.structure);
            testCase.verifyEqual(height(fromStructure.atoms), 3);

            legacyForceField = kssolv.analysis.matgenlab.io.lammps. ...
                LammpsForceField(pair_style = "lj/cut 8", ...
                pair_coeff = ["1 1 0.1 2", "2 2 0.2 3"], ...
                species = ["H", "O"]);
            legacyDict = legacyForceField.as_dict();
            legacyRoundTrip = kssolv.analysis.matgenlab.io.lammps. ...
                LammpsForceField.from_dict(legacyDict);
            testCase.verifyEqual(legacyRoundTrip.pair_style, ...
                "lj/cut 8");
            testCase.verifyEqual(string(legacyRoundTrip.species), ...
                ["H", "O"]);
            clear cleanup
        end

        function combinedDataBoundariesAndConversions(testCase)
            base = kssolv.analysis.matgenlab.io.lammps.LammpsData. ...
                from_file(fullfile(testCase.fixtureFolder, ...
                "li.data"));
            xyz = table(["Li"; "Li"], [0; 2], [0; 2], [0; 2], ...
                'VariableNames', {'atom', 'x', 'y', 'z'});
            combined = kssolv.analysis.matgenlab.io.lammps. ...
                CombinedData.from_lammpsdata({base}, "Li+", 2, xyz);
            testCase.verifyEqual(combined.names, "Li_");
            testCase.verifyEqual(height(combined.atoms), 2);
            testCase.verifySubstring(combined.get_str(), "# 2 Li_");
            testCase.verifyEqual(combined.structure.num_sites, 2);
            plain = combined.as_lammpsdata();
            testCase.verifyClass(plain, ...
                "kssolv.analysis.matgenlab.io.lammps.LammpsData");
            testCase.verifyNumElements(combined.disassemble(), 1);
            parsed = kssolv.analysis.matgenlab.io.lammps. ...
                CombinedData.parse_xyz(fullfile(testCase.fixtureFolder, ...
                "cocktail.xyz"));
            testCase.verifyEqual(height(parsed), 54);
            coordinatePath = tempname + ".xyz";
            cleanup = onCleanup(@() deleteIfPresent(coordinatePath));
            fid = fopen(coordinatePath, "w");
            fprintf(fid, "1\nLi\nLi 0 0 0\n");
            fclose(fid);
            loaded = kssolv.analysis.matgenlab.io.lammps. ...
                CombinedData.from_files(coordinatePath, 1, ...
                fullfile(testCase.fixtureFolder, "li.data"));
            testCase.verifyEqual(height(loaded.atoms), 1);
            testCase.verifyError(@() kssolv.analysis.matgenlab.io. ...
                lammps.CombinedData.from_structure(), ...
                "KSSOLV:Matgenlab:CombinedData:Unsupported");
            testCase.verifyError(@() kssolv.analysis.matgenlab.io. ...
                lammps.CombinedData.from_ff_and_topologies(), ...
                "KSSOLV:Matgenlab:CombinedData:Unsupported");
            clear cleanup
        end

        function inputFileFullSurfaceMatchesOfficialFixture(testCase)
            cls = kssolv.analysis.matgenlab.io.lammps.LammpsInputFile;
            input = cls.from_file(fullfile(testCase.fixtureFolder, ...
                "lgps.in"));
            testCase.verifyEqual(input.nstages, 1);
            testCase.verifyEqual(input.ncomments, 3);
            testCase.verifyEqual(input.stages_names, "Stage 1");
            testCase.verifyEqual(string(input.get_args("units")), "metal");
            testCase.verifyNumElements(input.get_args("set"), 4);
            testCase.verifyTrue(input.contains_command("pair_coeff"));
            input = input.set_args("units", "atomic", [], "first");
            testCase.verifyEqual(string(input.get_args("units")), ...
                "atomic");
            input = input.add_stage([], "run 10", "Run");
            input = input.add_commands("Run", ["thermo 2", "write_data out"]);
            input = input.rename_stage("Run", "Production");
            testCase.verifyEqual(input.nstages, 2);
            input = input.merge_stages(["Stage 1", "Production"]);
            testCase.verifyEqual(input.nstages, 1);
            other = cls.from_str("units real" + newline + ...
                "atom_style full");
            input = input.append(other);
            testCase.verifyEqual(input.nstages, 2);
            input = input.remove_command("units", "Stage 2", false);
            input = input.remove_stage("Stage 2");
            text = input.get_str(false, true);
            reparsed = cls.from_str(text, false, true);
            testCase.verifyGreaterThan(reparsed.nstages, 0);
            path = tempname + ".in";
            cleanup = onCleanup(@() deleteIfPresent(path));
            input.write_file(path);
            testCase.verifyTrue(isfile(path));
            clear cleanup
        end

        function legacyInputGeneratorsAndSet(testCase)
            data = kssolv.analysis.matgenlab.io.lammps.LammpsData. ...
                from_file(fullfile(testCase.fixtureFolder, ...
                "li.data"));
            template = "units ${units}" + newline + ...
                "atom_style full" + newline + ...
                "read_data system.data";
            generator = kssolv.analysis.matgenlab.io.lammps. ...
                BaseLammpsGenerator(template = template, data = data, ...
                settings = struct("units", "metal"));
            inputSet = generator.get_input_set(data);
            testCase.verifyClass(inputSet, ...
                "kssolv.analysis.matgenlab.io.lammps.LammpsInputSet");
            testCase.verifyEqual(string( ...
                inputSet.inputfile.get_args("units")), "metal");

            minimization = kssolv.analysis.matgenlab.io.lammps. ...
                LammpsMinimization([], "real", "full", 3, "f f f", ...
                "system.data", "pair_style lj/cut 8");
            testCase.verifyEqual(minimization.units, "real");
            testCase.verifyEqual(minimization.atom_style, "full");
            testCase.verifyEqual(minimization.dimension, 3);
            testCase.verifyEqual(minimization.boundary, "f f f");
            testCase.verifyEqual(minimization.read_data, "system.data");
            testCase.verifyEqual(minimization.force_field, ...
                "pair_style lj/cut 8");
            generated = minimization.get_input_set(data);
            testCase.verifyEqual(generated.calc_type, "minimization");

            settings = kssolv.analysis.matgenlab.io.lammps. ...
                LammpsSettings(struct("units", "metal", ...
                "atom_style", "full"));
            settings.update(struct("dimension", 3, "ensemble", "nvt"));
            roundTrip = kssolv.analysis.matgenlab.io.lammps. ...
                LammpsSettings.from_dict(settings.as_dict());
            testCase.verifyEqual(roundTrip.dimension, 3);

            setGenerator = kssolv.analysis.matgenlab.io.lammps. ...
                BaseLammpsSetGenerator(settings = struct( ...
                "atom_style", "full", "ensemble", "nvt"));
            setGenerator.update_settings(struct("nsteps", 7));
            generated = setGenerator.get_input_set(data);
            testCase.verifyEqual(generated.data, data);

            templatePath = fullfile(fileparts(which(class(minimization))), ...
                "templates", "minimization.template");
            legacy = kssolv.analysis.matgenlab.io.lammps. ...
                LammpsTemplateGen().get_input_set(templatePath, ...
                struct("units", "metal", "atom_style", "full", ...
                "dimension", 3, "boundary", "p p p", ...
                "read_data", "system.data", ...
                "force_field", "pair_style zero 10"));
            testCase.verifyTrue(isstruct(legacy));
        end

        function runWriterAndInputSetDirectory(testCase)
            data = kssolv.analysis.matgenlab.io.lammps.LammpsData. ...
                from_file(fullfile(testCase.fixtureFolder, ...
                "li.data"));
            folder = string(tempname);
            mkdir(folder);
            cleanup = onCleanup(@() removeFolder(folder));
            script = "units metal" + newline + ...
                "atom_style full" + newline + ...
                "read_data system.data";
            kssolv.analysis.matgenlab.io.lammps.write_lammps_inputs( ...
                folder, script, struct(), data);
            testCase.verifyTrue(isfile(fullfile(folder, "system.data")));

            run = kssolv.analysis.matgenlab.io.lammps.LammpsRun.md( ...
                data, "pair_style zero 10", 300, 5, struct());
            run.write_inputs(folder);
            testCase.verifyTrue(isfile(fullfile(folder, "in.md")));

            set = kssolv.analysis.matgenlab.io.lammps.LammpsInputSet. ...
                from_directory(folder);
            testCase.verifyEqual(string(set.calc_type), "read_from_dir");
            testCase.verifyError(@() set.validate(), ...
                "KSSOLV:Matgenlab:LammpsInputSet:NotImplemented");
            clear cleanup
        end

