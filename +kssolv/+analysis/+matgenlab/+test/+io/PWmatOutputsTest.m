        function officialDosSpinMatchesFrozenOracle(testCase)
            dos = kssolv.analysis.matgenlab.io.pwmat.DosSpin( ...
                pwmatOutputFixture("DOS.spinup_projected"));
            expectedLabels = ["Energy", "Total", "Cr-3S", "Cr-3Pz", ...
                "Cr-3Px", "Cr-3Py", "Cr-4S", "Cr-3Dz2", ...
                "Cr-3Dxz", "Cr-3Dyz", "Cr-3D(x^2-y^2)", ...
                "Cr-3Dxy", "I-4Dz2", "I-4Dxz", "I-4Dyz", ...
                "I-4D(x^2-y^2)", "I-4Dxy", "I-5S", ...
                "I-5Pz", "I-5Px", "I-5Py"];
            testCase.verifyEqual(dos.labels, expectedLabels);
            testCase.verifySize(dos.dos, [20, 21]);
            testCase.verifyEqual(dos.dos(1, :), ...
                [-1.3461, zeros(1, 20)], AbsTol = 1e-15);
            testCase.verifyEqual(dos.dos(end, :), ...
                [-.93765, 2.6331, 3.3024e-9, 1.0313e-7, ...
                3.8272e-7, 3.8138e-7, .00099164, .0034258, ...
                .576, .44439, .39186, .31456, 5.6428e-8, ...
                8.1113e-7, 8.9247e-7, 4.3818e-7, 3.785e-7, ...
                .0022301, .03783, .47422, .38761], ...
                AbsTol = 1e-15);
            testCase.verifyEqual(dos.get_partial_dos("total").', ...
                [0, 0, 0, .34071, 3.144, 12.168, 20.942, ...
                21.697, 22.704, 23.745, 19.62, 10.324, 4.4444, ...
                3.6435, 3.3347, 5.8741, 10.835, 10.815, ...
                5.6892, 2.6331], AbsTol = 1e-12);
            testCase.verifyError(@() dos.get_partial_dos("missing"), ...
                "KSSOLV:Matgenlab:PWmat:PartialDos");
            restored = kssolv.analysis.matgenlab.util.decode( ...
                dos.toJSON());
            testCase.verifyClass(restored, ...
                "kssolv.analysis.matgenlab.io.pwmat.DosSpin");
            testCase.verifyEqual(restored.dos, dos.dos);
        end

