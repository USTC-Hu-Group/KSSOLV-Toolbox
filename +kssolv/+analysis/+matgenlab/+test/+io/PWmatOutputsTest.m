classdef PWmatOutputsTest < matlab.unittest.TestCase
    % Frozen pymatgen 2026.5.4 oracle tests for io.pwmat.outputs.

    methods (Test)
        function frozenInventorySurfaceIsImplemented(testCase)
            ledger = readtable(fullfile(KSSOLV_Toolbox.RootDirectory, ...
                "dev", "matgenlab", "inventory", ...
                "compatibility_ledger.csv"), TextType = "string", ...
                Delimiter = ",");
            rows = ledger(ledger.module == ...
                "pymatgen.io.pwmat.outputs", :);
            testCase.verifyEqual(height(rows), 20);
            testCase.verifyTrue(all(rows.status == "implemented"), ...
                join(rows.api_id(rows.status ~= "implemented"), newline));

            package = "kssolv.analysis.matgenlab.io.pwmat.";
            expectedProperties = struct( ...
                "Movement", ["atom_configs", "e_tots", "atom_forces", ...
                    "e_atoms", "virials"], ...
                "OutFermi", "e_fermi", ...
                "Report", ["spin", "n_kpoints", "n_bands", ...
                    "eigenvalues", "kpoints", "kpoints_weight", "hsps"], ...
                "DosSpin", ["labels", "dos"]);
            classes = fieldnames(expectedProperties);
            for index = 1:numel(classes)
                metadata = meta.class.fromName( ...
                    package + classes{index});
                testCase.verifyNotEmpty(metadata, classes{index});
                properties = metadataNames(metadata.PropertyList);
                testCase.verifyTrue(all(ismember( ...
                    expectedProperties.(classes{index}), properties)));
            end
            metadata = meta.class.fromName(package + "DosSpin");
            testCase.verifyTrue(ismember("get_partial_dos", ...
                metadataNames(metadata.MethodList)));
        end

        function officialMovementMatchesFrozenOracle(testCase)
            movement = ...
                kssolv.analysis.matgenlab.io.pwmat.Movement( ...
                pwmatInputFixture("MOVEMENT.lzma"));
            testCase.verifyEqual(movement.n_ionic_steps, 1);
            testCase.verifyEqual(movement.chunk_sizes, 382);
            testCase.verifyEqual(movement.chunk_starts, 0);
            testCase.verifyEqual(numel(movement.ionic_steps), 1);
            testCase.verifyEqual(fieldnames(movement.ionic_steps{1}), ...
                {'atom_config'; 'e_tot'; 'atom_forces'; ...
                'atom_energies'; 'virial'});
            testCase.verifyEqual(movement.e_tots, ...
                -357677.2281, AbsTol = 1e-8);
            testCase.verifySize(movement.atom_forces, [1, 72, 3]);
            testCase.verifyEqual( ...
                squeeze(movement.atom_forces(1, 1, :)).', ...
                [0.018471657903432, 0.012960423864921, ...
                -0.049977022608987], AbsTol = 1e-15);
            testCase.verifyEmpty(movement.e_atoms);
            testCase.verifySize(movement.virials, [1, 3, 3]);
            testCase.verifyEqual(squeeze(movement.virials(1, :, :)), ...
                [734.547, -0.240455, -0.24418; ...
                -0.240469, 734.396, -0.246855; ...
                -0.244205, -0.246843, 734.414], AbsTol = 1e-12);
            testCase.verifyClass(movement.atom_configs{1}, ...
                "kssolv.analysis.matgenlab.core.Structure");
            testCase.verifyEqual( ...
                movement.atom_configs{1}.num_sites, 72);
            testCase.verifyEqual(movement.atom_configs{1}.lattice.matrix, ...
                [10.863786, 0, 0; 0, 10.863786, 0; ...
                0, 0, 7.242524], AbsTol = 1e-12);
        end

        function movementMultiStepAliasingAndSkipMatchUpstream(testCase)
            text = ...
                kssolv.analysis.matgenlab.io.pwmat.PWmatIOUtils. ...
                read_text(pwmatInputFixture("MOVEMENT.lzma"));
            second = regexprep(text, ...
                '-0\.3576772281E\+06', '-0.1230000000E+03', "once");
            path = string(tempname) + ".MOVEMENT";
            cleanup = onCleanup(@() deleteFiles(path));
            kssolv.analysis.matgenlab.io.pwmat.PWmatIOUtils. ...
                write_text(path, text + second);

            movement = ...
                kssolv.analysis.matgenlab.io.pwmat.Movement(path);
            testCase.verifyEqual(movement.n_ionic_steps, 2);
            testCase.verifyEqual(movement.chunk_sizes, [382, 382]);
            testCase.verifyEqual(movement.chunk_starts, [0, 382]);
            testCase.verifyEqual(movement.e_tots, [-123, -123]);

            selected = ...
                kssolv.analysis.matgenlab.io.pwmat.Movement(path, 2, 1);
            testCase.verifyEqual(selected.n_ionic_steps, 2);
            testCase.verifyEqual(numel(selected.ionic_steps), 1);
            testCase.verifyEqual(selected.e_tots, -123);
            zeroOffset = ...
                kssolv.analysis.matgenlab.io.pwmat.Movement(path, 2, 0);
            testCase.verifyEqual(numel(zeroOffset.ionic_steps), 2);
            testCase.verifyEqual(zeroOffset.e_tots, [-123, -123]);
            clear cleanup
        end

        function movementMSONAndMissingSeparatorError(testCase)
            movement = ...
                kssolv.analysis.matgenlab.io.pwmat.Movement( ...
                pwmatInputFixture("MOVEMENT.lzma"));
            value = movement.asDict();
            testCase.verifyEqual(value.x_module, ...
                "pymatgen.io.pwmat.outputs");
            restored = kssolv.analysis.matgenlab.util.decode( ...
                movement.toJSON());
            testCase.verifyClass(restored, ...
                "kssolv.analysis.matgenlab.io.pwmat.Movement");
            testCase.verifyEqual(restored.e_tots, movement.e_tots);

            path = string(tempname) + ".MOVEMENT";
            cleanup = onCleanup(@() deleteFiles(path));
            kssolv.analysis.matgenlab.io.pwmat.PWmatIOUtils. ...
                write_text(path, "1 atoms" + newline);
            testCase.verifyError(@() ...
                kssolv.analysis.matgenlab.io.pwmat.Movement(path), ...
                "KSSOLV:Matgenlab:PWmat:MovementChunks");
            clear cleanup
        end

        function outFermiPlainGzipMSONAndErrors(testCase)
            path = pwmatOutputFixture("OUT.FERMI");
            output = ...
                kssolv.analysis.matgenlab.io.pwmat.OutFermi(path);
            testCase.verifyEqual(output.e_fermi, -2.359, ...
                AbsTol = 1e-15);
            gzipPath = string(tempname) + ".OUT.FERMI.gz";
            cleanup = onCleanup(@() deleteFiles(gzipPath));
            kssolv.analysis.matgenlab.io.pwmat.PWmatIOUtils. ...
                write_text(gzipPath, fileread(path));
            testCase.verifyEqual( ...
                kssolv.analysis.matgenlab.io.pwmat.OutFermi( ...
                gzipPath).e_fermi, -2.359);
            restored = kssolv.analysis.matgenlab.util.decode( ...
                output.toJSON());
            testCase.verifyClass(restored, ...
                "kssolv.analysis.matgenlab.io.pwmat.OutFermi");
            badPath = string(tempname) + ".OUT.FERMI";
            badCleanup = onCleanup(@() deleteFiles(badPath));
            kssolv.analysis.matgenlab.io.pwmat.PWmatIOUtils. ...
                write_text(badPath, "bad");
            testCase.verifyError(@() ...
                kssolv.analysis.matgenlab.io.pwmat.OutFermi(badPath), ...
                "KSSOLV:Matgenlab:PWmat:OutFermi");
            clear cleanup badCleanup
        end

