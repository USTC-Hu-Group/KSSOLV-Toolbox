            species = cellfun(@(site) string(site.specie), ...
                provider.sites);
            testCase.verifyEqual(species, reshape(string(oracle.species), ...
                1, []));
        end

        function airssMetadataMatchesOracle(testCase)
            oracle = testCase.oracle().coc;
            provider = kssolv.analysis.matgenlab.io.res.AirssProvider. ...
                from_file(testCase.fixture("coc-115925-9326-14.res"), ...
                "strict");
            run = provider.get_run_start_info();
            testCase.verifyEqual(string(run{1}, "yyyy-MM-dd"), ...
                string(oracle.run_date));
            testCase.verifyEqual(run{2}, string(oracle.run_path));
            testCase.verifyEqual(provider.get_castep_version(), ...
                string(oracle.castep_version));
            functional = provider.get_func_rel_disp();
            testCase.verifyEqual(string(functional), ...
                [string(oracle.functional), string(oracle.relativity), ...
                string(oracle.dispersion)]);
            cutoff = provider.get_cut_grid_gmax_fsbc();
            testCase.verifyEqual([cutoff{1:3}], ...
                reshape(oracle.cut_grid_gmax, 1, []), AbsTol = 1e-12);
            testCase.verifyEqual(cutoff{4}, string(oracle.fsbc));
            grid = provider.get_mpgrid_offset_nkpts_spacing();
            testCase.verifyEqual(grid{1}, reshape(oracle.mp_grid, 1, []));
            testCase.verifyEqual(grid{2}, reshape(oracle.mp_offset, 1, []));
            testCase.verifyEqual(grid{3}, oracle.nkpts);
            testCase.verifyEqual(grid{4}, oracle.spacing, AbsTol = 1e-12);
            airss = provider.get_airss_version();
            testCase.verifyEqual(airss{1}, string(oracle.airss_version));
            testCase.verifyEqual(string(airss{2}, "yyyy-MM-dd"), ...
                string(oracle.airss_date));
            potentials = provider.get_pspots();
            testCase.verifyEqual(potentials.Co, string(oracle.pspots.Co));
            testCase.verifyEqual(potentials.C, string(oracle.pspots.C));
        end

