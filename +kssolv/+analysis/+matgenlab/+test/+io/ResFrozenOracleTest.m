    %RESFROZENORACLETEST Static parity oracle for pymatgen.io.res.

    methods (Test)
        function frozenInventoryHasAllFortySevenApis(testCase)
            package = "kssolv.analysis.matgenlab.io.res.";
            classes = ["AirssTITL", "ResCELL", "Ion", "ResSFAC", ...
                "Res", "ResParseError", "ResError", "ResParser", ...
                "ResWriter", "ResProvider", "AirssProvider", "ResIO"];
            writer = ["string", "write"];
            base = ["from_str", "from_file", "rems", "lattice", ...
                "sites", "structure"];
            airss = ["from_str", "from_file", "get_run_start_info", ...
                "get_castep_version", "get_func_rel_disp", ...
                "get_cut_grid_gmax_fsbc", ...
                "get_mpgrid_offset_nkpts_spacing", ...
                "get_airss_version", "get_pspots", "seed", "pressure", ...
                "volume", "energy", "integrated_spin_density", ...
                "integrated_absolute_spin_density", ...
                "spacegroup_label", "appearances", "entry", "as_dict"];
            conversions = ["structure_from_str", "structure_from_file", ...
                "structure_to_str", "structure_to_file", ...
                "entry_from_str", "entry_from_file", "entry_to_str", ...
                "entry_to_file"];
            testCase.verifyEqual(numel(classes) + numel(writer) + ...
                numel(base) + numel(airss) + numel(conversions), 47);
            for name = classes
                testCase.verifyNotEmpty(meta.class.fromName(package + name));
            end
            testCase.verifyMembers(package + "ResWriter", writer);
            testCase.verifyMembers(package + "ResProvider", base);
            testCase.verifyMembers(package + "AirssProvider", airss);
            testCase.verifyMembers(package + "ResIO", conversions);
        end

        function recordsMatchFrozenFormatting(testCase)
            title = kssolv.analysis.matgenlab.io.res.AirssTITL( ...
                "seed", 1.234, 2.34567, -3.456789, 4, 5, "P1", 6);
            testCase.verifyEqual(string(title), ...
                "TITL seed 1.23 2.3457 -3.45679 4.000000 " + ...
                "5.000000 (P1) n - 6");
            cellRecord = kssolv.analysis.matgenlab.io.res.ResCELL( ...
                1, 2, 3, 4, 90, 100, 110);
            testCase.verifyEqual(string(cellRecord), ...
                "CELL 1.00000 2.00000 3.00000 4.00000 " + ...
                "90.00000 100.00000 110.00000");
            plain = kssolv.analysis.matgenlab.io.res.Ion( ...
                "C", 1, [0.1, 0.2, 0.3], 0.5);
            magnetic = kssolv.analysis.matgenlab.io.res.Ion( ...
                "Co", 2, [-0.1, 0, 1.1], 1, -1.4);
            testCase.verifyEqual(string(plain), ...
                "C      1  0.10000000 0.20000000 0.30000000 0.500000");
            testCase.verifyEqual(string(magnetic), ...
                "Co     2  -0.10000000 0.00000000 1.10000000 " + ...
                "1.000000 -1.40");
            sfac = kssolv.analysis.matgenlab.io.res.ResSFAC( ...
                ["C", "Co"], {plain, magnetic});
            testCase.verifyTrue(endsWith(string(sfac), "END" + newline));
            parsed = kssolv.analysis.matgenlab.io.res.Res( ...
                title, "note", cellRecord, sfac);
            restored = kssolv.analysis.matgenlab.io.res.Res. ...
                from_dict(parsed.as_dict());
            testCase.verifyEqual(string(restored), string(parsed));
        end

