        function writerAndResIOAreReversible(testCase)
            source = string(fileread( ...
                testCase.fixture("coc-115925-9326-14.res")));
            provider = kssolv.analysis.matgenlab.io.res.AirssProvider. ...
                from_str(source);
            structureText = ...
                kssolv.analysis.matgenlab.io.res.ResIO. ...
                structure_to_str(provider.structure);
            testCase.verifyTrue(startsWith(structureText, ...
                "TITL" + newline + "CELL 1.00000"));
            testCase.verifyTrue(endsWith(structureText, newline));
            structure = kssolv.analysis.matgenlab.io.res.ResIO. ...
                structure_from_str(structureText);
            testCase.verifyEqual(structure.frac_coords, ...
                provider.structure.frac_coords, AbsTol = 5e-9);

            entry = provider.entry;
            first = kssolv.analysis.matgenlab.io.res.ResIO. ...
                entry_to_str(entry);
            secondEntry = kssolv.analysis.matgenlab.io.res.ResIO. ...
                entry_from_str(first);
            second = kssolv.analysis.matgenlab.io.res.ResIO. ...
                entry_to_str(secondEntry);
            testCase.verifyEqual(second, first);
            testCase.verifyEqual(secondEntry.energy, entry.energy);
            testCase.verifyTrue(endsWith(first, newline));
        end

        function fileAndGzipIOAreEquivalent(testCase)
            provider = kssolv.analysis.matgenlab.io.res.ResProvider. ...
                from_file(testCase.fixture("coc-115925-9326-14.res"));
            plain = string(tempname) + ".res";
            compressed = string(tempname) + ".res.gz";
            entryFile = string(tempname) + "-entry.res";
            cleanup = onCleanup(@() testCase.removeFiles( ...
                [plain, compressed, entryFile]));
            kssolv.analysis.matgenlab.io.res.ResIO. ...
                structure_to_file(provider.structure, plain);
            kssolv.analysis.matgenlab.io.res.ResIO. ...
                structure_to_file(provider.structure, compressed);
            first = kssolv.analysis.matgenlab.io.res.ResIO. ...
                structure_from_file(plain);
            second = kssolv.analysis.matgenlab.io.res.ResIO. ...
                structure_from_file(compressed);
            testCase.verifyEqual(first.frac_coords, second.frac_coords, ...
                AbsTol = 1e-12);
            testCase.verifyEqual(first.lattice.matrix, ...
                second.lattice.matrix, AbsTol = 1e-12);
            airss = kssolv.analysis.matgenlab.io.res.AirssProvider. ...
                from_file(testCase.fixture("coc-115925-9326-14.res"));
            kssolv.analysis.matgenlab.io.res.ResIO. ...
                entry_to_file(airss.entry, entryFile);
            restoredEntry = kssolv.analysis.matgenlab.io.res.ResIO. ...
                entry_from_file(entryFile);
            testCase.verifyEqual(restoredEntry.energy, airss.energy);
            clear cleanup
        end

        function msonRoundTripsBothProviders(testCase)
            provider = kssolv.analysis.matgenlab.io.res.AirssProvider. ...
                from_file(testCase.fixture("coc-115925-9326-14.res"), ...
                "strict");
            verbose = provider.as_dict(true);
            testCase.verifyEqual(sort(string(fieldnames(verbose))), ...
                sort(["x_module"; "x_class"; "res"; "parse_rems"]));
            restored = kssolv.analysis.matgenlab.io.res.AirssProvider. ...
                from_dict(verbose);
            testCase.verifyEqual(restored.as_dict(true), verbose);
            decoded = jsondecode(char(provider.toJSON()));
            jsonRestored = ...
                kssolv.analysis.matgenlab.io.res.AirssProvider. ...
                from_dict(decoded);
            testCase.verifyEqual(jsonRestored.seed, provider.seed);
            testCase.verifyEqual(jsonRestored.structure.frac_coords, ...
                provider.structure.frac_coords, AbsTol = 1e-12);
            compact = provider.as_dict(false);
            testCase.verifyEqual(numel(fieldnames(compact)), 10);
            testCase.verifyEqual(compact.seed, provider.seed);
            base = kssolv.analysis.matgenlab.io.res.ResProvider. ...
                from_file(testCase.fixture("coc-115925-9326-14.res"));
            baseRoundTrip = ...
                kssolv.analysis.matgenlab.io.res.ResProvider. ...
                from_dict(base.as_dict());
            testCase.verifyEqual(baseRoundTrip.structure.frac_coords, ...
                base.structure.frac_coords, AbsTol = 1e-12);
        end

        function malformedAndStrictErrorsMatchContract(testCase)
            parser = kssolv.analysis.matgenlab.io.res.ResParser();
            testCase.verifyEqual(parser.line, 0);
            testCase.verifyError(@() ...
                kssolv.analysis.matgenlab.io.res.ResParser. ...
                parse_str("TITL" + newline + ...
                "CELL 1 2 3" + newline + "SFAC C" + newline + "END"), ...
                "KSSOLV:Matgenlab:ResParseError");
            testCase.verifyError(@() ...
                kssolv.analysis.matgenlab.io.res.ResParser. ...
                parse_str("CELL 1 1 1 1 90 90 90" + newline + ...
                "SFAC C" + newline + "C 1 0 0 0 1"), ...
                "KSSOLV:Matgenlab:ResParseError");
            bare = "TITL seed 0 1 -1 0 0" + newline + ...
                "CELL 1 1 1 1 90 90 90" + newline + ...
                "LATT -1" + newline + "SFAC H" + newline + ...
                "H 1 0 0 0 1" + newline + "END" + newline;
            gentle = kssolv.analysis.matgenlab.io.res.AirssProvider. ...
                from_str(bare);
            testCase.verifyEmpty(gentle.get_castep_version());
            strict = kssolv.analysis.matgenlab.io.res.AirssProvider. ...
                from_str(bare, "strict");
            testCase.verifyError(@() strict.get_castep_version(), ...
                "KSSOLV:Matgenlab:ResParseError");
            noTitle = erase(bare, "TITL seed 0 1 -1 0 0" + newline);
            testCase.verifyError(@() ...
                kssolv.analysis.matgenlab.io.res.AirssProvider. ...
                from_str(noTitle), "KSSOLV:Matgenlab:ResError");
            testCase.verifyError(@() ...
                kssolv.analysis.matgenlab.io.res.AirssProvider. ...
                from_str(bare, "invalid"), ...
                "KSSOLV:Matgenlab:AirssProvider:ParseMode");
        end
    end

    methods (Static, Access = private)
        function verifyMembers(className, expected)
            metadata = meta.class.fromName(className);
            available = [string({metadata.MethodList.Name}), ...
                string({metadata.PropertyList.Name})];
            if ~all(ismember(expected, available))
                error("KSSOLV:Matgenlab:ResTest:Inventory", ...
                    "Missing members in %s: %s", className, ...
                    strjoin(expected(~ismember(expected, available)), ", "));
            end
        end

        function value = fixture(name)
            here = fileparts(mfilename("fullpath"));
            value = fullfile(here, "+fixtures", "+res", name);
        end

        function value = oracle()
            value = jsondecode(fileread( ...
                kssolv.analysis.matgenlab.test.io. ...
                ResFrozenOracleTest.fixture("res_oracle.json")));
        end

        function removeFiles(files)
            for file = files
                if isfile(file), delete(file); end
            end
        end
    end
