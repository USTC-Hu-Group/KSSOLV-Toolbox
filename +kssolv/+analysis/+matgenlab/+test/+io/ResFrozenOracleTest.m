                "strict");
            testCase.verifyEqual(provider.seed, string(oracle.seed));
            testCase.verifyEqual(provider.pressure, oracle.pressure, ...
                AbsTol = 1e-12);
            testCase.verifyEqual(provider.volume, oracle.volume, ...
                AbsTol = 1e-12);
            testCase.verifyEqual(provider.energy, oracle.energy, ...
                AbsTol = 1e-10);
            testCase.verifyEqual(provider.integrated_spin_density, ...
                oracle.integrated_spin_density);
            testCase.verifyEqual( ...
                provider.integrated_absolute_spin_density, ...
                oracle.integrated_absolute_spin_density);
            testCase.verifyEqual(provider.spacegroup_label, ...
                string(oracle.spacegroup_label));
            testCase.verifyEqual(provider.appearances, oracle.appearances);
            testCase.verifyEqual(numel(provider.rems), oracle.rem_count);
            testCase.verifyEqual(provider.lattice.lengths, ...
                reshape(oracle.lengths, 1, []), AbsTol = 1e-10);
            testCase.verifyEqual(provider.lattice.angles, ...
                reshape(oracle.angles, 1, []), AbsTol = 1e-10);
            testCase.verifyEqual(provider.structure.num_sites, ...
                oracle.site_count);
            testCase.verifyEqual(provider.structure.frac_coords(1, :), ...
                reshape(oracle.first_frac_coords, 1, []), ...
