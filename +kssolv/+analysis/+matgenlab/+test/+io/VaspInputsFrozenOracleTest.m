        function officialIncarMatchesOracle(testCase)
            [folder, oracle] = testCase.fixture();
            incar = kssolv.analysis.matgenlab.io.vasp.Incar. ...
                from_file(fullfile(folder, "INCAR"));
            testCase.verifyEqual(incar.get_str(sort_keys = true), ...
                string(oracle.incar.sorted));
            testCase.verifyEqual(incar.get_str( ...
                sort_keys = true, pretty = true), ...
                string(oracle.incar.pretty));
            testCase.verifyEqual( ...
                kssolv.analysis.matgenlab.io.vasp.Incar. ...
                proc_val("LREAL", "Auto"), ...
                string(oracle.incar.proc.LREAL));
            testCase.verifyEqual( ...
                kssolv.analysis.matgenlab.io.vasp.Incar. ...
                proc_val("MAGMOM", "2*5.0 1*-1.0"), ...
                double(oracle.incar.proc.MAGMOM).');
            testCase.verifyEqual( ...
                kssolv.analysis.matgenlab.io.vasp.Incar. ...
                proc_val("LATTICE_CONSTRAINTS", "T F T"), ...
                logical(oracle.incar.proc.LATTICE_CONSTRAINTS).');
            restored = kssolv.analysis.matgenlab.io.vasp.Incar. ...
                from_dict(incar.as_dict());
            testCase.verifyEqual(restored, incar);
        end

