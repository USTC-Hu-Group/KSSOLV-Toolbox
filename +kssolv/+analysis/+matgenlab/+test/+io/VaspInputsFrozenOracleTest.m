        function allOfficialKpointsFilesMatchOracle(testCase)
            [folder, oracle] = testCase.fixture();
            names = ["KPOINTS","KPOINTS_auto","KPOINTS_band", ...
                "KPOINTS_cartesian","KPOINTS_explicit", ...
                "KPOINTS_explicit_tet","KPOINTS_gamma"];
