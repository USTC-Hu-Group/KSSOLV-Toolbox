                restored = kssolv.analysis.matgenlab.io.vasp.Kpoints. ...
                    from_dict(points.as_dict());
                testCase.verifyEqual(restored, points);
            end
        end

        function constructorFamilyMatchesOracle(testCase)
            [folder, oracle] = testCase.fixture();
            structure = kssolv.analysis.matgenlab.io.vasp.Poscar. ...
                from_file(fullfile(folder, "POSCAR"), ...
                check_for_potcar = false).structure;
            previous = warning("off", ...
                "KSSOLV:Matgenlab:Kpoints:KspacingPreferred");
            cleanup = onCleanup(@() warning(previous));
            pathData = struct();
            pathData.kpoints = struct("G",[0,0,0], ...
                "X",[0.5,0,0],"L",[0.5,0.5,0.5]);
            pathData.path = {{"G","X","L"}};
            ibz = struct("kpath", pathData);
            constructors = {
                "default", kssolv.analysis.matgenlab.io.vasp.Kpoints()
                "positional", kssolv.analysis.matgenlab.io.vasp.Kpoints( ...
                    "positional",0,"Monkhorst",[4,6,8],[0.5,0.5,0.5])
                "automatic", kssolv.analysis.matgenlab.io.vasp.Kpoints. ...
                    automatic(25)
                "gamma", kssolv.analysis.matgenlab.io.vasp.Kpoints. ...
                    gamma_automatic([3,5,7],[0.5,0,0])
                "monkhorst", kssolv.analysis.matgenlab.io.vasp.Kpoints. ...
                    monkhorst_automatic([4,6,8])
                "density", kssolv.analysis.matgenlab.io.vasp.Kpoints. ...
                    automatic_density(structure,1000)
                "gamma_density", ...
                    kssolv.analysis.matgenlab.io.vasp.Kpoints. ...
                    automatic_gamma_density(structure,1000)
                "density_vol", ...
                    kssolv.analysis.matgenlab.io.vasp.Kpoints. ...
                    automatic_density_by_vol(structure,64)
                "density_lengths", ...
                    kssolv.analysis.matgenlab.io.vasp.Kpoints. ...
                    automatic_density_by_lengths(structure,[20,30,40])
                "linemode", ...
                    kssolv.analysis.matgenlab.io.vasp.Kpoints. ...
                    automatic_linemode(20,ibz)
                };
            for index = 1:size(constructors, 1)
                name = constructors{index, 1};
                points = constructors{index, 2};
                testCase.verifyEqual(string(points), ...
                    string(oracle.kpoint_constructors.(name).string), ...
                    "Constructor output differs for " + name);
            end
            clear cleanup
        end

        function syntheticPotcarMetadataMatchesOracle(testCase)
            [~, oracle] = testCase.fixture();
            previous = warning("off", ...
                "KSSOLV:Matgenlab:UnknownPotcarWarning");
            cleanup = onCleanup(@() warning(previous));
            single = kssolv.analysis.matgenlab.io.vasp.PotcarSingle( ...
                testCase.syntheticPotcar());
            reference = oracle.potcar_single;
            testCase.verifyEqual(single.header, string(reference.header));
            testCase.verifyEqual(single.element, string(reference.element));
            testCase.verifyEqual(single.atomic_no, ...
                double(reference.atomic_no));
            testCase.verifyEqual(single.nelectrons, ...
                double(reference.nelectrons));
            testCase.verifyEqual(single.symbol, string(reference.symbol));
            testCase.verifyEqual(single.potential_type, ...
                string(reference.potential_type));
            testCase.verifyEqual(single.functional, ...
                string(reference.functional));
            testCase.verifyEqual(single.functional_class, ...
                string(reference.functional_class));
            testCase.verifyEqual(single.is_valid, reference.is_valid);
            expected = reference.electron_configuration;
            actual = single.electron_configuration;
            testCase.verifyEqual(size(actual, 1), numel(expected));
            for index = 1:size(actual, 1)
                testCase.verifyEqual(actual{index, 1}, ...
                    double(expected{index}{1}));
                testCase.verifyEqual(string(actual{index, 2}), ...
                    string(expected{index}{2}));
                testCase.verifyEqual(actual{index, 3}, ...
                    double(expected{index}{3}), AbsTol = 1e-12);
            end
            copy = single.copy();
            testCase.verifyEqual(copy.data, single.data);
            clear cleanup
        end

        function vaspInputSerializationAndSpecBoundary(testCase)
            [folder, oracle] = testCase.fixture();
            incar = kssolv.analysis.matgenlab.io.vasp.Incar. ...
                from_file(fullfile(folder, "INCAR"));
            poscar = kssolv.analysis.matgenlab.io.vasp.Poscar. ...
                from_file(fullfile(folder, "POSCAR"), ...
                check_for_potcar = false);
            points = kssolv.analysis.matgenlab.io.vasp.Kpoints. ...
                gamma_automatic([3,5,7],[0.5,0,0]);
            inputs = kssolv.analysis.matgenlab.io.vasp.VaspInput( ...
                incar, points, poscar, "Fe", potcar_spec = true);
            testCase.verifyEqual(inputs.keys(), ...
                string(oracle.vasp_input.keys).');
            restored = kssolv.analysis.matgenlab.io.vasp.VaspInput. ...
                from_dict(inputs.as_dict());
