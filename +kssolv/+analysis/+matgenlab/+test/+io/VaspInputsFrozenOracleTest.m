            testCase.verifyError(@() ...
                kssolv.analysis.matgenlab.io.vasp.Kpoints( ...
                "bad",1,"Reciprocal",[0,0,0]), ...
                "KSSOLV:Matgenlab:Kpoints:ExplicitMetadata");
            testCase.verifyError(@() ...
                kssolv.analysis.matgenlab.io.vasp.Kpoints( ...
                comment = "x", unknown = 1), ...
                "KSSOLV:Matgenlab:Kpoints:Option");
            testCase.verifyError(@() ...
                kssolv.analysis.matgenlab.io.vasp.Kpoints. ...
                automatic_density_by_lengths( ...
                kssolv.analysis.matgenlab.core.Structure( ...
                eye(3),{"H"},[0,0,0]), [1,2]), ...
                "KSSOLV:Matgenlab:Kpoints:LengthDensities");
            testCase.verifyError(@() ...
                kssolv.analysis.matgenlab.io.vasp.KpointsSupportedModes. ...
                from_str("invalid"), ...
                "KSSOLV:Matgenlab:Kpoints:InvalidMode");
        end

        function potcarCollectionIoAndAuthorizationBoundary(testCase)
            previousWarning = warning("off", ...
                "KSSOLV:Matgenlab:UnknownPotcarWarning");
            warningCleanup = onCleanup(@() warning(previousWarning));
            raw = testCase.syntheticPotcar();
            collection = kssolv.analysis.matgenlab.io.vasp.Potcar. ...
                from_str(raw + raw);
            folder = string(tempname);
            mkdir(folder);
            folderCleanup = onCleanup(@() rmdir(folder, "s"));
            filename = fullfile(folder, "POTCAR");
            collection.write_file(filename);
            restored = kssolv.analysis.matgenlab.io.vasp.Potcar. ...
                from_file(filename);
            testCase.verifyEqual(restored.symbols, ["Fe","Fe"]);
            specFile = fullfile(folder, "POTCAR.spec.json.gz");
            collection.write_potcar_spec(specFile);
            testCase.verifyTrue(isfile(specFile));
            testCase.verifyEqual(numel(collection.spec), 2);
            singleFile = fullfile(folder, "POTCAR.Fe");
            collection(1).write_file(singleFile);
            singleRestored = ...
                kssolv.analysis.matgenlab.io.vasp.PotcarSingle. ...
                from_file(singleFile);
            testCase.verifyEqual(singleRestored.symbol, "Fe");
            [functions, symbols] = collection(1).identify_potcar();
            testCase.verifyEmpty(functions);
            testCase.verifyEmpty(symbols);
            stats = collection(1).summary_stats;
            testCase.verifyTrue( ...
                kssolv.analysis.matgenlab.io.vasp.PotcarSingle. ...
                compare_potcar_stats(stats, stats));
            testCase.verifyError(@() ...
                kssolv.analysis.matgenlab.io.vasp.Potcar. ...
                from_spec(collection.spec), ...
                "KSSOLV:Matgenlab:Potcar:SpecMismatch");

            previousDirectory = getenv("PMG_VASP_PSP_DIR");
            directoryCleanup = onCleanup(@() setenv( ...
                "PMG_VASP_PSP_DIR", previousDirectory));
            setenv("PMG_VASP_PSP_DIR", "");
            testCase.verifyError(@() ...
                kssolv.analysis.matgenlab.io.vasp.Potcar. ...
                from_dict(collection.as_dict()), ...
                "KSSOLV:Matgenlab:PmgVaspPspDirError");
            clear directoryCleanup folderCleanup warningCleanup
        end

        function vaspInputOptionalFilesCopyAndRun(testCase)
            [folder, ~] = testCase.fixture();
            incar = kssolv.analysis.matgenlab.io.vasp.Incar. ...
                from_file(fullfile(folder, "INCAR"));
            poscar = kssolv.analysis.matgenlab.io.vasp.Poscar. ...
                from_file(fullfile(folder, "POSCAR"), ...
                check_for_potcar = false);
            points = kssolv.analysis.matgenlab.io.vasp.Kpoints. ...
                gamma_automatic();
            inputs = kssolv.analysis.matgenlab.io.vasp.VaspInput( ...
                incar, points, poscar, "Si", potcar_spec = true, ...
                README = "optional");
            testCase.verifyEqual(inputs.get("README"), "optional");
            shallow = inputs.copy(false);
            deep = inputs.copy(true);
            testCase.verifyEqual(shallow.get("README"), "optional");
            testCase.verifyEqual(deep.get("README"), "optional");
            runFolder = string(tempname);
            cleanup = onCleanup(@() rmdir(runFolder, "s"));
            inputs.run_vasp(run_dir = runFolder, ...
                vasp_cmd = ["/bin/sh","-c","echo native-run"], ...
                output_file = "vasp.out", err_file = "vasp.err");
            testCase.verifySubstring(string(fileread( ...
                fullfile(runFolder, "vasp.out"))), "native-run");
            clear cleanup
        end

        function reexportedTypesAndWarningCategories(testCase)
            orbital = kssolv.analysis.matgenlab.electronic_structure. ...
                Orbital.dyz;
            testCase.verifyEqual(double(orbital), 5);
            testCase.verifyEqual(string(orbital), "dyz");
            description = kssolv.analysis.matgenlab.io.vasp. ...
                OrbitalDescription(2, -3.8, 23, 2.3);
            values = double(description);
            testCase.verifyEqual(values(1:4), [2,-3.8,23,2.3], ...
                AbsTol = 1e-12);
            classes = {
                kssolv.analysis.matgenlab.io.vasp. ...
                    BadPoscarWarning.identifier, ...
                    "KSSOLV:Matgenlab:BadPoscarWarning"
                kssolv.analysis.matgenlab.io.vasp. ...
                    BadIncarWarning.identifier, ...
                    "KSSOLV:Matgenlab:BadIncarWarning"
                kssolv.analysis.matgenlab.io.vasp. ...
                    UnknownPotcarWarning.identifier, ...
                    "KSSOLV:Matgenlab:UnknownPotcarWarning"
                kssolv.analysis.matgenlab.io.vasp. ...
                    PmgVaspPspDirError.identifier, ...
                    "KSSOLV:Matgenlab:PmgVaspPspDirError"
                };
            for index = 1:size(classes, 1)
                testCase.verifyEqual(classes{index, 1}, ...
                    classes{index, 2});
            end
        end
    end

