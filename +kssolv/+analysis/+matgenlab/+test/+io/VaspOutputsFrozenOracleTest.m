        function vasprunFamilyMatchesOracle(testCase)
            [folder, oracle] = testCase.fixture();
            run = kssolv.analysis.matgenlab.io.vasp.Vasprun( ...
                fullfile(folder, "vasprun.Al.xml.gz"), ...
                parse_potcar_file = false);
            expected = oracle.vasprun_al;
            testCase.verifyEqual(run.final_energy, ...
                expected.final_energy, AbsTol = 1e-10);
            testCase.verifyEqual(run.run_type, string(expected.run_type));
            testCase.verifyEqual(run.converged_electronic, ...
                expected.converged_electronic);
            testCase.verifyEqual(run.converged_ionic, ...
                expected.converged_ionic);
            testCase.verifyEqual(run.converged, expected.converged);
            testCase.verifyEqual(run.is_spin, expected.is_spin);
            testCase.verifyEqual(run.is_hubbard, expected.is_hubbard);
            testCase.verifyEmpty(fieldnames(run.hubbards));
            testCase.verifyEqual(run.md_n_steps, expected.md_n_steps);
            testCase.verifyEqual(run.nionic_steps, expected.nionic_steps);
            testCase.verifyEqual(run.efermi, ...
                expected.efermi, AbsTol = 1e-10);
            testCase.verifyEqual(numel(run.structures), ...
                expected.structure_count);
            testCase.verifyEqual(run.final_structure.volume, ...
                expected.final_volume, AbsTol = 1e-10);
            testCase.verifyEqual(size(run.actual_kpoints, 1), ...
                expected.actual_kpoints);

            properties = run.eigenvalue_band_properties;
            testCase.verifyEqual(cell2mat(properties(1:3)), ...
                [expected.band_properties{1:3}], AbsTol = 1e-10);
            testCase.verifyEqual(properties{4}, ...
                expected.band_properties{4});
            testCase.verifyEqual(run.calculate_efermi(), ...
                expected.efermi, AbsTol = 1e-10);

            entry = run.get_computed_entry();
            testCase.verifyEqual(entry.energy, ...
                expected.final_energy, AbsTol = 1e-10);
            scalarEntry = run.get_computed_entry(inc_structure = false);
            testCase.verifyEqual(scalarEntry.energy, entry.energy);
            trajectory = run.get_trajectory();
            testCase.verifyEqual(length(trajectory), ...
                expected.trajectory_count);
            testCase.verifyEqual(trajectory(1).volume, ...
                expected.trajectory_first_volume, AbsTol = 1e-10);
            bands = run.get_band_structure();
            testCase.verifyEqual(numel(bands.kpoints), ...
                expected.actual_kpoints);
            testCase.verifyEqual(bands.efermi, expected.efermi);
            testCase.verifyNotEmpty(run.complete_dos);
            testCase.verifyNotEmpty(run.complete_dos_normalized);
            testCase.verifyEmpty(run.get_potcars(false));
            run.update_potcar_spec(false);
            run.update_charge_from_potcar(false);
            dictionary = run.as_dict();
            testCase.verifyTrue(isfield(dictionary, "input"));
            testCase.verifyTrue(isfield(dictionary, "output"));

            previous = warning("off", ...
                "KSSOLV:Matgenlab:Vasprun:DeprecatedSpelling");
            cleanup = onCleanup(@() warning(previous));
            run.projected_magnetisation = [];
            testCase.verifyEmpty(run.projected_magnetisation);
            clear cleanup

            compact = kssolv.analysis.matgenlab.io.vasp.BSVasprun( ...
                fullfile(folder, "vasprun.Al.xml.gz"), false, false);
            compactDictionary = compact.as_dict();
            testCase.verifyTrue(compactDictionary.has_vasp_completed);
        end

