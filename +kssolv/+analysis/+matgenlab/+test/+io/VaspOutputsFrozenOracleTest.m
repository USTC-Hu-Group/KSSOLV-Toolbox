                fullfile(folder, "PROCAR.simple"));
            expected = oracle.procar;
            testCase.verifyEqual([projection.nkpoints, ...
                projection.nbands, projection.nions, projection.nspins], ...
                [expected.nkpoints, expected.nbands, ...
                expected.nions, expected.nspins]);
            testCase.verifyEqual(projection.orbitals, ...
                string(expected.orbitals).');
            occupation = projection.get_occupation(1, "s");
            testCase.verifyEqual([occupation.up, occupation.down], ...
                double(expected.occupation_s_atom1).', AbsTol = 1e-12);
            structure = kssolv.analysis.matgenlab.core.Structure( ...
                eye(3), {"Li", "Li", "O"}, ...
                [0, 0, 0; 0.25, 0.25, 0.25; 0.5, 0.5, 0.5]);
            elementProjection = projection. ...
                get_projection_on_elements(structure);
            testCase.verifyTrue(isfield(elementProjection.up{1, 1}, "Li"));
            reread = projection.read(fullfile(folder, "PROCAR.simple"));
            testCase.verifyEqual(reread.nkpoints, projection.nkpoints);

            trajectory = kssolv.analysis.matgenlab.io.vasp.Xdatcar( ...
                fullfile(folder, "XDATCAR_traj_combine_test_2"));
            expected = oracle.xdatcar;
            testCase.verifyEqual(length(trajectory), ...
                expected.structure_count);
            testCase.verifyEqual(trajectory.site_symbols, ...
                string(expected.site_symbols).');
            testCase.verifyEqual(trajectory.natoms, ...
                double(expected.natoms).');
            testCase.verifyEqual(trajectory.comment, ...
                string(expected.comment));
            testCase.verifyEqual(trajectory.structures{1}.volume, ...
                expected.first_volume, AbsTol = 1e-10);
            testCase.verifyNotEmpty(trajectory.get_str(1, 3));
            shortened = kssolv.analysis.matgenlab.io.vasp.Xdatcar( ...
                fullfile(folder, "XDATCAR_traj_combine_test_2"), 1, 3);
            testCase.verifyEqual(length(shortened), 2);
