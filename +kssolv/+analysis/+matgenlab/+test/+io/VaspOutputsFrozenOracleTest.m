        function hdf5OutputReadersAndBoundaries(testCase)
            [folder, oracle] = testCase.fixture();
            output = kssolv.analysis.matgenlab.io.vasp.Vaspout( ...
                fullfile(folder, ...
                "vaspout.line_mode_band_structure.h5.gz"), ...
                store_potcar = false);
            expected = oracle.vaspout;
            testCase.verifyEqual(output.final_energy, ...
                expected.final_energy, AbsTol = 1e-10);
            testCase.verifyEqual(output.kpoints.num_kpts, ...
                expected.num_kpoints);
            testCase.verifyEqual(numel(output.ionic_steps), ...
                expected.ionic_steps);
            testCase.verifyEqual(output.is_spin, expected.is_spin);
            testCase.verifyEqual(output.is_hubbard, expected.is_hubbard);
            temporary = string(tempname) + ".h5";
            cleanup = onCleanup(@() testCase.deleteIfPresent(temporary));
            output.remove_potcar_and_write_file(temporary);
            scrubbed = kssolv.analysis.matgenlab.io.vasp.Vaspout( ...
                temporary, store_potcar = false);
            testCase.verifyEqual(scrubbed.final_energy, ...
                output.final_energy, AbsTol = 1e-10);
            clear cleanup

            wave = kssolv.analysis.matgenlab.io.vasp.Vaspwave( ...
                fullfile(folder, "vaspwave.h5"));
            coefficients = wave.get_band_coeffs(1, 1, 1);
            testCase.verifyNotEmpty(coefficients);
            testCase.verifyNotEmpty(wave.fft_mesh(1, 1));
            testCase.verifyNotEmpty(wave.evaluate_wavefunc( ...
                1, 1, [0, 0, 0]));
            testCase.verifyClass(wave.get_chgcar(), ...
                "kssolv.analysis.matgenlab.io.vasp.Chgcar");
            testCase.verifyClass(wave.get_locpot(), ...
                "kssolv.analysis.matgenlab.io.vasp.Locpot");
            poscar = kssolv.analysis.matgenlab.io.vasp.Poscar. ...
                from_file(fullfile(folder, "POSCAR"), ...
                check_for_potcar = false);
            testCase.verifyClass(wave.get_parchg( ...
                poscar, 1, 1, scale = 1), ...
                "kssolv.analysis.matgenlab.io.vasp.Chgcar");
            unkFolder = string(tempname);
            mkdir(unkFolder);
            unkCleanup = onCleanup(@() rmdir(unkFolder, "s"));
            wave.write_unks(unkFolder);
            testCase.verifyTrue(isfile(fullfile( ...
                unkFolder, "UNK00001.1")));
            clear unkCleanup

            missing = string(tempname);
            mkdir(missing);
            missingCleanup = onCleanup(@() rmdir(missing, "s"));
            testCase.verifyError(@() ...
                kssolv.analysis.matgenlab.io.vasp. ...
                get_band_structure_from_vasp_multiple_branches(missing), ...
                "KSSOLV:Matgenlab:VaspParseError");
            copyfile(fullfile(folder, "vasprun.Al.xml.gz"), ...
                fullfile(missing, "vasprun.xml.gz"));
            reconstructed = kssolv.analysis.matgenlab.io.vasp. ...
                get_band_structure_from_vasp_multiple_branches(missing);
            testCase.verifyEqual(numel(reconstructed.kpoints), 84);
            testCase.verifyEqual( ...
                kssolv.analysis.matgenlab.io.vasp. ...
                get_adjusted_fermi_level(1, 2, ...
                output.get_band_structure()), 1);
            clear missingCleanup
        end
