        function volumetricReadersAndWritersRoundTrip(testCase)
            [folder, oracle] = testCase.fixture();
            expected = oracle.volumetric;
            charge = kssolv.analysis.matgenlab.io.vasp.Chgcar. ...
                from_file(fullfile(folder, "CHGCAR.nospin.gz"));
            testCase.verifyEqual(charge.dim, ...
                double(expected.chgcar_dim).');
            testCase.verifyEqual(charge.data.total(1), ...
                expected.chgcar_first, AbsTol = 1e-12);
            testCase.verifyEmpty(charge.net_magnetization);
            [poscar, data, augmentation] = ...
                kssolv.analysis.matgenlab.io.vasp.VolumetricData. ...
                parse_file(fullfile(folder, "CHGCAR.nospin.gz"));
            testCase.verifyEqual(data.total, charge.data.total);
            testCase.verifyNotEmpty(poscar);
            testCase.verifyTrue(isfield(augmentation, "total"));

            potential = kssolv.analysis.matgenlab.io.vasp.Locpot. ...
                from_file(fullfile(folder, "LOCPOT.gz"));
            testCase.verifyEqual(potential.dim, ...
                double(expected.locpot_dim).');
            testCase.verifyEqual(potential.data.total(1), ...
                expected.locpot_first, AbsTol = 1e-12);
            testCase.verifyEqual(sum(potential.get_average_along_axis(1)), ...
                -217.05226954, AbsTol = 1e-8);
            axisGrid = potential.get_axis_grid(1);
            testCase.verifyEqual(axisGrid(end), 2.87629, AbsTol = 1e-2);

            elf = kssolv.analysis.matgenlab.io.vasp.Elfcar. ...
                from_file(fullfile(folder, "ELFCAR.gz"));
            testCase.verifyEqual(elf.dim, double(expected.elfcar_dim).');
            testCase.verifyEqual(elf.data.total(1), ...
                expected.elfcar_total_first, AbsTol = 1e-12);
            testCase.verifyEqual(elf.data.diff(1), ...
                expected.elfcar_diff_first, AbsTol = 1e-12);
            alpha = elf.get_alpha();
            testCase.verifyEqual(alpha.data.total(1), ...
                expected.elfcar_alpha_first, AbsTol = 1e-10);

            copy = potential.copy();
            testCase.verifyClass(copy, class(potential));
            combined = charge + charge;
            testCase.verifyEqual(combined.data.total, ...
                2 * charge.data.total, AbsTol = 1e-12);
            difference = combined - charge;
            testCase.verifyEqual(difference.data.total, ...
                charge.data.total, AbsTol = 1e-12);
            testCase.verifyEqual(charge.value_at(0, 0, 0), ...
                charge.data.total(1));
            testCase.verifySize(charge.linear_slice( ...
                [0, 0, 0], [0.5, 0.5, 0.5], 5), [5, 1]);

            temporary = string(tempname);
            mkdir(temporary);
            cleanup = onCleanup(@() rmdir(temporary, "s"));
            output = fullfile(temporary, "CHGCAR");
            charge.write_file(output);
            restored = kssolv.analysis.matgenlab.io.vasp.Chgcar. ...
                from_file(output);
            testCase.verifyEqual(restored.data.total, ...
                charge.data.total, AbsTol = 1e-12);
            clear cleanup
        end

