        function perturbDiscretizeAndChargeMatchOracle(testCase)
            import kssolv.analysis.matgenlab.core.*
            import kssolv.analysis.matgenlab.transformations.*
            oracle = testCase.oracle();
            base = testCase.chargedStructure();
            exact = PerturbStructureTransformation(.05). ...
                apply_transformation(base);
            distances = arrayfun(@(index) ...
                exact(index).distance(base(index)), 1:base.num_sites);
            testCase.verifyEqual(distances, ...
                .05 * ones(1, base.num_sites), AbsTol = 1e-12);
            ranged = PerturbStructureTransformation(.05, 0). ...
                apply_transformation(base);
            distances = arrayfun(@(index) ...
                ranged(index).distance(base(index)), 1:base.num_sites);
            testCase.verifyGreaterThanOrEqual(distances, 0);
            testCase.verifyLessThanOrEqual(distances, .05);

            disordered = Structure(Lattice.cubic(4), ...
                {{"Li", .19; "Na", .19; "K", .62}, {"O", 1}}, ...
                [0,0,0; .5,.5,.5]);
            discretized = DiscretizeOccupanciesTransformation(5, .5). ...
                apply_transformation(disordered);
            expected = oracle.discrete_occupancies;
            testCase.verifyEqual(discretized(1).species("Li"), expected.Li);
            testCase.verifyEqual(discretized(1).species("Na"), expected.Na);
            testCase.verifyEqual(discretized(1).species("K"), expected.K);
            testCase.verifyError(@() ...
                DiscretizeOccupanciesTransformation(5, .01). ...
                apply_transformation(disordered), ...
                "KSSOLV:Matgenlab:DiscretizeOccupancies:Tolerance");
            charged = ChargedCellTransformation(oracle.charge). ...
                apply_transformation(disordered);
            testCase.verifyEqual(charged.charge, oracle.charge);
            transformation = ChargedCellTransformation(3);
            testCase.verifyError(@() testCase.readInverse(transformation), ...
                "KSSOLV:Matgenlab:ChargedCellTransformation:Inverse");
        end

        function officialScaleToRelaxedFixtureMatchesOracle(testCase)
            import kssolv.analysis.matgenlab.core.*
            import kssolv.analysis.matgenlab.transformations.*
            oracle = testCase.oracle();
            initial = Structure.from_file( ...
                testCase.fixture("Cu_slab_init.cif"));
            relaxed = Structure.from_file( ...
                testCase.fixture("Cu_slab_fin.cif"));
            gold = Structure.from_file(testCase.fixture("Au_slab_init.cif"));
            scaled = ScaleToRelaxedTransformation(initial, relaxed). ...
                apply_transformation(gold);
            testCase.verifyEqual([gold.volume, scaled.volume], ...
                reshape(oracle.scale_volume, 1, []), AbsTol = 1e-8);
            testCase.verifyEqual(scaled.lattice.matrix, ...
                oracle.scale_matrix, AbsTol = 2e-8);
            testCase.verifyEqual(scaled.num_sites, oracle.scale_count);
            testCase.verifyEqual(scaled.symbol_set, ...
                string(oracle.scale_species));
            explicit = ScaleToRelaxedTransformation( ...
                initial, relaxed, {"Cu", "Au"}). ...
                apply_transformation(gold);
            testCase.verifyEqual(explicit.lattice.matrix, ...
                scaled.lattice.matrix, AbsTol = 1e-12);
            testCase.verifyEqual(explicit.frac_coords, ...
                scaled.frac_coords, AbsTol = 1e-12);
        end

        function randomManipulationsAreSeededUniqueAndValid(testCase)
            import kssolv.analysis.matgenlab.core.*
            import kssolv.analysis.matgenlab.transformations.*
            structure = Structure(Lattice.cubic(4), ...
                {"Li", "Li", "Li", "Li"}, ...
                [0,0,0; .25,0,0; .5,0,0; .75,0,0]);
            manipulations = {{0, 2, 1:4, "Na"}};
            first = get_randomly_manipulated_structures( ...
                structure, manipulations, 7, 3);
            second = get_randomly_manipulated_structures( ...
                structure, manipulations, 7, 3);
            keys = strings(1, 3);
            for index = 1:3
                testCase.verifyEqual(first{index}.formula, "Na2 Li2");
                testCase.verifyEqual(first{index}, second{index});
                keys(index) = strjoin(cellfun(@(site) ...
                    site.species_string, first{index}.sites), ",");
            end
            testCase.verifyEqual(numel(unique(keys)), 3);
            testCase.verifyError(@() ...
                get_randomly_manipulated_structures( ...
                structure, {{0, 5, 1:4, "Na"}}, 7, 1), ...
                "KSSOLV:Matgenlab:RandomManipulation:Impossible");
        end

        function allTransformationsMsonRoundTrip(testCase)
            import kssolv.analysis.matgenlab.transformations.*
            structure = testCase.chargedStructure();
            objects = {
                RotationTransformation([0, 1, 0], 30)
                OxidationStateDecorationTransformation( ...
                    struct("Li", 1, "O", -2))
                AutoOxiStateDecorationTransformation()
                OxidationStateRemovalTransformation()
                SupercellTransformation([2,0,0; 0,1,0; 0,0,1])
                SubstitutionTransformation({"Li+", "Na+"})
                RemoveSpeciesTransformation("Li+")
                PartialRemoveSpecieTransformation("Li+", .5)
                OrderDisorderedStructureTransformation()
                PrimitiveCellTransformation()
                ConventionalCellTransformation()
                PerturbStructureTransformation(.02)
                DeformStructureTransformation(eye(3))
                DiscretizeOccupanciesTransformation()
                ChargedCellTransformation(2)
                ScaleToRelaxedTransformation(structure, structure)
                };
            for index = 1:numel(objects)
                encoded = kssolv.analysis.matgenlab.util.encode( ...
                    objects{index});
                testCase.verifyFalse(contains(lower(encoded), "python"));
                restored = kssolv.analysis.matgenlab.util.decode(encoded);
                testCase.verifyClass(restored, class(objects{index}));
            end
        end
