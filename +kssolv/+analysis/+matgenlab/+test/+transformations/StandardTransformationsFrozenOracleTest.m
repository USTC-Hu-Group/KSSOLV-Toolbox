        function rotationAndDeformationMatchOracle(testCase)
            import kssolv.analysis.matgenlab.core.*
            import kssolv.analysis.matgenlab.transformations.*
            oracle = testCase.oracle();
            lattice = testCase.referenceLattice();
            structure = Structure(lattice, {"Si", "Si"}, ...
                [0, 0, 0; 0.75, 0.5, 0.75]);
            rotation = RotationTransformation([0, 1, 0], 30);
            rotated = rotation.apply_transformation(structure);
            testCase.verifyEqual(rotated.lattice.matrix, ...
                oracle.rotation_matrix, AbsTol = 1e-12);
            restored = rotation.inverse.apply_transformation(rotated);
            testCase.verifyEqual(restored.lattice.matrix, ...
                structure.lattice.matrix, AbsTol = 1e-12);

            coordinates = [0,0,0; .375,.375,.375; .5,.5,.5; ...
                .875,.875,.875; .125,.125,.125; .25,.25,.25; ...
                .625,.625,.625; .75,.75,.75];
            charged = Structure(lattice, ...
                [repmat({"Li+"}, 1, 4), repmat({"O2-"}, 1, 4)], ...
                coordinates);
            deformation = DeformStructureTransformation( ...
                [1,0,0; 0,1,0; 0,.05,1]);
            deformed = deformation.apply_transformation(charged);
            testCase.verifyEqual(deformed.lattice.lengths, ...
                reshape(oracle.deformed_lengths, 1, []), ...
                AbsTol = 1e-12);
            testCase.verifyEqual(deformation.inverse. ...
                apply_transformation(deformed).lattice.matrix, ...
                charged.lattice.matrix, AbsTol = 1e-11);
        end

        function oxidationDecorationsMatchOfficialFixture(testCase)
            import kssolv.analysis.matgenlab.core.*
            import kssolv.analysis.matgenlab.transformations.*
            oracle = testCase.oracle();
            plain = Structure(testCase.referenceLattice(), ...
                {"Li", "Li", "O", "O"}, testCase.fourCoordinates());
            decorated = OxidationStateDecorationTransformation( ...
                struct("Li", 1, "O", -2)).apply_transformation(plain);
            labels = cellfun(@(site) site.species_string, decorated.sites);
            testCase.verifyEqual(labels, ...
                reshape(string(oracle.decorated_species), 1, []));
            removed = OxidationStateRemovalTransformation(). ...
                apply_transformation(decorated);
            labels = cellfun(@(site) site.species_string, removed.sites);
            testCase.verifyEqual(labels, ...
                reshape(string(oracle.undecorated_species), 1, []));

            lfp = Structure.from_file( ...
                testCase.fixture("POSCAR_LiFePO4"), "poscar");
            automatic = AutoOxiStateDecorationTransformation(). ...
                apply_transformation(lfp);
            expected = oracle.auto_oxidation_states;
            for index = 1:automatic.num_sites
                specie = automatic(index).specie;
                testCase.verifyEqual(specie.oxi_state, ...
                    expected.(char(specie.symbol)), AbsTol = 1e-12);
            end

            copper = Structure.from_spacegroup( ...
                "Fm-3m", Lattice.cubic(3.677), {"Cu"}, [0, 0, 0]);
            testCase.verifyError(@() ...
                AutoOxiStateDecorationTransformation(). ...
                apply_transformation(copper), ...
                "KSSOLV:Matgenlab:AutoOxiState:Failed");
            zero = AutoOxiStateDecorationTransformation( ...
                .1, 4, 100000, 1.015, true). ...
                apply_transformation(copper);
            testCase.verifyEqual(cellfun(@(site) ...
                site.specie.oxi_state, zero.sites), ...
                zeros(1, zero.num_sites));
        end

        function supercellFactoriesAndErrorsMatchOracle(testCase)
            import kssolv.analysis.matgenlab.core.*
            import kssolv.analysis.matgenlab.transformations.*
            oracle = testCase.oracle();
            charged = testCase.chargedStructure();
            transformed = SupercellTransformation( ...
                [2,1,0; 0,2,0; 1,0,2]). ...
                apply_transformation(charged);
            testCase.verifyEqual(transformed.formula, ...
                string(oracle.super_formula));
            diagonal = SupercellTransformation. ...
                from_scaling_factors(2, 3, 4);
            testCase.verifyEqual(diagonal.scaling_matrix, diag([2, 3, 4]));
            cubic = Structure.from_spacegroup( ...
                "Pm-3m", 4 * eye(3), {"H"}, [0, 0, 0]);
            fixed = SupercellTransformation. ...
                from_boundary_distance(cubic, 9, false);
            rotated = SupercellTransformation. ...
                from_boundary_distance(cubic, 9, true);
            testCase.verifyEqual(fixed.scaling_matrix, ...
                oracle.boundary_no_rotation);
            testCase.verifyEqual(rotated.scaling_matrix, ...
                oracle.boundary_rotation);
            testCase.verifyEqual([fixed.apply_transformation(cubic).num_sites, ...
                rotated.apply_transformation(cubic).num_sites], ...
                reshape(oracle.boundary_counts, 1, []));
            testCase.verifyError(@() ...
                SupercellTransformation.from_boundary_distance( ...
                charged, 6, false, 10), ...
                "KSSOLV:Matgenlab:SupercellTransformation:MaxAtoms");
            testCase.verifyError(@() testCase.readInverse(fixed), ...
                "KSSOLV:Matgenlab:SupercellTransformation:Inverse");
        end

        function substitutionsAndRemovalMatchOracle(testCase)
            import kssolv.analysis.matgenlab.transformations.*
            oracle = testCase.oracle();
            charged = testCase.chargedStructure();
            substitution = SubstitutionTransformation({
                "Li+", "Na+"
                "O2-", {"S2-", .5; "Se2-", .5}
                });
            changed = substitution.apply_transformation(charged);
            testCase.verifyEqual(changed.formula, ...
                string(oracle.substitution_formula));
            simple = SubstitutionTransformation({
                "Li+", "Na+"
                "O2-", "S2-"
                });
            restored = simple.inverse.apply_transformation( ...
                simple.apply_transformation(charged));
            testCase.verifyEqual(restored.formula, charged.formula);
            removed = RemoveSpeciesTransformation("Li+"). ...
                apply_transformation(charged);
            testCase.verifyEqual(removed.formula, ...
                string(oracle.removed_formula));
            testCase.verifyError(@() testCase.readInverse(substitution), ...
                "KSSOLV:Matgenlab:SubstitutionTransformation:Inverse");
        end

        function orderingAndPartialRemovalMatchOracle(testCase)
            import kssolv.analysis.matgenlab.core.*
            import kssolv.analysis.matgenlab.transformations.*
            oracle = testCase.oracle();
            six = Structure(Lattice.cubic(10), repmat({"Li+"}, 1, 6), ...
                [0,0,0; .75,.75,.75; .5,.5,.5; .25,.25,.25; ...
                .1,.1,.1; .3,.75,.3]);
            partial = PartialRemoveSpecieTransformation("Li+", .5);
            reduced = partial.apply_transformation(six);
            testCase.verifyTrue(partial.is_one_to_many);
            testCase.verifyEqual(reduced.num_sites, oracle.partial_count);
            testCase.verifyEqual(reduced.frac_coords, ...
                oracle.partial_coords, AbsTol = 1e-12);

            disordered = Structure(testCase.referenceLattice(), ...
                repmat({{"Si4+", .5; "O2-", .25; "P5+", .25}}, ...
                1, 4), testCase.fourCoordinates());
            ordering = OrderDisorderedStructureTransformation();
            ranked = ordering.apply_transformation(disordered, 50);
            testCase.verifyTrue(ordering.is_one_to_many);
            testCase.verifyEqual(numel(ranked), oracle.order_count);
            testCase.verifyEqual(ranked{1}.energy, ...
                oracle.order_energy, AbsTol = 1e-9);
            testCase.verifyEqual(ranked{1}.structure.formula, ...
                string(oracle.order_formula));
            testCase.verifyEqual(ordering.lowest_energy_structure, ...
                ranked{1}.structure);

            tooSmall = Structure(testCase.referenceLattice(), ...
                {{"X4+", .33; "O2-", .33; "P5+", .33}}, ...
                [.5, .5, .5]);
            testCase.verifyError(@() ordering. ...
                apply_transformation(tooSmall), ...
                "KSSOLV:Matgenlab:OrderDisordered:Occupancy");

            alloy = Structure.from_spacegroup("Fm-3m", ...
                Lattice.cubic(3.677), ...
                {{"Cu1+", .5; "Au2+", .5}}, [0, 0, 0]);
            symmetryAware = OrderDisorderedStructureTransformation( ...
                OrderDisorderedStructureTransformation.ALGO_FAST, ...
                true, true);
            alloyRanked = symmetryAware.apply_transformation(alloy, 10);
            testCase.verifyEqual(numel(alloyRanked), 6);
            testCase.verifyEqual(alloyRanked{1}.structure.formula, ...
                "Cu2 Au2");
            testCase.verifyTrue(all(cellfun(@(site) ...
                isa(site.specie, ...
                "kssolv.analysis.matgenlab.core.Element"), ...
                alloyRanked{1}.structure.sites)));
        end

