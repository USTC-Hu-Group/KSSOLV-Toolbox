classdef NumUtilsTest < matlab.unittest.TestCase
    methods (Test)
        function significantFiguresMatchUpstream(testCase)
            values = [424.2425, 2.3425356, 0.000042535636653, ...
                .23, 2.468e6, 0, -1.392156];
            expected = [400 420 424 424.2 424.24; ...
                2 2.3 2.34 2.343 2.3425; ...
                4e-5 4.3e-5 4.25e-5 4.254e-5 4.2536e-5; ...
                .2 .23 .23 .23 .23; ...
                2e6 2.5e6 2.47e6 2.468e6 2.468e6; ...
                0 0 0 0 0; ...
                -1 -1.4 -1.39 -1.392 -1.3922];
            actual = zeros(size(expected));
            for row = 1:numel(values)
                for sig = 1:5
                    actual(row, sig) = ...
                        kssolv.analysis.matgenlab.util.round_to_sigfigs( ...
                        values(row), sig);
                end
            end
            testCase.verifyEqual(actual, expected, RelTol=1e-14, AbsTol=1e-14);
        end

        function significantFigureErrors(testCase)
            testCase.verifyError(@() ...
                kssolv.analysis.matgenlab.util.round_to_sigfigs(3.5, -2), ...
                "KSSOLV:Matgenlab:Num:SigFigsNotPositive");
            testCase.verifyError(@() ...
                kssolv.analysis.matgenlab.util.round_to_sigfigs(3.5, 3.5), ...
                "KSSOLV:Matgenlab:Num:SigFigsNotInteger");
        end

        function symmetricMatrix(testCase)
            actual = kssolv.analysis.matgenlab.util. ...
                make_symmetric_matrix_from_upper_tri(1:6);
            testCase.verifyEqual(actual, [1 4 5; 4 2 6; 5 6 3]);
        end
    end
end
