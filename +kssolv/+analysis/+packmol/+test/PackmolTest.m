        function movableEulerMatrixAndDerivativesMatchSource(testCase)
            angles = [0.31, -0.72, 1.17];
            [rotation, derivatives] = ...
                kssolv.analysis.packmol.eulerrmat(angles(1), ...
                angles(2), angles(3));
            expected = [ ...
                0.794449231021982, -0.015652542038795, -0.607128830855780; ...
                0.538474886639722,  0.480487825530672,  0.692225574487930; ...
                0.280882921849871, -0.876861703716459,  0.390151684308230];
            testCase.verifyEqual(rotation, expected, AbsTol = 5e-15);
            step = 1e-6;
            for axis = 1:3
                plus = angles;
                minus = angles;
                plus(axis) = plus(axis) + step;
                minus(axis) = minus(axis) - step;
                numerical = (kssolv.analysis.packmol.eulerrmat( ...
                    plus(1), plus(2), plus(3)) - ...
                    kssolv.analysis.packmol.eulerrmat( ...
                    minus(1), minus(2), minus(3))) / (2 * step);
                testCase.verifyEqual(derivatives(:, :, axis), ...
                    numerical, AbsTol = 2e-10);
            end
        end

        function everyConstraintGradientMatchesFiniteDifference(testCase)
            cases = { ...
                2, [0 0 0 3], [-.7 1 4]; ...
                3, [0 0 0 2 3 4], [-.7 1 5]; ...
                4, [0 0 0 2], [3 .2 .1]; ...
                5, [0 0 0 2 3 4 1], [3 .2 .1]; ...
                6, [0 0 0 3], [.8 1.2 1.4]; ...
                7, [0 0 0 2 3 4], [.8 1.2 1.4]; ...
                8, [0 0 0 2], [1 .2 .1]; ...
                9, [0 0 0 2 3 4 1], [1 .2 .1]; ...
                10, [1 2 3 4], [.1 .2 .3]; ...
                11, [1 2 3 0], [.1 .2 .3]; ...
                12, [0 0 0 0 0 1 2 1 4], [3 0 2]; ...
                13, [0 0 0 0 0 1 2 1 4], [1 0 2]; ...
                14, [0 0 2 3 1 4], [.5 .7 0]; ...
                15, [0 0 2 3 1 4], [.5 .7 5]};
            step = 1e-6;
            for i = 1:size(cases, 1)
                type = cases{i, 1};
                parameters = cases{i, 2};
                point = cases{i, 3};
                [~, analytical] = ...
                    kssolv.analysis.packmol.constraint_function( ...
                    type, parameters, point);
                numerical = zeros(1, 3);
                for axis = 1:3
                    plus = point;
                    minus = point;
                    plus(axis) = plus(axis) + step;
                    minus(axis) = minus(axis) - step;
                    numerical(axis) = ( ...
                        kssolv.analysis.packmol.constraint_function( ...
                            type, parameters, plus) - ...
                        kssolv.analysis.packmol.constraint_function( ...
                            type, parameters, minus)) / (2 * step);
                end
                if type == 9
                    % Upstream comprest omits scale2 for this objective
                    % while gwalls keeps it in the analytical gradient.
                    testCase.verifyEqual(analytical, 1e-2 * numerical, ...
                        "Outside-ellipsoid source behavior differs.", ...
                        AbsTol = 3e-8);
                else
                    testCase.verifyEqual(analytical, numerical, ...
                        sprintf( ...
                        "Constraint type %d gradient differs.", type), ...
                        AbsTol = 3e-8);
                end
            end
        end

        function sphericalPenaltyUsesUpstreamScale2(testCase)
