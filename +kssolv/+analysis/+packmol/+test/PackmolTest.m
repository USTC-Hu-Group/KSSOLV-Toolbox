function value = basicInput(filename, number, constraint)
value = "tolerance 2" + newline + ...
    "filetype xyz" + newline + ...
    "output output.xyz" + newline + ...
    "seed 1" + newline + ...
    "maxit 20" + newline + ...
    "nloop 2" + newline + ...
    "structure " + filename + newline + ...
    " number " + number + newline + ...
    " " + constraint + newline + ...
    "end structure" + newline;
end

function gradient = centralDifference(fun, value)
step = 1e-6;
gradient = zeros(size(value));
for i = 1:numel(value)
    plus = value;
    minus = value;
    plus(i) = plus(i) + step;
    minus(i) = minus(i) - step;
    gradient(i) = (fun(plus) - fun(minus)) / (2 * step);
end
end

function [folder, cleanup] = fixtureFolder()
folder = string(tempname);
mkdir(folder);
cleanup = onCleanup(@() removeFolder(folder));
end

function writeText(path, value)
fileId = fopen(path, "w");
assert(fileId >= 0);
cleanup = onCleanup(@() fclose(fileId));
fprintf(fileId, "%s", char(value));
clear cleanup
end

function removeFolder(folder)
if isfolder(folder)
    rmdir(folder, "s");
end
end
