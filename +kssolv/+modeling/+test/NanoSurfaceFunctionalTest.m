        function genericOxygenHydrogenFragmentPreservesDraggedGeometry(testCase)
            model=kssolv.modeling.test. ...
                ModelingFunctionalTestUtils.surfaceSlab();
            anchorSite=1;
            normal=model.lattice.matrix(3,:);
            normal=normal/norm(normal);
            oxygen=model.cart_coords(anchorSite,:)+2.05*normal;
            tangent=model.lattice.matrix(1,:);
            tangent=tangent/norm(tangent);
            direction=.8*normal+.6*tangent;
            direction=direction/norm(direction);
            hydrogen=oxygen+.96*direction;
            result=kssolv.modeling.CommandExecutor.execute(model, ...
                "place_adsorbate",struct("anchorSites",anchorSite, ...
                "adsorbateName","O-H fragment", ...
                "adsorbateSpecies",["O","H"], ...
                "adsorbateCoordinates",[oxygen;hydrogen], ...
                "adsorbateBonds",[1,2,1], ...
                "anchorAtomIndices",1, ...
                "minimumDistance",.1));
            testCase.verifyTrue(result.changed);
            testCase.verifyEqual(result.model.num_sites,model.num_sites+2);
            testCase.verifyEqual(result.model.cart_coords(end-1,:), ...
                oxygen,AbsTol=1e-12);
            testCase.verifyEqual(result.model.cart_coords(end,:), ...
                hydrogen,AbsTol=1e-12);
            metadata=result.model.properties.adsorbate;
            testCase.verifyEqual(metadata.schemaVersion,2);
            testCase.verifyEqual(metadata.placementMode,"direct-manipulation");
            testCase.verifyEqual(metadata.name,"O-H fragment");
            testCase.verifyEqual(metadata.species,["O","H"]);
            testCase.verifyEqual(metadata.bonds,[1,2,1]);
            testCase.verifyEqual(metadata.hostAnchorSites,anchorSite);
            testCase.verifyEqual(metadata.hostBondLengths,2.05, ...
                AbsTol=1e-12);
            testCase.verifyEqual(norm(metadata.coordinates(2,:) - ...
                metadata.coordinates(1,:)),.96, ...
                AbsTol=1e-12);
            testCase.verifyEqual(sort(string(fieldnames(metadata))), ...
                sort(["schemaVersion"; "placementMode"; "name"; ...
                "species"; "coordinates"; "bonds"; ...
                "anchorAtomIndices"; "hostAnchorSites"; ...
                "hostAnchorLabels"; "hostBondLengths"; "guestFormula"]));
        end

        function interfaceSearchEnumeratesAndAppliesRotation(testCase)
            bottom = kssolv.modeling.test. ...
                ModelingFunctionalTestUtils.graphene();
            rotated=kssolv.modeling.LatticeEditorCommands.execute( ...
                bottom,"rotate_lattice",struct("axis",[0,0,1], ...
                "angleDegrees",10));
            top=rotated.model;
            candidates = kssolv.modeling.builders. ...
                InterfaceCandidateBuilder.enumerate(bottom, top, ...
                maximumRepeat = 1, maximumCandidates = 1, ...
                maximumRotation = 15, rotationStep = 5);
            testCase.verifyEqual(abs(candidates.rotationDegrees),10, ...
                AbsTol=1e-10);
            result = kssolv.modeling.CommandExecutor.execute(bottom, ...
                "stack_heterostructure", struct("otherModel", top, ...
                "maximumRepeat", 1, "maximumRotation", 15, ...
                "rotationStep", 5, "candidateIndex", 1, ...
                "maximumStrain", .03));
            testCase.verifyEqual(abs( ...
                result.analysis.candidates(1).rotationDegrees),10, ...
                AbsTol=1e-10);
            testCase.verifyEqual(result.model.num_sites, 4);

            matched=kssolv.modeling.builders. ...
                InterfaceCandidateBuilder.enumerate(bottom,bottom, ...
                maximumRepeat=2,maximumCandidates=20, ...
                maximumRotation=30,sortMode="strain");
            nonDiagonal=find(arrayfun(@(item) ...
                item.bottomTransform(1,2)~=0 && isequal( ...
                item.bottomTransform,item.topTransform),matched),1);
            testCase.verifyNotEmpty(nonDiagonal);
            selected=matched(nonDiagonal);
            testCase.verifyEqual(selected.strain,0,AbsTol=1e-12);
            testCase.verifyEqual(selected.atomCount,8);
            matrixResult=kssolv.modeling.CommandExecutor.execute(bottom, ...
                "stack_heterostructure",struct("otherModel",bottom.copy(), ...
                "maximumRepeat",2,"candidateIndex",nonDiagonal, ...
                "maximumStrain",.03));
            testCase.verifyEqual(matrixResult.model.num_sites,8);
            testCase.verifyEqual( ...
                matrixResult.analysis.candidates(nonDiagonal). ...
                bottomTransform,selected.bottomTransform);
        end
    end

