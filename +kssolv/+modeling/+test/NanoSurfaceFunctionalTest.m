classdef NanoSurfaceFunctionalTest < matlab.unittest.TestCase
    %NANOSURFACEFUNCTIONALTEST Execute nano/surface/interface commands.

    properties (TestParameter)
        NanoCommand = { ...
            "roll_nanotube", "cut_nanoribbon", ...
            "cut_nanowire", "quantum_dot_void"}
        SurfaceCommand = { ...
            "build_slab", "add_vacuum", "insert_structure", ...
            "stack_heterostructure", "twist_moire", ...
            "interpolate_neb", "find_adsorption_sites", ...
            "locate_adsorbate", "place_adsorbate", ...
            "passivate_surface", "add_solvent_layer"}
    end

    methods (Test)
        function nanostructureCommandIsFunctional(testCase, NanoCommand)
            commandId = string(NanoCommand);
            [model, parameters] = testCase.nanoCase(commandId);
            result = ...
                kssolv.modeling.test.ModelingFunctionalTestUtils. ...
                execute(testCase, model, commandId, parameters);
            testCase.verifyTrue(result.changed);
            testCase.verifyNanoResult(commandId, model, result.model);
        end

        function surfaceBuilderEnumeratesTerminationsAndFixesLayers(testCase)
            bulk=kssolv.analysis.matgenlab.core.Structure. ...
                from_spacegroup("Fm-3m",eye(3)*3.92,"Pt",[0,0,0]);
            result=kssolv.modeling.CommandExecutor.execute(bulk, ...
                "build_slab",struct("millerIndex",[1,1,1], ...
                "slabSize",8,"vacuumSize",10,"centerSlab",true, ...
                "primitive",true,"terminationIndex",1));
            testCase.verifyGreaterThanOrEqual( ...
                numel(result.analysis.terminations),1);
            testCase.verifyEqual( ...
                result.model.properties.surface.terminationIndex,1);
            testCase.verifyTrue(isfield(result.model.site_properties, ...
                "surface_layer"));
            candidates=kssolv.ui.features.modeling. ...
                AnalysisResultPresenter.surfaceTerminationTable(result);
            testCase.verifyEqual(height(candidates), ...
                numel(result.analysis.terminations));
            fixed=kssolv.modeling.CommandExecutor.execute(result.model, ...
                "fix_atoms",struct("indices",1,"bottomLayerCount",1));
            layers=fixed.model.site_properties.surface_layer;
            if iscell(layers), layers=cell2mat(layers); end
            flags=fixed.model.site_properties.surface_fixed;
            if iscell(flags), flags=cell2mat(flags); end
            testCase.verifyEqual(logical(flags),double(layers)==1);
        end

        function interactiveAdsorbateProtocolAcceptsGenericCarboxyl(testCase)
            host = kssolv.modeling.test. ...
                ModelingFunctionalTestUtils.surfaceSlab();
            anchor = 1;
            carbon = host.cart_coords(anchor, :) + [0, 0, 2];
            coordinates = [carbon; carbon + [1.23,0,0]; ...
                carbon + [-.65,1.12,0]; carbon + [-1.1,1.9,0]];
            bonds = [1,2,2;1,3,1;3,4,1];
            result = kssolv.modeling.CommandExecutor.execute(host, ...
                "place_adsorbate", struct("anchorSites", anchor, ...
                "adsorbateName", "Carboxyl", ...
                "adsorbateSpecies", ["C","O","O","H"], ...
                "adsorbateCoordinates", coordinates, ...
                "adsorbateBonds", bonds, "anchorAtomIndices", 1, ...
                "minimumDistance", .35));
            testCase.verifyEqual(result.model.num_sites, host.num_sites + 4);
            metadata = result.model.structure_properties.adsorbate;
            testCase.verifyEqual(metadata.schemaVersion, 2);
            testCase.verifyEqual(metadata.name, "Carboxyl");
            testCase.verifyEqual(metadata.species, ["C","O","O","H"]);
            testCase.verifyEqual(metadata.bonds, bonds);
            testCase.verifyEqual(metadata.placementMode, "direct-manipulation");
            testCase.verifyEqual(metadata.hostAnchorSites, anchor);
            testCase.verifyEqual(metadata.anchorAtomIndices, 1);
            testCase.verifyEqual(metadata.hostBondLengths, 2, ...
                "AbsTol", 1e-12);
            testCase.verifyEqual(sort(string(fieldnames(metadata))), ...
                sort(["schemaVersion"; "placementMode"; "name"; ...
                "species"; "coordinates"; "bonds"; ...
                "anchorAtomIndices"; "hostAnchorSites"; ...
                "hostAnchorLabels"; "hostBondLengths"; "guestFormula"]));
        end

        function threeRequiredSlabsMatchFrozenOracle(testCase)
            path=fullfile(KSSOLV_Toolbox.RootDirectory,"dev","modeling", ...
                "acceptance","oracles","surface-builder-v1.json");
            oracle=jsondecode(fileread(path));
            testCase.verifyEqual(numel(oracle.cases),3);
            for index=1:numel(oracle.cases)
                item=oracle.cases(index);
                species=cellstr(string(item.species));
                if isscalar(species), species=species{1}; end
                bulk=kssolv.analysis.matgenlab.core.Structure. ...
                    from_prototype(string(item.prototype),species, ...
                    "a",item.a);
                result=kssolv.modeling.CommandExecutor.execute(bulk, ...
                    "build_slab",struct("millerIndex",item.miller, ...
                    "slabSize",item.slabSize, ...
                    "vacuumSize",item.vacuumSize, ...
                    "centerSlab",true,"primitive",true, ...
                    "terminationIndex",1));
                context="Oracle case "+string(item.name);
                testCase.verifyEqual(result.model.num_sites, ...
                    item.atomCount,context);
                testCase.verifyEqual(string(result.model.reduced_formula), ...
                    string(item.formula),context);
                testCase.verifyEqual(numel(result.analysis.terminations), ...
                    item.terminationCount,context);
                testCase.verifyEqual(result.model.lattice.c,item.c, ...
                    AbsTol=1e-10);
                testCase.verifyEqual( ...
                    kssolv.modeling.provenance.CanonicalHash.of(result.model), ...
                    string(item.hash),context);
            end
        end

