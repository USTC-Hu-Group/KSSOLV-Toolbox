classdef PolymerPackingFunctionalTest < matlab.unittest.TestCase
    methods (Test)
        function builtInPolymersHaveExactCompositionAndState(testCase)
            base=blank();
            for kind=["PE","PP","PS","PEO"]
                result=kssolv.modeling.CommandExecutor.execute(base, ...
                    "build_homopolymer",struct("repeatUnit",kind, ...
                    "repeatCount",5,"seed",17));
                testCase.verifyEqual(result.analysis.repeatUnits,5);
                testCase.verifyEqual(result.analysis.actualCounts,5);
                testCase.verifyEqual(result.analysis.state, ...
                    "constructed_not_equilibrated");
                report=kssolv.modeling.chemistry.MoleculeDiagnostics. ...
                    inspect(result.model);
                testCase.verifyEmpty(report.collisions);
                testCase.verifyFalse(any(string({report.atomIssues.severity})=="error"));
            end
        end

        function userRepeatUnitStoresHeadsTailsAndLeavingAtoms(testCase)
            storePath=string(tempname)+" repeat unit's store.json";
            cleanup=onCleanup(@()deleteIfPresent(storePath)); %#ok<NASGU>
            unit=molecule(["C","C","H"], ...
                [0,0,0;1.5,0,0;2.5,0,0],[1,2,1;2,3,1]);
            saved=kssolv.modeling.CommandExecutor.execute(unit, ...
                "save_user_repeat_unit",struct( ...
                "repeatUnitName","USER_CC","headIndex",1, ...
                "tailIndex",2,"leavingIndices",3, ...
                "storePath",storePath));
            testCase.verifyFalse(saved.changed);
            entry=kssolv.modeling.polymers.RepeatUnitLibrary.get( ...
                "USER_CC",storePath=storePath);
            testCase.verifyEqual(entry.species,["C","C"]);
            testCase.verifyEqual(entry.head,1);
            testCase.verifyEqual(entry.tail,2);
            testCase.verifyEmpty(dir(storePath+".*.tmp"));
            polymer=kssolv.modeling.polymers.PolymerBuilder. ...
                homopolymer("USER_CC",4,storePath=storePath);
            testCase.verifyEqual(polymer.num_sites,26);
        end

        function blockRandomStereoAndBranchesAreReproducible(testCase)
            base=blank();
            block=execute(base,"build_block_copolymer",struct( ...
                "blockKinds","PEO PPO PEO","blockLengths",[3,4,3], ...
                "seed",8));
            testCase.verifyEqual(block.analysis.actualKinds,["PEO","PPO"]);
            testCase.verifyEqual(block.analysis.actualCounts,[6,4]);
            first=execute(base,"build_random_copolymer",struct( ...
                "monomerKinds","PE PP","fractions",[.3,.7], ...
                "repeatCount",20,"exactComposition",true,"seed",91, ...
                "tacticity","syndiotactic"));
            second=execute(base,"build_random_copolymer",struct( ...
                "monomerKinds","PE PP","fractions",[.3,.7], ...
                "repeatCount",20,"exactComposition",true,"seed",91, ...
                "tacticity","syndiotactic"));
            testCase.verifyEqual(first.analysis.actualCounts,[6,14]);
            testCase.verifyEqual(first.analysis.sequence,second.analysis.sequence);
            stereo=cellfun(@double,first.model.site_properties.stereo);
            repeat=cellfun(@double,first.model.site_properties.repeat_unit);
            signs=arrayfun(@(unit)stereo(find(repeat==unit,1)),1:20);
            testCase.verifyEqual(signs,(-1).^(0:19));
            branched=execute(base,"build_branched_polymer",struct( ...
                "repeatCount",10,"branchInterval",3,"seed",5));
            testCase.verifyEqual(branched.analysis.branchCount,3);
        end

        function architectureControlsHaveExactDeterministicSemantics(testCase)
            [multi,info]=kssolv.modeling.polymers.PolymerBuilder. ...
                homopolymer("PE",4,chainCount=3,headGroup="O-H fragment", ...
                tailGroup="Methyl",conformation="zigzag", ...
                headTailMode="alternating",addHydrogens=false);
            chainIds=cellfun(@double,multi.site_properties.chain_id);
            testCase.verifyEqual(unique(chainIds),1:3);
            testCase.verifyEqual(histcounts(chainIds,.5:1:3.5), ...
                repmat(multi.num_sites/3,1,3));
            testCase.verifyEqual(info.headTailFlipped,[false,true,false,true]);
            testCase.verifyEqual(info.conformation,"zigzag");
            testCase.verifyEqual(info.headGroup,"O-H fragment");
            testCase.verifyEqual(info.tailGroup,"Methyl");

            [block,blockInfo]=kssolv.modeling.polymers.PolymerBuilder. ...
                block(["PE","PP"],[2,1],superunitCount=3, ...
                addHydrogens=false);
            testCase.verifyEqual(blockInfo.repeatUnits,9);
            testCase.verifyEqual(blockInfo.sequence, ...
                repmat(["PE","PE","PP"],1,3));
            testCase.verifyGreaterThan(block.num_sites,0);

            [biased,biasedInfo]=kssolv.modeling.polymers.PolymerBuilder. ...
                random(["PE","PP"],200,[.5,.5],seed=29, ...
                exactComposition=false,reactivityRatios=[12,.08], ...
                addHydrogens=false);
            [repeated,repeatedInfo]=kssolv.modeling.polymers.PolymerBuilder. ...
                random(["PE","PP"],200,[.5,.5],seed=29, ...
                exactComposition=false,reactivityRatios=[12,.08], ...
                addHydrogens=false);
            testCase.verifyEqual(biasedInfo.sequence,repeatedInfo.sequence);
            testCase.verifyGreaterThan(biasedInfo.actualCounts(1),100);
            testCase.verifyEqual( ...
                kssolv.modeling.provenance.CanonicalHash.of(biased), ...
                kssolv.modeling.provenance.CanonicalHash.of(repeated));
        end

        function basicDendrimerHasExactGenerationTopology(testCase)
            [heavy,info]=kssolv.modeling.polymers.PolymerBuilder. ...
                dendrimer(2,coreFunctionality=3,branchingFactor=2, ...
                addHydrogens=false,seed=11);
            testCase.verifyEqual(info.generationCounts,[3,6]);
            testCase.verifyEqual(info.heavyAtomCount,10);
            testCase.verifyEqual(heavy.num_sites,10);
            bonds=kssolv.modeling.chemistry.MoleculeDiagnostics. ...
                topology(heavy);
            testCase.verifySize(bonds,[9,3]);
            generations=cellfun(@double,heavy.site_properties.generation);
            testCase.verifyEqual(histcounts(generations,-.5:1:2.5),[1,3,6]);
            built=execute(blank(),"build_dendrimer",struct( ...
                "generations",2,"coreFunctionality",3, ...
                "branchingFactor",2,"seed",11));
            testCase.verifyEqual(built.analysis.architecture,"basic_dendrimer");
            testCase.verifyEqual(built.model.num_sites,32);
        end

        function polymerPreflightEstimatesCoverEveryArchitecture(testCase)
            cases={
                "build_homopolymer",struct("repeatUnit","PE", ...
                    "repeatCount",10,"chainCount",2, ...
                    "headGroup","O-H fragment","tailGroup","Methyl")
                "build_block_copolymer",struct("blockKinds","PEO PPO", ...
                    "blockLengths",[2,3],"superunitCount",2)
                "build_random_copolymer",struct("monomerKinds","PE PP", ...
                    "repeatCount",12)
                "build_branched_polymer",struct("repeatUnit","PE", ...
                    "repeatCount",12,"branchInterval",3, ...
                    "branchFragment","Methyl")
                "build_dendrimer",struct("generations",3, ...
                    "coreFunctionality",3,"branchingFactor",2)
                };
            for row=1:size(cases,1)
                estimate=kssolv.modeling.polymers.PolymerCommands. ...
                    estimate(cases{row,1},cases{row,2});
                testCase.verifyGreaterThan(estimate.estimatedAtoms,0);
                testCase.verifyFalse(estimate.warning);
            end
            large=kssolv.modeling.polymers.PolymerCommands.estimate( ...
                "build_homopolymer",struct("repeatUnit","PE", ...
                "repeatCount",2000));
            testCase.verifyTrue(large.warning);
            testCase.verifyEmpty(kssolv.modeling.polymers.PolymerCommands. ...
                estimate("unknown",struct()));
            testCase.verifyError(@() ...
                kssolv.modeling.polymers.PolymerCommands.estimate( ...
                "build_block_copolymer",struct("blockKinds","PE PP", ...
                "blockLengths",2)),"KSSOLV:Modeling:PolymerBlocks");
        end

        function densityPackingHasCountsContactsSeedAndWorkflowState(testCase)
            water=molecule(["O","H","H"], ...
                [0,0,0;.9572,0,0;-.239,0.927,0],[1,2,1;1,3,1]);
            ethanol=molecule(["C","C","O"], ...
                [0,0,0;1.52,0,0;2.85,.3,0],[1,2,1;2,3,1]);
            [first,info]=kssolv.modeling.packing.PackingBuilder.pack( ...
                {water,ethanol},[20,10],density=.5,seed=22,tolerance=.65);
            [second,~]=kssolv.modeling.packing.PackingBuilder.pack( ...
                {water,ethanol},[20,10],density=.5,seed=22,tolerance=.65);
            testCase.verifyEqual(first.density,.5,AbsTol=5e-12);
            testCase.verifyEqual(info.counts,[20,10]);
            testCase.verifyEqual(info.state,"packed_not_equilibrated");
            testCase.verifyEqual( ...
                kssolv.modeling.provenance.CanonicalHash.of(first), ...
                kssolv.modeling.provenance.CanonicalHash.of(second));
            ids=cellfun(@double,first.site_properties.molecule_id);
            testCase.verifyGreaterThanOrEqual( ...
                minimumIntermolecularDistance(first.cart_coords,ids, ...
                info.boxLength),.65-1e-12);
        end

