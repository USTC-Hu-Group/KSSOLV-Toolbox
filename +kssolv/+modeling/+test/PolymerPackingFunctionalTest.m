        function compositionModesAndWorkflowTemplatesAreExplicit(testCase)
            water=molecule(["O","H","H"], ...
                [0,0,0;.9572,0,0;-.239,0.927,0],[1,2,1;1,3,1]);
            ethanol=molecule(["C","C","O"], ...
                [0,0,0;1.52,0,0;2.85,.3,0],[1,2,1;2,3,1]);
            mole=kssolv.modeling.packing.CompositionCalculator.counts( ...
                {water,ethanol},[.25,.75],"mole_fraction",20);
            testCase.verifyEqual(mole,[5,15]);
            mass=kssolv.modeling.packing.CompositionCalculator.counts( ...
                {water,ethanol},[.5,.5],"mass_fraction",100);
            testCase.verifyEqual(sum(mass),100);
            testCase.verifyGreaterThan(mass(1),mass(2));
            workflow=kssolv.modeling.packing.PackingWorkflowTemplate. ...
                create("density_ramp_npt");
            testCase.verifyEqual(workflow.inputState, ...
                "packed_not_equilibrated");
            testCase.verifyEqual(workflow.engine,"unassigned");
        end

        function ringPiercingFixtureHasZeroFalseNegatives(testCase)
            angles=(0:5).'*pi/3;
            ring=[cos(angles),sin(angles),zeros(6,1)];
            coordinates=[ring;0,0,-1;0,0,1];
            moleculeIds=[ones(1,6),2,2];
            ringBonds=[(1:6).',[2:6,1].',ones(6,1)];
            bonds=[ringBonds;7,8,1];
            hits=kssolv.modeling.packing.PackingDiagnostics. ...
                ringPiercings(coordinates,moleculeIds,bonds,{1:6});
            testCase.verifyNumElements(hits,1);
            safe=coordinates; safe(7:8,1)=2;
            testCase.verifyEmpty(kssolv.modeling.packing.PackingDiagnostics. ...
                ringPiercings(safe,moleculeIds,bonds,{1:6}));
        end

        function existingBoxExclusionRampAndBatchesAreExplicit(testCase)
            container=kssolv.analysis.matgenlab.core.Structure( ...
                diag([20,20,20]),{"Si"},[10,10,10], ...
                coords_are_cartesian=true, ...
                site_properties=struct("fixed",{{true}}));
            helium=molecule("He",[0,0,0],zeros(0,3));
            progress=zeros(0,2);
            [filled,info]=kssolv.modeling.packing.PackingBuilder.packInto( ...
                container,{helium},4,seed=7,tolerance=.4, ...
                exclusionCenter=[10,10,10],exclusionRadius=4, ...
                batchSize=2,progressFcn=@recordProgress);
            testCase.verifyEqual(filled.num_sites,5);
            testCase.verifyEqual(filled.lattice.matrix,diag([20,20,20]));
            testCase.verifyEqual(filled(1).specie.symbol,"Si");
            testCase.verifyTrue(filled.site_properties.fixed{1});
            testCase.verifyEqual(info.containerAtoms,1);
            testCase.verifyEqual(info.addedAtoms,4);
            testCase.verifyEqual(info.batchCount,2);
            testCase.verifyEqual(progress,[1,4;2,4;3,4;4,4]);
            testCase.verifyGreaterThanOrEqual(min(vecnorm( ...
                filled.cart_coords(2:end,:)-[10,10,10],2,2)),4);

            command=execute(container,"pack_into_existing_box",struct( ...
                "components",{{helium}},"counts",2,"tolerance",.4, ...
                "seed",9,"batchSize",1));
            testCase.verifyTrue(command.analysis.preservedExistingBox);
            testCase.verifyEqual(command.model.num_sites,3);

            [~,ramp]=kssolv.modeling.packing.PackingBuilder.pack( ...
                {helium},6,density=.2,tolerance=.1,seed=3, ...
                densityRamp=[.05,.1,.2],batchSize=2);
            testCase.verifyEqual(ramp.densityRamp,[.05,.1,.2]);
            testCase.verifyEqual(ramp.batchCount,3);
            testCase.verifyEqual(numel(ramp.densityStageVolumes),3);
            function recordProgress(done,total)
                progress(end+1,:)=[done,total]; %#ok<AGROW>
            end
        end

        function linkedRingFixtureIsReportedAsChainInterlock(testCase)
            angles=(0:11).'*2*pi/12;
            first=[cos(angles),sin(angles),zeros(12,1)];
            secondAngles=angles+pi/12;
            second=[.5*ones(12,1),.7*cos(secondAngles), ...
                .7*sin(secondAngles)];
            coordinates=[first;second];
            firstBonds=[(1:12).',[2:12,1].',ones(12,1)];
            secondBonds=[(13:24).',[14:24,13].',ones(12,1)];
            hits=kssolv.modeling.packing.PackingDiagnostics. ...
                chainInterlocks(coordinates,[ones(1,12),2*ones(1,12)], ...
                [firstBonds;secondBonds],{1:12,13:24});
            testCase.verifyNotEmpty(hits);
            testCase.verifyEqual(hits(1).molecules,[1,2]);
        end

        function packingCancellationLeavesNoPartialModel(testCase)
            water=molecule(["O","H","H"], ...
                [0,0,0;.9572,0,0;-.239,.927,0],[1,2,1;1,3,1]);
            calls=0; progress=0;
            testCase.verifyError(@() ...
                kssolv.modeling.packing.PackingBuilder.pack( ...
                {water},100,density=.1,tolerance=.1, ...
                cancelFcn=@cancelAfterFive,progressFcn=@countProgress), ...
                "KSSOLV:Modeling:PackingCancelled");
            testCase.verifyEqual(progress,5);
            function value=cancelAfterFive()
                calls=calls+1; value=calls>5;
            end
            function countProgress(~,~), progress=progress+1; end
        end
    end
