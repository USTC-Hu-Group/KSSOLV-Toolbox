        function applyEnvironmentProbe(this, probe)
            this.Widgets.ClusterMatlabRoot.Value = ...
                string(probe.ClusterMatlabRoot);
            if isfield(probe, "RemoteJobStorageLocation") && ...
                    strlength(string( ...
                    probe.RemoteJobStorageLocation)) > 0
                this.Widgets.RemoteJobStorageLocation.Value = ...
                    string(probe.RemoteJobStorageLocation);
            end
            if isfield(probe, "NumWorkers") && ...
                    isfinite(double(probe.NumWorkers)) && ...
                    double(probe.NumWorkers) >= 1
                this.Widgets.NumWorkers.Value = ...
                    floor(double(probe.NumWorkers));
            end
            if isfield(probe, "PoolSize") && ...
                    isfinite(double(probe.PoolSize)) && ...
                    double(probe.PoolSize) >= 0
                this.Widgets.PoolSize.Value = min( ...
                    floor(double(probe.PoolSize)), ...
                    this.Widgets.NumWorkers.Value);
            end
            this.Widgets.TabGroup.SelectedTab = ...
                this.Widgets.ComputeTab;
            this.setResourceProbeStatus(sprintf( ...
                remoteMessage("RemoteEnvironmentProbeSucceeded"), ...
                probe.Hostname, probe.MatlabRelease, ...
                probe.ClusterMatlabRoot, probe.NumWorkers, ...
                probe.PoolSize), false);
        end

        function updateConditionalControls(this)
            if this.SelectedIndex == 0
                return
            end
            mode = string(this.Widgets.ExecutionMode.Value);
            standard = mode == "Standard";
            bridge = mode == "Bridge";
            mirror = mode == "Mirror";
            cloud = mode == "Cloud";
            routed = standard || bridge || mirror;

            if bridge || mirror
                this.Widgets.ConnectionMode.Value = "SSH";
            elseif cloud
                this.Widgets.ProfileSource.Value = ...
                    "ExistingMatlabProfile";
                this.Widgets.ConnectionMode.Value = "Direct";
                this.Widgets.PostLoginScript.Value = {''};
                this.Widgets.PostLoginCommandTemplate.Value = ...
                    {'{command}'};
                this.Widgets.PostLoginPromptRules.Data = table( ...
                    strings(0, 1), strings(0, 1), ...
                    VariableNames=["Pattern", "CredentialLabel"]);
            end
            managed = this.Widgets.ProfileSource.Value == "ManagedSlurm";
            ssh = this.Widgets.ConnectionMode.Value == "SSH";
            identity = this.Widgets.AuthenticationMode.Value == ...
                "IdentityFile";
            automatedMfa = routed && ssh && ...
                this.Widgets.AuthenticationMode.Value == "Multifactor";
            storedPassword = routed && ssh && any( ...
                this.Widgets.AuthenticationMode.Value == ...
                ["Password", "Multifactor"]);
            rememberTotpSecret = automatedMfa && ...
                this.Widgets.RememberTotpSecret.Value;
            if ~storedPassword
                this.clearCredentialInputs();
            elseif ~rememberTotpSecret
                setPasswordValue(this.Widgets.TotpSecretInput, "");
            end
            installed = this.Widgets.CodeDeploymentMode.Value == ...
                "ClusterInstalled";
            onlineLicensing = this.Widgets.RequiresOnlineLicensing.Value;
            this.updateFieldVisibility();
            set(this.Widgets.CloudProvider, "Enable", onOff(cloud));
            set(this.Widgets.CloudResourceName, "Enable", onOff(cloud));
            set(this.Widgets.CloudRegion, "Enable", onOff(cloud));
            set(this.Widgets.ProfileSource, "Enable", onOff(standard));
            set(this.Widgets.ConnectionMode, "Enable", ...
                onOff(standard));
            set(this.Widgets.Host, "Enable", ...
                onOff(routed && ssh));
            set(this.Widgets.Username, "Enable", ...
                onOff(routed && ssh));
            set(this.Widgets.AuthenticationMode, "Enable", ...
                onOff(routed && ssh));
            set(this.Widgets.IdentityFile, "Enable", ...
                onOff(routed && ssh && identity));
            set(this.Widgets.RememberTotpSecret, "Enable", ...
                onOff(automatedMfa));
            setPasswordEnabled(this.Widgets.PasswordInput, storedPassword);
            setPasswordEnabled(this.Widgets.TotpSecretInput, ...
                rememberTotpSecret);
            set(this.Widgets.ExistingProfileName, "Enable", ...
                onOff(cloud || (standard && ~managed)));
            set(this.Widgets.DiscoverProfiles, "Enable", ...
                onOff(cloud || (standard && ~managed)));
            set(this.Widgets.RemoteBridgeProfileName, "Enable", ...
                onOff(bridge));
            set(this.Widgets.ClusterMatlabRoot, "Enable", ...
                onOff(bridge || mirror || (standard && managed)));
            set(this.Widgets.RemoteJobStorageLocation, "Enable", ...
                onOff(routed && ssh));
            set(this.Widgets.PostLoginScript, "Enable", onOff(routed));
            set(this.Widgets.PostLoginCommandTemplate, "Enable", ...
                onOff(routed));
            set(this.Widgets.PostLoginPromptRules, "Enable", ...
                onOff(routed));
            set(this.Widgets.AddPromptRule, "Enable", onOff(routed));
            set(this.Widgets.RemovePromptRule, "Enable", onOff(routed));
            directManaged = standard && managed;
            names = ["Partition", "Account", "QoS", "Walltime", ...
                "AdditionalSubmitArgs", "HasSharedFilesystem", ...
                "RequiresOnlineLicensing"];
            for name = names
                set(this.Widgets.(name), "Enable", onOff(directManaged));
            end
            set(this.Widgets.RemoteKssolvRoot, "Enable", onOff(installed));
            set(this.Widgets.LicenseNumber, "Enable", ...
                onOff(directManaged && onlineLicensing));
        end

        function updateFieldVisibility(this)
            mode = string(this.Widgets.ExecutionMode.Value);
            managed = this.Widgets.ProfileSource.Value == "ManagedSlurm";
            ssh = this.Widgets.ConnectionMode.Value == "SSH";
            identity = this.Widgets.AuthenticationMode.Value == ...
                "IdentityFile";
            installed = this.Widgets.CodeDeploymentMode.Value == ...
