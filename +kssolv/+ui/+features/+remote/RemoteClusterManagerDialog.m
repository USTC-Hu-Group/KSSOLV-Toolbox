        function validateCredentialSetup(this, configuration)
            if ~any(configuration.ExecutionMode == ...
                    ["Standard", "Bridge", "Mirror"]) || ...
                    configuration.ConnectionMode ~= "SSH" || ...
                    ~any(configuration.AuthenticationMode == ...
                    ["Password", "Multifactor"])
                return
            end
            if strlength(configuration.EncryptedPassword) == 0
                error("KSSOLV:Remote:UI:StoredPasswordRequired", ...
                    remoteMessage("RemoteStoredPasswordRequired"));
            end
            this.CredentialCipher.decrypt( ...
                configuration.EncryptedPassword);
            if configuration.AuthenticationMode == "Multifactor" && ...
                    configuration.RememberTotpSecret
                if strlength(configuration.EncryptedTotpSecret) == 0
                    error("KSSOLV:Remote:UI:StoredTotpRequired", ...
                        remoteMessage("RemoteStoredTotpRequired"));
                end
                secret = this.CredentialCipher.decrypt( ...
                    configuration.EncryptedTotpSecret);
                kssolv.services.remote.security.Totp.generate(secret);
            end
        end

