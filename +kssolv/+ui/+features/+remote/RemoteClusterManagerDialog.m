function rules = promptRulesFromTable(data)
rules = repmat(struct("Pattern", "", "CredentialLabel", ""), 0, 1);
for index = 1:height(data)
    pattern = strip(string(data.Pattern(index)));
    label = strip(string(data.CredentialLabel(index)));
    if strlength(pattern) == 0 && strlength(label) == 0
        continue
    end
    rules(end + 1, 1) = struct( ...
        "Pattern", pattern, "CredentialLabel", label); %#ok<AGROW>
end
end

