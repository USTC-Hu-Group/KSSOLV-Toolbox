                grid.RowHeight = rowHeights;
                children = grid.Children;
                for index = 1:numel(children)
                    row = children(index).Layout.Row;
                    setComponentTreeVisible(children(index), ...
                        all(visibleRows{tab}(row)));
                end
            end
        end

