    methods
        function this = RemoteClusterManagerDialog(options)
            arguments
                options.ConfigurationStore = ...
                    kssolv.services.remote.config.RemoteConfigurationStore()
                options.SelectionStore = ...
                    kssolv.services.remote.config.RemoteSelectionStore()
                options.CredentialCipher = ...
                    kssolv.services.remote.security.LocalCredentialCipher()
                options.Visible (1, 1) logical = true
            end
            this.ConfigurationStore = options.ConfigurationStore;
            this.SelectionStore = options.SelectionStore;
            this.CredentialCipher = options.CredentialCipher;
            this.buildUI();
            this.reload();
            if options.Visible
                kssolv.ui.util.DialogWindow.showCentered(this.Figure);
            else
                movegui(this.Figure, "center");
            end
        end

        function delete(this)
            this.stopConnectionTest(true);
            this.stopResourceProbe(true);
            this.clearCredentialInputs();
            if ~isempty(this.Figure) && isvalid(this.Figure)
                delete(this.Figure);
            end
        end

        function reload(this)
            this.Configurations = this.ConfigurationStore.list();
            this.refreshTable();
            if isempty(this.Configurations)
                this.SelectedIndex = 0;
                this.setEditorEnabled(false);
                return
            end
            this.selectIndex(min(max(this.SelectedIndex, 1), ...
                numel(this.Configurations)));
        end

        function configuration = saveCurrent(this)
            if this.SelectedIndex < 1 || ...
                    this.SelectedIndex > numel(this.Configurations)
                error("KSSOLV:Remote:UI:NoConfigurationSelected", ...
                    remoteMessage("RemoteNoConfigurationSelected"));
            end
            configuration = this.readEditor( ...
                this.Configurations(this.SelectedIndex));
            configuration = this.applyCredentialInputs(configuration);
            configuration = kssolv.services.remote.config.RemoteConfiguration. ...
                create(configuration);
            this.validateCredentialSetup(configuration);
            this.ConfigurationStore.upsert(configuration);
            this.Configurations(this.SelectedIndex) = configuration;
            this.clearCredentialInputs();
            this.refreshTable();
            this.selectIndex(this.SelectedIndex);
            this.setConfigurationStatus( ...
                remoteMessage("RemoteConfigurationSaved"), false);
        end
    end

