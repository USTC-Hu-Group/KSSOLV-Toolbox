                case "Standard"
                    visibleFields = [visibleFields, "ProfileSource", ...
                        "ConnectionMode", "PostLoginScript", ...
                        "PostLoginCommandTemplate", ...
                        "PostLoginPromptRules", "NumWorkers", "PoolSize"];
