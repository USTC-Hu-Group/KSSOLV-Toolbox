        function refreshTable(this)
            configurations = this.Configurations;
            if isempty(configurations)
                data = table(false(0, 1), strings(0, 1), ...
                    strings(0, 1), ...
                    VariableNames=["Enabled", "Name", "Mode"]);
            else
                data = table(logical([configurations.Enabled]).', ...
                    string({configurations.DisplayName}).', ...
                    string({configurations.ExecutionMode}).', ...
                    VariableNames=["Enabled", "Name", "Mode"]);
            end
            this.Widgets.Table.Data = data;
            this.Widgets.Table.ColumnName = [ ...
                remoteMessage("RemoteEnabled")
                remoteMessage("RemoteDisplayName")
                remoteMessage("RemoteExecutionMode")];
        end

        function tableSelectionChanged(this, event)
            if isempty(event.Indices)
                return
            end
            this.selectIndex(event.Indices(1));
        end

        function selectIndex(this, index)
            if index < 1 || index > numel(this.Configurations)
                return
            end
            this.SelectedIndex = index;
            this.Widgets.Table.Selection = [index, 1];
            this.writeEditor(this.Configurations(index));
            this.setEditorEnabled(true);
            this.updateConditionalControls();
            this.setConnectionStatus("", false);
            this.setResourceProbeStatus("", false);
        end

        function writeEditor(this, value)
            this.clearCredentialInputs();
            this.Widgets.PostLoginScript.Value = ...
                cellstr(splitlines(string(value.PostLoginScript)));
            this.Widgets.PostLoginCommandTemplate.Value = ...
                cellstr(splitlines(string(value.PostLoginCommandTemplate)));
            rules = value.PostLoginPromptRules;
            if isempty(rules)
                this.Widgets.PostLoginPromptRules.Data = table( ...
                    strings(0, 1), strings(0, 1), ...
                    VariableNames=["Pattern", "CredentialLabel"]);
            else
                this.Widgets.PostLoginPromptRules.Data = table( ...
                    string({rules.Pattern}).', ...
                    string({rules.CredentialLabel}).', ...
                    VariableNames=["Pattern", "CredentialLabel"]);
            end
            names = fieldnames(this.Widgets);
            valueNames = fieldnames(value);
            for index = 1:numel(valueNames)
                name = valueNames{index};
                if any(string(name) == ...
                        ["PostLoginScript", "PostLoginCommandTemplate", ...
                        "PostLoginPromptRules"])
                    continue
                end
                if any(strcmp(names, name)) && ...
                        isprop(this.Widgets.(name), "Value")
                    this.Widgets.(name).Value = value.(name);
                end
            end
        end

        function value = readEditor(this, value)
            names = ["DisplayName", "Enabled", "ExecutionMode", ...
                "CloudProvider", "CloudResourceName", "CloudRegion", ...
                "ProfileSource", ...
                "ConnectionMode", "Host", "Username", ...
                "AuthenticationMode", "IdentityFile", ...
                "RememberTotpSecret", ...
                "ExistingProfileName", "RemoteBridgeProfileName", ...
                "ClusterMatlabRoot", ...
                "RemoteJobStorageLocation", "NumWorkers", "PoolSize", ...
                "Partition", "Account", "QoS", "Walltime", ...
                "AdditionalSubmitArgs", "CodeDeploymentMode", ...
                "RemoteKssolvRoot", "HasSharedFilesystem", ...
                "RequiresOnlineLicensing", "LicenseNumber"];
            for name = names
                value.(name) = this.Widgets.(name).Value;
            end
            value.PostLoginCommandTemplate = join(string( ...
                this.Widgets.PostLoginCommandTemplate.Value), newline);
            value.PostLoginScript = join(string( ...
                this.Widgets.PostLoginScript.Value), newline);
            value.PostLoginPromptRules = promptRulesFromTable( ...
                this.Widgets.PostLoginPromptRules.Data);
            if ~value.RememberTotpSecret
                value.EncryptedTotpSecret = "";
            end
            if ~any(value.AuthenticationMode == ...
                    ["Password", "Multifactor"])
                value.EncryptedPassword = "";
                value.EncryptedTotpSecret = "";
            elseif value.AuthenticationMode == "Password"
                value.RememberTotpSecret = false;
                value.EncryptedTotpSecret = "";
            end
        end

        function value = applyCredentialInputs(this, value)
            storedPassword = any(value.ExecutionMode == ...
                ["Standard", "Bridge", "Mirror"]) && ...
                value.ConnectionMode == "SSH" && ...
                any(value.AuthenticationMode == ...
                ["Password", "Multifactor"]);
            if ~storedPassword
                return
            end

            password = passwordValue(this.Widgets.PasswordInput);
            if strlength(password) > 0
                value.EncryptedPassword = ...
                    this.CredentialCipher.encrypt(password);
            end
            if value.AuthenticationMode == "Multifactor" && ...
                    value.RememberTotpSecret
                totpSecret = passwordValue( ...
                    this.Widgets.TotpSecretInput);
                if strlength(totpSecret) > 0
                    kssolv.services.remote.security.Totp.generate(totpSecret);
                    value.EncryptedTotpSecret = ...
                        this.CredentialCipher.encrypt(totpSecret);
                end
            else
                value.EncryptedTotpSecret = "";
            end
        end

        function clearCredentialInputs(this)
            names = ["PasswordInput", "TotpSecretInput"];
            for name = names
                if isfield(this.Widgets, name) && ...
                        isvalid(this.Widgets.(name))
                    setPasswordValue(this.Widgets.(name), "");
                end
            end
        end

        function addConfiguration(this)
            value = kssolv.services.remote.config.RemoteConfiguration.defaults();
            value.DisplayName = remoteMessage("RemoteNewConfiguration");
            this.Configurations(end + 1, 1) = value;
            this.refreshTable();
            this.selectIndex(numel(this.Configurations));
            this.setConfigurationStatus( ...
                remoteMessage("RemoteCompleteAndSave"), false);
        end

        function duplicateConfiguration(this)
            try
                saved = this.saveCurrent();
                duplicate = this.ConfigurationStore.duplicate(saved.Id);
                this.reload();
                ids = string({this.Configurations.Id});
                this.selectIndex(find(ids == duplicate.Id, 1));
            catch exception
                this.setConfigurationStatus(exception.message, true);
            end
        end

        function deleteConfiguration(this)
            if this.SelectedIndex < 1 || ...
                    this.SelectedIndex > numel(this.Configurations)
                return
            end
            value = this.Configurations(this.SelectedIndex);
            try
                referencedJobs = kssolv.services.remote.job.RemoteJobStore().list();
                if ~isempty(referencedJobs) && any( ...
                        string({referencedJobs.ConfigurationId}) == value.Id)
                    error("KSSOLV:Remote:UI:ConfigurationInUse", ...
                        remoteMessage("RemoteConfigurationInUse"));
                end
                if value.ExecutionMode == "Standard" && ...
                        value.ProfileSource == "ManagedSlurm" && ...
                        strlength(value.ManagedProfileName) > 0
                    kssolv.services.remote.cluster.ClusterFactory(). ...
                        removeManagedProfile(value);
                end
                this.ConfigurationStore.remove(value.Id);
                selected = this.SelectionStore.get(this.ConfigurationStore);
                if selected == value.Id
                    this.SelectionStore.set("");
                end
                this.SelectedIndex = max(1, this.SelectedIndex - 1);
                this.reload();
                this.setConfigurationStatus(remoteMessage( ...
                    "RemoteConfigurationDeleted"), false);
            catch exception
                this.setConfigurationStatus(exception.message, true);
            end
        end

