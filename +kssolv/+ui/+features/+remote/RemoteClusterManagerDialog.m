                            "QoS", "Walltime", "AdditionalSubmitArgs", ...
                            "HasSharedFilesystem", ...
                            "RequiresOnlineLicensing"];
                        if onlineLicensing
                            visibleFields(end + 1) = "LicenseNumber";
                        end
                    else
                        visibleFields(end + 1) = "ExistingProfileName";
                    end
                case "Bridge"
                    visibleFields = [visibleFields, "Host", "Username", ...
                        "AuthenticationMode", ...
                        "RemoteBridgeProfileName", "ClusterMatlabRoot", ...
                        "RemoteJobStorageLocation", ...
                        "PostLoginScript", ...
                        "PostLoginCommandTemplate", ...
                        "PostLoginPromptRules", "NumWorkers", "PoolSize"];
                    if identity
                        visibleFields(end + 1) = "IdentityFile";
                    end
                case "Mirror"
                    visibleFields = [visibleFields, "Host", "Username", ...
                        "AuthenticationMode", "ClusterMatlabRoot", ...
                        "RemoteJobStorageLocation", ...
                        "PostLoginScript", ...
                        "PostLoginCommandTemplate", ...
                        "PostLoginPromptRules", "NumWorkers", "PoolSize"];
                    if identity
                        visibleFields(end + 1) = "IdentityFile";
                    end
                case "Cloud"
                    visibleFields = [visibleFields, "CloudProvider", ...
                        "CloudResourceName", "CloudRegion", ...
                        "ExistingProfileName", "NumWorkers", "PoolSize"];
            end
            storedPassword = any(mode == ...
                ["Standard", "Bridge", "Mirror"]) && ssh && ...
                any(this.Widgets.AuthenticationMode.Value == ...
                ["Password", "Multifactor"]);
            automatedMfa = storedPassword && ...
                this.Widgets.AuthenticationMode.Value == "Multifactor";
