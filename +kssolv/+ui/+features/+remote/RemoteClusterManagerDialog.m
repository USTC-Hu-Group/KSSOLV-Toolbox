        function pollResourceProbe(this)
            session = this.ResourceProbeSession;
            if isempty(session) || ~isvalid(session)
                return
            end
            state = session.poll();
            switch state
                case "Queued"
                    this.setResourceProbeStatus(connectionProgressMessage( ...
                        session, "RemoteEnvironmentProbeQueued"), false);
                case "Running"
                    this.setResourceProbeStatus(connectionProgressMessage( ...
                        session, "RemoteEnvironmentProbeRunning"), false);
                case "Succeeded"
                    this.applyEnvironmentProbe(session.Report.Probe);
                    this.setResourceProbeRunning(false);
                    drawnow;
                    this.stopResourceProbe(false);
                case "Failed"
                    this.setResourceProbeStatus(connectionStatusMessage( ...
                        session.ErrorIdentifier, ...
                        session.ErrorSummary, false), true);
                    this.setResourceProbeRunning(false);
                    drawnow;
                    this.stopResourceProbe(false);
                case "Cancelled"
                    this.setResourceProbeStatus(remoteMessage( ...
                        "RemoteResourceProbeCancelled"), false);
                    this.setResourceProbeRunning(false);
                    drawnow;
                    this.stopResourceProbe(false);
            end
        end

        function cancelResourceProbe(this)
            if isempty(this.ResourceProbeSession) || ...
                    ~isvalid(this.ResourceProbeSession)
                return
            end
            this.setResourceProbeStatus(remoteMessage( ...
                "RemoteCancellingResourceProbe"), false);
            this.Widgets.CancelResourceProbe.Enable = "off";
            drawnow;
            this.ResourceProbeSession.cancel();
            this.pollResourceProbe();
        end

        function stopResourceProbe(this, cancelActive)
            arguments
                this
                cancelActive (1, 1) logical
            end
            if ~isempty(this.ResourceProbeTimer) && ...
                    isvalid(this.ResourceProbeTimer)
                stop(this.ResourceProbeTimer);
                delete(this.ResourceProbeTimer);
            end
            this.ResourceProbeTimer = [];
            if ~isempty(this.ResourceProbeSession) && ...
                    isvalid(this.ResourceProbeSession)
                if cancelActive && ~any( ...
                        this.ResourceProbeSession.State == ...
                        this.ResourceProbeSession.TerminalStates)
                    this.ResourceProbeSession.cancel();
                end
                this.ResourceProbeSession.cleanup();
            end
        end

        function cancelConnectionTest(this)
            if isempty(this.ConnectionTestSession) || ...
                    ~isvalid(this.ConnectionTestSession)
                return
            end
            this.setConnectionStatus(remoteMessage( ...
                "RemoteCancellingConnectionTest"), false);
            this.Widgets.CancelTest.Enable = "off";
            drawnow;
            this.ConnectionTestSession.cancel();
            this.pollConnectionTest();
        end

