        function testConnection(this)
            try
                if this.SelectedIndex < 1 || ...
                        this.SelectedIndex > numel(this.Configurations)
                    error("KSSOLV:Remote:UI:NoConfigurationSelected", ...
                        remoteMessage("RemoteNoConfigurationSelected"));
                end
                value = this.readEditor( ...
                    this.Configurations(this.SelectedIndex));
                value = this.applyCredentialInputs(value);
                mode = string(value.ExecutionMode);
                sshLogin = any(mode == ["Bridge", "Mirror"]) || ...
                    (mode == "Standard" && ...
                    string(value.ProfileSource) == "ManagedSlurm" && ...
                    string(value.ConnectionMode) == "SSH");
                if sshLogin
                    value = kssolv.services.remote.diagnostics. ...
                        RemoteLoginTest.prepareConfiguration(value);
                    this.validateCredentialSetup(value);
                    session = kssolv.services.remote.diagnostics. ...
                        RemoteLoginTestSession(value, ...
                        this.CredentialCipher.KeyRoot);
                else
                    value = kssolv.services.remote.config.RemoteConfiguration. ...
                        create(value);
                    this.validateCredentialSetup(value);
                    session = createConnectionTestSession(value, false);
                end
                this.setConnectionStatus( ...
                    remoteMessage("RemoteTestingConnection"), false);
                this.setConnectionTestRunning(true);
                drawnow;
                this.ConnectionTestSession = session;
                this.ConnectionTestSession.start();
                this.ConnectionTestTimer = timer( ...
                    "ExecutionMode", "fixedSpacing", ...
                    "Period", 0.25, ...
                    "BusyMode", "drop", ...
                    "TimerFcn", @(~, ~) this.pollConnectionTest());
                start(this.ConnectionTestTimer);
            catch exception
                this.stopConnectionTest(false);
                this.setConnectionTestRunning(false);
                this.setConnectionStatus(connectionStatusMessage( ...
                    exception.identifier, exception.message, true), true);
            end
        end

        function discoverProfiles(this)
            try
                mode = string(this.Widgets.ExecutionMode.Value);
                if mode == "Cloud"
                    backend = kssolv.services.remote.backend.CloudBackend();
                    profiles = backend.discoverProfiles( ...
                        string(this.Widgets.CloudProvider.Value));
                    profiles = profiles([profiles.Available]);
                    names = string({profiles.Name});
                else
                    names = string(parallel.listProfiles());
                end
                names = unique(names(strlength(names) > 0), "stable");
                if isempty(names)
                    this.setConfigurationStatus(remoteMessage( ...
                        "RemoteNoProfilesDiscovered"), true);
                    return
                end
                current = string(this.Widgets.ExistingProfileName.Value);
                initial = find(names == current, 1);
                if isempty(initial)
                    initial = 1;
                end
                [selection, accepted] = listdlg( ...
                    "PromptString", char(remoteMessage( ...
                    "RemoteChooseProfile")), ...
                    "ListString", cellstr(names), ...
                    "SelectionMode", "single", ...
                    "InitialValue", initial, ...
                    "Name", char(remoteMessage("RemoteDiscoverProfiles")));
                if accepted
                    this.Widgets.ExistingProfileName.Value = ...
                        names(selection);
                    this.setConfigurationStatus("", false);
                end
            catch exception
                this.setConfigurationStatus(exception.message, true);
            end
        end

        function pollConnectionTest(this)
            session = this.ConnectionTestSession;
            if isempty(session) || ~isvalid(session)
                return
            end
            state = session.poll();
            switch state
                case "Queued"
                    if isa(session, ...
                            "kssolv.services.remote.diagnostics.RemoteLoginTestSession")
                        key = "RemoteLoginTestQueued";
                    else
                        key = "RemoteConnectionTestQueued";
                    end
                    this.setConnectionStatus(connectionProgressMessage( ...
                        session, key), false);
                case "Running"
                    if isa(session, ...
                            "kssolv.services.remote.diagnostics.RemoteLoginTestSession")
                        key = "RemoteLoginTestRunning";
                    else
                        key = "RemoteConnectionTestRunning";
                    end
                    this.setConnectionStatus(connectionProgressMessage( ...
                        session, key), false);
                case "Succeeded"
                    if isa(session, ...
                            "kssolv.services.remote.diagnostics.RemoteLoginTestSession")
                        this.setConnectionStatus(sprintf( ...
                            remoteMessage("RemoteLoginTestSucceeded"), ...
                            session.Report.Hostname), false);
                    else
                        this.setConnectionStatus(sprintf( ...
                            remoteMessage("RemoteProfileConnectionSucceeded"), ...
                            session.Report.ProfileName, ...
                            session.Report.Connection.Hostname), false);
                    end
                    this.setConnectionTestRunning(false);
                    drawnow;
                    this.stopConnectionTest(false);
                case "Failed"
                    this.setConnectionStatus(connectionStatusMessage( ...
                        session.ErrorIdentifier, ...
                        session.ErrorSummary, false), true);
                    this.setConnectionTestRunning(false);
                    drawnow;
                    this.stopConnectionTest(false);
                case "Cancelled"
                    this.setConnectionStatus(remoteMessage( ...
                        "RemoteConnectionTestCancelled"), false);
                    this.setConnectionTestRunning(false);
                    drawnow;
                    this.stopConnectionTest(false);
            end
        end

