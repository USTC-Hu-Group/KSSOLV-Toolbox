function value = connectionProgressMessage(session, fallbackKey)
key = string(fallbackKey);
if isa(session, ...
        "kssolv.services.remote.diagnostics.RemoteEnvironmentProbeSession")
    switch string(session.Phase)
        case "Connecting"
            key = "RemoteEnvironmentConnecting";
        case "PostLoginAndDiscovery"
            key = "RemoteEnvironmentPostLoginAndDiscovery";
        case "Cancelling"
            key = "RemoteCancellingConnectionTest";
    end
elseif isa(session, ...
        "kssolv.services.remote.diagnostics.RemoteLoginTestSession")
    switch string(session.Phase)
        case "Connecting"
            key = "RemoteEnvironmentConnecting";
        case "PostLogin"
            key = "RemoteLoginPostLoginRunning";
        case "Cancelling"
            key = "RemoteCancellingConnectionTest";
    end
end
value = remoteMessage(key);
if isprop(session, "StartedAt") && ...
        ~isempty(session.StartedAt) && ~isnat(session.StartedAt)
    elapsed = max(0, floor(seconds(datetime("now") - ...
        session.StartedAt)));
    value = value + " " + sprintf( ...
        remoteMessage("RemoteConnectionElapsed"), elapsed);
end
end

function value = connectionStatusMessage(identifier, detail, beforeStart)
identifier = string(identifier);
detail = strip(string(detail));
combined = lower(identifier + " " + detail);
if beforeStart
    key = "RemoteConnectionNotStarted";
elseif contains(combined, lower( ...
        "KSSOLV:Remote:PostLoginScriptFailed"))
    key = "RemoteConnectionSucceededScriptFailed";
elseif any(contains(combined, lower( ...
        ["KSSOLV:Remote:EnvironmentProbeFailed", ...
        "KSSOLV:Remote:EnvironmentProbeInvalidOutput"])))
    key = "RemoteConnectionSucceededProbeFailed";
elseif contains(combined, lower( ...
        "KSSOLV:Remote:EnvironmentConnectionFailed"))
    key = "RemoteConnectionFailed";
else
    key = "RemoteConnectionFailed";
end
value = remoteMessage(key);
if strlength(detail) > 0
    value = value + " " + sprintf( ...
        remoteMessage("RemoteConnectionDiagnosticDetail"), detail);
end
end
