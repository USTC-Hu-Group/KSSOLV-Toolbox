        function presentationCatalogCoversEveryCommand(testCase)
            testCase.verifyWarningFree(@() ...
                kssolv.ui.features.modeling.CommandPresentationCatalog.validate());
            commandIds = kssolv.modeling.CommandCatalog.commandIds();
            testCase.verifyEqual(numel( ...
                kssolv.ui.features.modeling.CommandPresentationCatalog. ...
                iconNames()), numel(commandIds));
            for index = 1:numel(commandIds)
                commandId = commandIds(index);
                assetId = ...
                    kssolv.ui.features.modeling.CommandPresentationCatalog. ...
                    iconName(commandId);
                verifyAsset(assetId, @(size) ...
                    kssolv.ui.features.modeling.CommandPresentationCatalog. ...
                    icon(commandId, size));
            end
            categoryIds = ...
                kssolv.ui.features.modeling.CommandPresentationCatalog. ...
                categoryIds();
            for index = 1:numel(categoryIds)
                categoryId = categoryIds(index);
                verifyAsset("category_" + categoryId, @(size) ...
                    kssolv.ui.features.modeling.CommandPresentationCatalog. ...
                    categoryIcon(categoryId, size));
            end
            utilityIds = ...
                kssolv.ui.features.modeling.CommandPresentationCatalog. ...
                utilityIds();
            for index = 1:numel(utilityIds)
                utilityId = utilityIds(index);
                verifyAsset("history_" + utilityId, @(size) ...
                    kssolv.ui.features.modeling.CommandPresentationCatalog. ...
                    utilityIcon(utilityId, size));
            end

            function verifyAsset(assetId, iconFactory)
                masterPath = kssolv.ui.features.modeling. ...
                    CommandPresentationCatalog.sourceAssetPath( ...
                    assetId, 64);
                testCase.verifyTrue(isfile(masterPath));
                markup = string(fileread(masterPath));
                testCase.verifyTrue(contains(markup, 'width="64"'));
                testCase.verifyTrue(contains(markup, 'height="64"'));
                for size = [16, 24]
                    iconPath = kssolv.ui.features.modeling. ...
                        CommandPresentationCatalog.assetPath( ...
                        assetId, size);
                    testCase.verifyTrue(isfile(iconPath));
                    metadata = imfinfo(iconPath);
                    testCase.verifyEqual( ...
                        [metadata.Width, metadata.Height], [size, size]);
                    icon = iconFactory(size);
                    testCase.verifyClass(icon, ...
                        "matlab.ui.internal.toolstrip.Icon");
                    testCase.verifyTrue(startsWith( ...
                        string(icon.getIconClass()), ...
                        "data:image/svg+xml;base64,"));
                end
            end
        end

