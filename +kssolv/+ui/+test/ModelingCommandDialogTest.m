        function everyCommandDialogAcceptsItsDefaultForm(testCase)
            [app, display] = testCase.createDisplay();
            cleanup = onCleanup(@()testCase.cleanupDisplay(app));
            commandIds = kssolv.modeling.CommandCatalog.commandIds();

            for index = 1:numel(commandIds)
                commandId = commandIds(index);
                commandInfo = ...
                    kssolv.modeling.CommandCatalog.find(commandId);
                fields = ...
                    kssolv.ui.features.modeling.ParameterSchema.forCommand( ...
                    commandId, display);
                preset = testCase.referencePreset(fields);
                dialog = kssolv.ui.features.modeling.CommandDialog( ...
                    commandInfo, display, preset);
                dialogCleanup = onCleanup(@()deleteIfValid(dialog));

                callback = ...
                    dialog.Widgets.ApplyButton.ButtonPushedFcn;
                callback([], []);
                parameters = dialog.Parameters;
                cancelled = dialog.Cancelled;

                testCase.verifyFalse(cancelled, ...
                    "Default form did not apply for " + commandId);
                testCase.verifyClass(parameters, "struct");
                clear dialogCleanup
            end
            clear cleanup

            function deleteIfValid(value)
                if ~isempty(value) && isvalid(value)
                    delete(value);
                end
            end
        end

        function commandDialogSupportsAppContainerModalHost(testCase)
            [app, display] = testCase.createDisplay();
            cleanup = onCleanup(@()testCase.cleanupDisplay(app));
            commandInfo = ...
                kssolv.modeling.CommandCatalog.find("translate_atoms");
            dialog = kssolv.ui.features.modeling.CommandDialog( ...
                commandInfo, display, struct());
            dialogCleanup = onCleanup(@()deleteIfValid(dialog));
            dialogFigure = dialog.getWidget();
            testCase.verifyEqual( ...
                string(dialogFigure.WindowStyle), "modal");
            cancelCallback = dialog.Widgets.CancelButton.ButtonPushedFcn;
            closeTimer = timer( ...
                "StartDelay", 0.1, ...
                "TimerFcn", @(~, ~)cancelCallback([], []));
            timerCleanup = onCleanup(@()deleteTimer(closeTimer));

            start(closeTimer);
            [parameters, cancelled] = dialog.show(app);

            testCase.verifyTrue(cancelled);
            testCase.verifyEmpty(fieldnames(parameters));
            clear timerCleanup dialogCleanup cleanup

            function deleteIfValid(value)
                if ~isempty(value) && isvalid(value)
                    delete(value);
                end
            end

            function deleteTimer(value)
                if isvalid(value)
                    stop(value);
                    delete(value);
                end
            end
        end

        function defectAndQuantumPresetsControlVisibleFields(testCase)
            [app, display] = testCase.createDisplay();
            cleanup = onCleanup(@()testCase.cleanupDisplay(app));

            vacancy = testCase.createDialog( ...
                display, "create_point_defects", ...
                struct("defectType", "vacancy"));
            vacancyCleanup = onCleanup(@()delete(vacancy));
            testCase.verifyEqual( ...
                string(vacancy.Widgets.indices.Visible), "on");
            testCase.verifyEqual( ...
                string(vacancy.Widgets.species.Visible), "off");
            testCase.verifyEqual( ...
                string(vacancy.Widgets.coordinates.Visible), "off");
            clear vacancyCleanup

            interstitial = testCase.createDialog( ...
                display, "create_point_defects", ...
                struct("defectType", "interstitial"));
            interstitialCleanup = onCleanup(@()delete(interstitial));
            testCase.verifyEqual( ...
                string(interstitial.Widgets.indices.Visible), "off");
            testCase.verifyEqual( ...
                string(interstitial.Widgets.species.Visible), "on");
            testCase.verifyEqual( ...
                string(interstitial.Widgets.coordinates.Visible), "on");
            clear interstitialCleanup

            dot = testCase.createDialog( ...
                display, "quantum_dot_void", struct("mode", "dot"));
            dotCleanup = onCleanup(@()delete(dot));
            testCase.verifyEqual( ...
                string(dot.Widgets.vacuum.Visible), "on");
            clear dotCleanup

            void = testCase.createDialog( ...
                display, "quantum_dot_void", struct("mode", "void"));
            voidCleanup = onCleanup(@()delete(void));
            testCase.verifyEqual( ...
                string(void.Widgets.vacuum.Visible), "off");
            clear voidCleanup
            clear cleanup
        end

