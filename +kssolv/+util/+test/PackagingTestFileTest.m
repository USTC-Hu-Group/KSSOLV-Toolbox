classdef PackagingTestFileTest < matlab.unittest.TestCase
    methods (Test)
        function retainsDocumentationImagesNamedLatest(testCase)
            paths = ["docs/desktop-start-latest.png", ...
                "docs/Latest.png", "docs/latest.m", "docs/guide.md"];
            testCase.verifyFalse(any(kssolv.util.isTestFileName(paths)));
        end

        function rejectsTestCodeAndFixtures(testCase)
            paths = ["ParallelHybridTest.m", "SolverTests.p", ...
                "test_solver.m", "solver_test.m", "solver_tests.m", ...
                "bridge.test.js", "test.json"];
            testCase.verifyTrue(all(kssolv.util.isTestFileName(paths)));
        end

        function toolboxManifestIncludesRelocatedBrowserResources(testCase)
            root = KSSOLV_Toolbox.RootDirectory;
            plan = buildfile;
            assets = string(plan("stage").Inputs.paths);
            for name = browserResources()
                resource = kssolv.ui.browser.resourcePath(name);
                testCase.verifyTrue(any(assets == string(resource)), name);
            end
            testCase.verifyFalse(any(startsWith(assets, ...
                fullfile(root, 'server') + string(filesep))));
            testCase.verifyFalse(any(startsWith(assets, ...
                fullfile(root, 'scripts') + string(filesep))));
            normalizedAssets = replace(assets, '\', '/');
            for locale = ["zh_CN", "en_US"]
                testCase.verifyTrue(any(assets == ...
                    kssolv.ui.features.documentation.manualPath(locale)));
            end
            testCase.verifyFalse(any(contains(normalizedAssets, '/docs/presentations/')));
            testCase.verifyFalse(any(contains(normalizedAssets, '/docs/manual-zh/')));
            testCase.verifyFalse(any(endsWith(normalizedAssets, ...
                ["/AGENTS.md", "/docs/manual-plan.zh-CN.md", ...
                "/docs/kssolv-mcp-skills-development-plan.zh-CN.md"])));
            sources = string(plan("pcode").Inputs.paths);
            testCase.verifyTrue(any(endsWith(sources, fullfile( ...
                '+ui', '+browser', 'BrowserSession.m'))));
            testCase.verifyTrue(any(endsWith(sources, fullfile( ...
                '+ui', '+util', 'BrowserSession.m'))));
            testCase.verifyTrue(any(endsWith(sources, fullfile( ...
                '+services', '+http', 'HTTPJSONRequest.m'))));
            testCase.verifyTrue(any(endsWith(sources, fullfile( ...
                '+util', 'HTTPJSONRequest.m'))));
            testCase.verifyTrue(any(endsWith(sources, fullfile( ...
                '+remote', '+diagnostics', 'RemoteLoginTest.m'))));
            testCase.verifyFalse(any(endsWith(sources, 'RemoteLoginTestTest.m')));
        end

        function standaloneManifestRetainsResourcesAndCompatibilityEntries(testCase)
            files = kssolv.util.StandaloneBuild.applicationRuntimeFiles( ...
                KSSOLV_Toolbox.RootDirectory);
            for name = browserResources()
                testCase.verifyTrue(any(files == string( ...
                    kssolv.ui.browser.resourcePath(name))), name);
            end
            for suffix = [ ...
                    "+ui/+browser/BrowserSession.m", ...
                    "+ui/+util/BrowserSession.m", ...
                    "+services/+http/HTTPJSONRequest.m", ...
                    "+util/HTTPJSONRequest.m", ...
                    "+services/+llm/+online/+internal/sendRequest.m", ...
                    "+services/+llm/+online/sendRequest.m", ...
                    "+services/+llm/+online/+internal/sendNativeRequest.m", ...
                    "+services/+llm/+online/sendNativeRequest.m", ...
                    "+services/+remote/+diagnostics/RemoteLoginTest.m", ...
                    "+services/+filemanager/+internal/migrateWorkflowResources.m"]
                testCase.verifyTrue(any(endsWith( ...
                    replace(files, '\', '/'), suffix)), suffix);
            end
            testCase.verifyFalse(any(contains(replace(files, '\', '/'), ...
                ["/+test/", "/tests/", "/server/", "/scripts/"])));
            testFiles = kssolv.util.isTestFileName(files) & ...
                ~endsWith(replace(files, '\', '/'), ...
                '/+remote/+diagnostics/RemoteLoginTest.m');
            testCase.verifyFalse(any(testFiles));
            testCase.verifyTrue(all(isfile(files)));
        end

        function standaloneManifestRejectsMissingBrowserResources(testCase)
            folder = testCase.applyFixture( ...
                matlab.unittest.fixtures.TemporaryFolderFixture).Folder;
            collect = @() kssolv.util.StandaloneBuild.applicationRuntimeFiles(folder);
            testCase.verifyError(collect, 'KSSOLV:Deployment:MissingBrowserResources');
            target = fullfile(folder, '+kssolv', '+ui', 'resources', 'browser');
            mkdir(target);
            for name = browserResources()
                copyfile(kssolv.ui.browser.resourcePath(name), fullfile(target, name));
            end
            delete(fullfile(target, 'sidebar.html'));
            testCase.verifyError(collect, 'KSSOLV:Deployment:MissingBrowserResources');
        end
    end
end

function names = browserResources()
names = ["online-actions.html", "online-files.html", ...
    "online-fill-figure.js", "online-html-bootstrap.js", ...
    "online-modal.html", "online-native-grid.js", ...
    "online-shortcuts.js", "sidebar.html"];
end
